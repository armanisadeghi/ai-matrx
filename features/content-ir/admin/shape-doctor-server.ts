async function fetchDbGather(): Promise<DbGather> {
  const supabase = await createClient();

  // Privilege-complete gather via the super-admin-gated SECURITY DEFINER RPC
  // (migrations/shape_doctor_gather_rpc.sql). Viewer-scoped RLS reads are WRONG
  // here: the coverage baselines (contract manifest + shapes-status snapshot)
  // are service-key-complete, so hidden tenant-org kinds would surface as fake
  // contract-gap reds and snapshot-only drift. The RPC returns one jsonb array
  // per dataset; a non-array payload throws loudly, never degrades silently.
  const gather = async <T>(dataset: string, what: string): Promise<T[]> => {
    const { data, error } = await supabase.rpc("shape_doctor_gather", {
      p_dataset: dataset,
    });
    if (error) {
      throw new Error(`shape doctor read ${what} failed: ${error.message}`);
    }
    if (!Array.isArray(data)) {
      throw new Error(
        `shape doctor read ${what} failed: shape_doctor_gather('${dataset}') returned a non-array payload`,
      );
    }
    return data as unknown as T[];
  };

  const [kindRows, exampleRows, componentRows, surfaceRows, edgeRows, skillRows, blockRows] =
    await Promise.all([
      gather<GatherKindRow>("kinds", "content_ir.kind_definition"),
      gather<GatherExampleRow>("examples", "content_ir.kind_example"),
      gather<GatherComponentRow>("components", "content_ir.kind_component"),
      gather<GatherSurfaceRow>("surfaces", "content_ir.kind_surface"),
      // The nesting graph — feeds the doctor's nested-only-child `n/a` classing.
      gather<GatherEdgeRow>("edges", "content_ir.kind_edge"),
      gather<GatherSkillRow>("render_block_skills", "skill.definition"),
      gather<GatherBlockRow>("content_blocks", "public.content_blocks"),
    ]);

  return {
    kinds: kindRows.map((r) => ({
      id: r.id,
      kind: r.kind,
      label: r.label,
      isActive: r.is_active,
      emittedJsonSchema: r.emitted_json_schema,
      sampleData: r.sample_data,
      updatedAt: r.updated_at,
      data: r.data,
      version: r.version,
      visibility: r.visibility,
      metadata: r.metadata,
    })),
    edges: edgeRows.map(
      (r): DoctorKindEdge => ({
        parentDefinitionId: r.parent_definition_id,
        childDefinitionId: r.child_definition_id,
        fieldName: r.field_name,
      }),
    ),
    examples: exampleRows.map((r) => ({
      id: r.id,
      kindDefinitionId: r.kind_definition_id,
      isCanonical: r.is_canonical,
      data: r.data,
      updatedAt: r.updated_at,
    })),
    components: componentRows.map((r) => ({
      id: r.id,
      kindDefinitionId: r.kind_definition_id,
      platform: r.platform,
      role: r.role,
      componentKey: r.component_key,
      source: r.source,
      isActive: r.is_active,
      isDefault: r.is_default,
    })),
    surfaces: surfaceRows.map((r) => ({
      id: r.id,
      kindDefinitionId: r.kind_definition_id,
      surfaceType: r.surface_type,
      token: r.token,
      parserStrategy: r.parser_strategy,
      streaming: r.streaming,
      isActive: r.is_active,
    })),
    renderBlockSkills: skillRows.map((r) => ({
      skillId: r.skill_id,
      label: r.label,
      body: r.body,
    })),
    contentBlocks: blockRows.map((r) => ({
      id: r.id,
      label: r.label,
      template: r.template,
    })),
  };
}

// ─── Live doctor run ────────────────────────────────────────────────────────

export interface LiveDoctorRun {
  report: ShapeDoctorReport;
  db: DbGather;
  excludedFromDrift: AssetColumn[];
  warnings: string[];
}

export async function runLiveShapeDoctor(): Promise<LiveDoctorRun> {
  const db = await fetchDbGather();
  const code = gatherCodeInputs();

  const report = runShapeDoctor({
    kinds: db.kinds.map((k) => ({
      id: k.id,
      kind: k.kind,
      label: k.label,
      isActive: k.isActive,
      emittedJsonSchema: k.emittedJsonSchema,
      sampleData: k.sampleData,
      updatedAt: k.updatedAt,
      metadata: k.metadata,
    })),
    examples: db.examples,
    components: db.components,
    surfaces: db.surfaces,
    edges: db.edges,
    renderBlockSkills: db.renderBlockSkills,
    contentBlocks: db.contentBlocks,
    detectorTokens: code.detectorTokens,
    hostSurfaceTokens: code.hostSurfaceTokens ?? undefined,
    codeRenderPaths: {
      compiledKinds: code.compiledKinds,
      artifactKinds: code.artifactKinds,
    },
    // Coverage-gate inputs — bundled committed snapshots (same source the CLI
    // reads from disk), so the board raises the same vocab-unclassified /
    // contract-gap reds without filesystem access at runtime.
    crosswalkNames: new Set(committedCrosswalk.rows.map((r) => r.name)),
    contractManifest: committedContractManifest.contracts.map((c) => ({
      kind: c.kind,
      family: c.family,
    })),
  });

  return {
    report,
    db,
    excludedFromDrift: code.excludedFromDrift,
    warnings: code.warnings,
  };
}

// ─── Board model (live vs committed snapshot) ───────────────────────────────

interface SnapshotRow {
  kind: string;
  is_active: boolean;
  assets: Record<string, string>;
}

// Board model types live in kind-detail-types.ts (pure, client-shareable —
// keeps this module's `server-only` poison pill out of client chunks).
export type {
  BoardRowPresence,
  KindBoardRow,
  KindStatusBoardModel,
} from "@/features/content-ir/admin/kind-detail-types";

function snapshotStatus(value: string | undefined): AssetStatus | null {
  return value === "ok" || value === "warn" || value === "missing" || value === "n/a"
    ? value
    : null;
}

export async function buildKindStatusBoard(): Promise<KindStatusBoardModel> {
  const { report, db, excludedFromDrift, warnings } = await runLiveShapeDoctor();

  // Catalog-column enrichment sources (all already gathered — no extra reads).
  const dbKindBySlug = new Map(db.kinds.map((k) => [k.kind, k]));
  const familyByKind = new Map(
    committedContractManifest.contracts.map((c) => [c.kind, c.family]),
  );
  const componentCounts = new Map<string, number>();
  for (const c of db.components) {
    componentCounts.set(
      c.kindDefinitionId,
      (componentCounts.get(c.kindDefinitionId) ?? 0) + 1,
    );
  }
  const surfaceCounts = new Map<string, number>();
  for (const s of db.surfaces) {
    surfaceCounts.set(
      s.kindDefinitionId,
      (surfaceCounts.get(s.kindDefinitionId) ?? 0) + 1,
    );
  }
  const exampleCounts = new Map<string, number>();
  const canonicalExampleIds = new Set<string>();
  for (const e of db.examples) {
    exampleCounts.set(
      e.kindDefinitionId,
      (exampleCounts.get(e.kindDefinitionId) ?? 0) + 1,
    );
    if (e.isCanonical) canonicalExampleIds.add(e.kindDefinitionId);
  }

  const snapshotRows = new Map<string, SnapshotRow>(
    (committedSnapshot.rows as SnapshotRow[]).map((r) => [r.kind, r]),
  );
  const excluded = new Set<AssetColumn>(excludedFromDrift);

  const redFindings = report.findings.filter((f) => f.severity === "red");
  const redCodesByKind = new Map<string, string[]>();
  for (const f of redFindings) {
    if (!f.kind) continue;
    const list = redCodesByKind.get(f.kind) ?? [];
    list.push(f.code);
    redCodesByKind.set(f.kind, list);
  }

  const rows: KindBoardRow[] = report.rows.map((row) => {
    const snapshot = snapshotRows.get(row.kind);
    snapshotRows.delete(row.kind);

    const driftedCells: AssetColumn[] = [];
    if (snapshot) {
      for (const col of ASSET_COLUMNS) {
        if (excluded.has(col)) continue;
        const committed = snapshotStatus(snapshot.assets[col]);
        if (committed !== null && committed !== row.assets[col].status) {
          driftedCells.push(col);
        }
      }
    }

    const dbKind = dbKindBySlug.get(row.kind);
    return {
      kind: row.kind,
      label: row.label,
      isActive: row.isActive,
      presence: snapshot ? "both" : "live-only",
      cells: row.assets,
      driftedCells,
      activeDrift: snapshot ? snapshot.is_active !== row.isActive : false,
      redCodes: redCodesByKind.get(row.kind) ?? [],
      version: dbKind?.version ?? null,
      visibility: dbKind?.visibility ?? null,
      family: familyByKind.get(row.kind) ?? null,
      componentCount: dbKind ? (componentCounts.get(dbKind.id) ?? 0) : 0,
      surfaceCount: dbKind ? (surfaceCounts.get(dbKind.id) ?? 0) : 0,
      exampleCount: dbKind ? (exampleCounts.get(dbKind.id) ?? 0) : 0,
      hasCanonicalExample: dbKind ? canonicalExampleIds.has(dbKind.id) : false,
    };
  });

  // Kinds the snapshot knows but the live DB no longer has — shown, never hidden.
  for (const leftover of snapshotRows.values()) {
    const cells = {} as Record<AssetColumn, AssetCell>;
    for (const col of ASSET_COLUMNS) {
      cells[col] = {
        status: snapshotStatus(leftover.assets[col]) ?? "missing",
        detail: "committed snapshot value — kind is GONE from the live DB",
      };
    }
    rows.push({
      kind: leftover.kind,
      label: leftover.kind,
      isActive: leftover.is_active,
      presence: "snapshot-only",
      cells,
      driftedCells: [],
      activeDrift: false,
      redCodes: [],
      version: null,
      visibility: null,
      family: familyByKind.get(leftover.kind) ?? null,
      componentCount: 0,
      surfaceCount: 0,
      exampleCount: 0,
      hasCanonicalExample: false,
    });
  }
  rows.sort((a, b) => a.kind.localeCompare(b.kind));

  const driftedRowCount = rows.filter(
    (r) => r.presence !== "both" || r.driftedCells.length > 0 || r.activeDrift,
  ).length;

  return {
    rows,
    redFindings,
    yellowFindingCount: report.findings.filter((f) => f.severity === "yellow").length,
    totals: report.totals,
    driftedRowCount,
    snapshotStamp: committedSnapshot.generated_for,
    excludedFromDrift,
    warnings,
    generatedAt: new Date().toISOString(),
  };
}

// ─── Per-kind detail (the [kind] page's server payload) ─────────────────────
// Shape lives in kind-detail-types.ts (shared with the client tabs).

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export async function gatherKindDetail(
  kindSlug: string,
): Promise<KindDetailData | null> {
  const { report, db, warnings } = await runLiveShapeDoctor();

  const kind = db.kinds.find((k) => k.kind === kindSlug);
  const doctorRow = report.rows.find((r) => r.kind === kindSlug);
  if (!kind || !doctorRow) return null;

  const knownKinds = new Set(db.kinds.map((k) => k.kind));
  const skills = attributeSkillsToKinds(db.renderBlockSkills, knownKinds).filter(
    (t) => t.kind === kindSlug,
  );

  const blockPattern = new RegExp(`"__kind"\\s*:\\s*"${escapeRegExp(kindSlug)}"`);
  const contentBlocks = db.contentBlocks
    .filter((b) => blockPattern.test(b.template))
    .map((b) => ({ id: b.id, label: b.label }));

  return {
    id: kind.id,
    kind: kind.kind,
    label: kind.label,
    isActive: kind.isActive,
    version: kind.version,
    visibility: kind.visibility,
    updatedAt: kind.updatedAt,
    fieldData: kind.data,
    emittedJsonSchema: kind.emittedJsonSchema,
    doctorRow,
    skills,
    contentBlocks,
    components: db.components
      .filter((c) => c.kindDefinitionId === kind.id)
      .map(({ kindDefinitionId: _ignored, ...rest }) => rest),
    surfaces: db.surfaces
      .filter((s) => s.kindDefinitionId === kind.id)
      .map(({ kindDefinitionId: _ignored, ...rest }) => rest),
    warnings,
  };
}
