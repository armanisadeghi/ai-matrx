import { buildNotesEditorContextData } from "./buildNotesEditorContextData";

const NOTE_ID = "22222222-2222-4222-8222-222222222222";

function build(overrides: Partial<Parameters<typeof buildNotesEditorContextData>[0]> = {}) {
  return buildNotesEditorContextData({
    noteId: NOTE_ID,
    content: "# Heading\nA persisted note body.",
    selectionStart: 0,
    selectionEnd: 0,
    editorMode: "plain",
    ...overrides,
  });
}

describe("notes agent context", () => {
  it("sends one canonical reference for a clean persisted note", () => {
    const scope = build();
    expect(scope.current_note).toEqual({
      __kind: "resource_ref",
      resource_type: "note",
      resource_id: NOTE_ID,
    });
    // The body on screen is always supplied on the universal key.
    expect(scope.content).toBe("# Heading\nA persisted note body.");
    expect(scope.active_text).toBeUndefined();
    expect(scope.shared_access).toEqual({ shared_with_me: false, permission_level: "admin", owner_email: null });
    expect(scope.context).toEqual(expect.objectContaining({ surface: "notes", note_id: NOTE_ID }));
    expect(scope.current_note_title).toBeUndefined();
  });

  it("carries an unsaved buffer inside the same reference", () => {
    const scope = build({ content: "unsaved body", isDirty: true });
    expect(scope.current_note).toEqual(
      expect.objectContaining({
        resource_id: NOTE_ID,
        overlay: { content: "unsaved body", is_dirty: true },
      }),
    );
    expect(scope.content).toBe("unsaved body");
  });

  it("uses the content escape hatch only for a new client-only note", () => {
    const scope = build({ noteId: "__phantom__", content: "new note", isAutogenerated: true });
    expect(scope.current_note).toBeUndefined();
    expect(scope.content).toBe("new note");
  });

  it("packs the open note and its workspace into one XML bundle", () => {
    const scope = build({
      content: "# Clinic intake checklist\n- Confirm insurance card",
      noteRecord: {
        label: "Clinic intake checklist",
        folder_name: "Draft",
        tags: ["clinic", "intake"],
        visibility: "organization",
        updated_at: "2026-09-27T04:10:00Z",
      },
      openTabs: [NOTE_ID, "33333333-3333-4333-8333-333333333333"],
      notesMap: {
        "33333333-3333-4333-8333-333333333333": {
          id: "33333333-3333-4333-8333-333333333333",
          label: "Front desk script",
          folder_name: "Draft",
        },
      },
      allFolders: ["Draft", "Study Notes"],
      scopeAssignments: [{ scope_id: "s1", scope_name: "Patient intake", scope_type: "Workflow" }],
    });
    const bundle = String(scope.note_bundle);
    expect(bundle.startsWith("<notes_workspace>")).toBe(true);
    expect(bundle).toContain(`<note id="${NOTE_ID}" title="Clinic intake checklist" folder="Draft" tags="clinic, intake"`);
    expect(bundle).toContain("<body># Clinic intake checklist\n- Confirm insurance card</body>");
    expect(bundle).toContain('<scope type="Workflow">Patient intake</scope>');
    expect(bundle).toContain('<open_tabs total="1"><tab id="33333333-3333-4333-8333-333333333333" folder="Draft">Front desk script</tab></open_tabs>');
    expect(bundle).toContain('<folders total="2">');
    expect(bundle).not.toContain("unsaved=");
  });

  it("clips a long body and says so", () => {
    const scope = build({ content: "x".repeat(9000) });
    expect(String(scope.note_bundle)).toContain('clipped="true" total_chars="9000"');
    expect(String(scope.note_bundle).length).toBeLessThan(7300);
  });

  it("sends no bundle when no note is open", () => {
    expect(build({ noteId: "" }).note_bundle).toBeUndefined();
  });
});
