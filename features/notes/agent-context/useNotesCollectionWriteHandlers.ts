"use client";

/**
 * The notes surface's COLLECTION write targets — the agent twins of the
 * page's own create / duplicate / edit / archive / tag controls:
 *
 *   create_notes  — the sidebar's "New Note" and the tab menu's "Duplicate"
 *                   (an item with `copy_of`)
 *   update_notes  — title / body / tags of any note by id (the open note's
 *                   own draft targets stay the way to edit what is on screen)
 *   delete_notes  — the "Delete" menu item: ARCHIVES (moves to Trash,
 *                   restorable), never a permanent delete
 *   note_scopes   — the "Context" picker: the open note's full scope set
 *
 * Every handler saves through the page's own path (createNewNote, copyNote,
 * updateNote with the record's version, deleteNote, setEntityScopes), checks
 * the whole value before the approval card, and reports what landed with ids.
 */

import { useAppDispatch, useAppStore } from "@/lib/redux/hooks";
import type { SurfaceWriteHandlers } from "@/features/surfaces/runtime/SurfaceRuntimeContext";
import {
  collectProblems,
  collectionWriteHandlers,
  readCollectionList,
  repeatsProblem,
  ListLevelProblem,
} from "@/features/surfaces/runtime/collection-write-targets";
import { refuseSurfaceWrite } from "@/features/surfaces/runtime/surface-writeback";
import {
  copyNote,
  createNewNote,
  deleteNote,
  fetchAllNoteScopes,
} from "@/features/notes/redux/thunks";
import { upsertNoteFromServer } from "@/features/notes/redux/slice";
import { updateNote } from "@/features/notes/service/notesService";
import { resolveNewNoteOrganization } from "@/features/notes/hooks/useNewNoteOrganization";
import type { FolderReference } from "@/features/notes/types";
import type { NoteRecord } from "@/features/notes/redux/notes.types";
import { scopesService } from "@/features/scopes/service/scopesService";
import { setEntityScopes } from "@/features/scopes/redux/thunks/setEntityScopes";
import { isScopesRpcErr } from "@/features/scopes/types";
import type { RootState } from "@/lib/redux/rootReducer";

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

function isObject(v: unknown): v is Record<string, unknown> {
  return v !== null && typeof v === "object" && !Array.isArray(v);
}

function optionalString(item: Record<string, unknown>, key: string): string | undefined {
  const v = item[key];
  if (v === undefined || v === null) return undefined;
  if (typeof v !== "string") throw new Error(`"${key}" must be a string.`);
  return v;
}

function optionalTags(item: Record<string, unknown>): string[] | undefined {
  const v = item.tags;
  if (v === undefined || v === null) return undefined;
  if (!Array.isArray(v) || !v.every((t) => typeof t === "string" && t.trim()))
    throw new Error('"tags" must be an array of non-empty strings (the full tag set).');
  return (v as string[]).map((t) => t.trim().replace(/^#/, ""));
}

function checkTitle(title: string): string {
  const t = title.trim();
  if (!t) throw new Error('"title" must not be empty.');
  if (/[\r\n]/.test(t)) throw new Error('"title" must be a single line.');
  return t;
}

type CreatePlan =
  | { kind: "new"; title: string; content: string; tags: string[]; folder: FolderReference | null }
  | { kind: "copy"; copyOf: string; name: string };

interface UpdatePlan {
  id: string;
  name: string;
  label?: string;
  content?: string;
  tags?: string[];
}

interface DeletePlan {
  id: string;
  name: string;
}

export interface NotesCollectionWriteOptions {
  instanceId: string;
  /** The folders the page offers (the folder picker's list). */
  folders: FolderReference[];
  /** The open note — its organization disambiguates same-name folders. */
  activeNoteId: string;
  activeOrganizationId: string | null;
  /** The open note is view-only for this person: no tag writes. */
  readOnly: boolean;
}

export function useNotesCollectionWriteHandlers(
  options: NotesCollectionWriteOptions,
): () => SurfaceWriteHandlers {
  const dispatch = useAppDispatch();
  const store = useAppStore();

  return () => {
    const { instanceId, folders, activeNoteId, activeOrganizationId, readOnly } = options;
    const notes = () => (store.getState() as RootState).notes.notes as Record<string, NoteRecord>;

    const noteFor = (target: string, id: unknown): NoteRecord => {
      if (typeof id !== "string" || !UUID.test(id))
        throw new Error(`${target}: "id" must be a note id from the page (a uuid).`);
      const rec = notes()[id];
      if (!rec || rec._isAutogenerated)
        throw new ListLevelProblem(`${target}: no saved note with id ${id} is on this page.`);
      return rec;
    };

    const folderFor = (name: string): FolderReference => {
      const matches = folders.filter((f) => f.name === name.trim());
      if (matches.length === 0)
        throw new Error(
          `folder "${name}" does not exist — use one of: ${Array.from(new Set(folders.map((f) => f.name))).join(" | ")}. Folders are created by the person, not by an agent.`,
        );
      if (matches.length === 1) return matches[0];
      const inOrg = matches.find((f) => f.organizationId === activeOrganizationId);
      if (inOrg) return inOrg;
      throw new Error(
        `folder "${name}" exists in ${matches.length} organizations; open a note in the one you mean first.`,
      );
    };

    const handlers = collectionWriteHandlers(
      {
        plural: "notes",
        singular: "note",
        create: {
          parse: (value: unknown): CreatePlan[] => {
            const list = readCollectionList("create_notes", "notes", value, 10);
            return collectProblems<CreatePlan>(
              "create_notes",
              list,
              (raw) => {
                if (!isObject(raw)) throw new Error("each item must be an object.");
                const copyOf = optionalString(raw, "copy_of");
                if (copyOf !== undefined) {
                  const rec = noteFor("create_notes", copyOf);
                  const extra = ["title", "content", "tags", "folder"].filter((k) => raw[k] !== undefined);
                  if (extra.length)
                    throw new Error(`a copy takes only "copy_of"; drop ${extra.join(", ")} (edit the copy afterwards with update_notes).`);
                  return { kind: "copy", copyOf, name: `${rec.label} (Copy)` };
                }
                const title = checkTitle(optionalString(raw, "title") ?? "");
                const folderName = optionalString(raw, "folder");
                return {
                  kind: "new",
                  title,
                  content: optionalString(raw, "content") ?? "",
                  tags: optionalTags(raw) ?? [],
                  folder: folderName ? folderFor(folderName) : null,
                };
              },
              {
                nameOf: (raw) => (isObject(raw) ? String(raw.title ?? raw.copy_of ?? "") : ""),
                listChecks: (items) => [
                  repeatsProblem(
                    "create_notes",
                    items.map((i) => (i.ok && i.value?.kind === "new" ? i.value.title : null)),
                    "title",
                  ),
                ],
              },
            );
          },
          run: async (plan: CreatePlan) => {
            if (plan.kind === "copy") {
              const note = await dispatch(copyNote({ noteId: plan.copyOf, instanceId })).unwrap();
              return { id: note.id, name: note.label };
            }
            const organizationId = plan.folder?.organizationId ?? (await resolveNewNoteOrganization(store));
            const note = await dispatch(
              createNewNote({
                label: plan.title,
                content: plan.content,
                tags: plan.tags,
                organization_id: organizationId,
                ...(plan.folder ? { folder_id: plan.folder.id, folder_name: plan.folder.name } : {}),
              }),
            ).unwrap();
            return { id: note.id, name: note.label };
          },
          nameOf: (plan: CreatePlan) => (plan.kind === "copy" ? plan.name : plan.title),
        },
        update: {
          parse: (value: unknown): UpdatePlan[] => {
            const list = readCollectionList("update_notes", "notes", value, 10);
            return collectProblems<UpdatePlan>(
              "update_notes",
              list,
              (raw) => {
                if (!isObject(raw)) throw new Error("each item must be an object with an id.");
                const rec = noteFor("update_notes", raw.id);
                if (rec._sharedWithMe && rec._sharedMeta?.permissionLevel === "viewer")
                  throw new Error(`"${rec.label}" is shared with this person view-only.`);
                if (rec._dirty)
                  throw new Error(`"${rec.label}" has unsaved typing in the editor; edit it with note_content / note_title / note_tags while it is open, or wait for it to save.`);
                const title = optionalString(raw, "title");
                const plan: UpdatePlan = {
                  id: rec.id,
                  name: rec.label,
                  ...(title !== undefined ? { label: checkTitle(title) } : {}),
                  ...(raw.content !== undefined ? { content: optionalString(raw, "content") ?? "" } : {}),
                  ...(raw.tags !== undefined ? { tags: optionalTags(raw) ?? [] } : {}),
                };
                if (plan.label === undefined && plan.content === undefined && plan.tags === undefined)
                  throw new Error('nothing to change — send "title", "content" (replaces the body) and/or "tags" (replaces the tag set).');
                return plan;
              },
              {
                nameOf: (raw) => (isObject(raw) ? String(raw.id ?? "") : ""),
                listChecks: (items) => [
                  repeatsProblem("update_notes", items.map((i) => (i.ok ? i.value?.id : null)), "note id"),
                ],
              },
            );
          },
          run: async (plan: UpdatePlan) => {
            const rec = notes()[plan.id];
            const note = await updateNote(
              plan.id,
              {
                ...(plan.label !== undefined ? { label: plan.label } : {}),
                ...(plan.content !== undefined ? { content: plan.content } : {}),
                ...(plan.tags !== undefined ? { tags: plan.tags } : {}),
              },
              rec?.version !== undefined && rec.version !== null ? { expectedVersion: rec.version } : undefined,
            );
            dispatch(upsertNoteFromServer({ note, fetchStatus: "full" }));
            return { id: note.id, name: note.label };
          },
          nameOf: (plan: UpdatePlan) => plan.name,
          changedOf: (plan: UpdatePlan) =>
            [plan.label !== undefined && "title", plan.content !== undefined && "content", plan.tags !== undefined && "tags"].filter(
              (x): x is string => Boolean(x),
            ),
        },
        delete: {
          parse: (value: unknown): DeletePlan[] => {
            const list = readCollectionList("delete_notes", "notes", value, 10);
            return collectProblems<DeletePlan>(
              "delete_notes",
              list,
              (raw) => {
                const id = isObject(raw) ? raw.id : raw;
                const rec = noteFor("delete_notes", id);
                if (rec._sharedWithMe && rec._sharedMeta?.permissionLevel !== "admin")
                  throw new Error(`"${rec.label}" belongs to someone else; only its owner can archive it.`);
                return { id: rec.id, name: rec.label };
              },
              {
                nameOf: (raw) => String(isObject(raw) ? (raw.id ?? "") : (raw ?? "")),
                listChecks: (items) => [
                  repeatsProblem("delete_notes", items.map((i) => (i.ok ? i.value?.id : null)), "note id"),
                ],
              },
            );
          },
          run: async (plan: DeletePlan) => {
            await dispatch(deleteNote(plan.id)).unwrap();
            return { id: plan.id, name: plan.name };
          },
          nameOf: (plan: DeletePlan) => plan.name,
        },
      },
      refuseSurfaceWrite,
    );

    if (readOnly || !activeNoteId || !activeOrganizationId) return handlers;

    const parseScopes = (value: unknown): string[] => {
      if (!Array.isArray(value) || !value.every((v) => typeof v === "string" && v.trim()))
        throw new Error(
          "note_scopes expects an array of scope names (the FULL set — it replaces the note's scopes); [] clears them.",
        );
      const names = (value as string[]).map((v) => v.trim());
      const repeat = repeatsProblem("note_scopes", names, "scope");
      if (repeat) throw new Error(repeat);
      return names;
    };

    // Names resolve against the database BEFORE the approval card, so an
    // unknown or ambiguous scope is refused without asking the person.
    const resolveScopes = async (value: unknown) => {
      const names = parseScopes(value);
      const found = await scopesService.findScopesByName(activeOrganizationId, names);
      if (isScopesRpcErr(found)) throw new Error(found.error.message);
      const byName = new Map<string, Array<{ id: string; name: string; type: string }>>();
      for (const s of found.data) {
        const k = s.name.toLowerCase();
        byName.set(k, [...(byName.get(k) ?? []), s]);
      }
      const missing = names.filter((n) => !byName.has(n.toLowerCase()));
      if (missing.length)
        throw new Error(
          `No scope named ${missing.map((m) => `"${m}"`).join(", ")} in this note's organization. Scopes are created by the person; use names that already exist. Nothing was changed.`,
        );
      const ambiguous = names.filter((n) => (byName.get(n.toLowerCase())?.length ?? 0) > 1);
      if (ambiguous.length)
        throw new Error(
          `More than one scope is named ${ambiguous.map((m) => `"${m}"`).join(", ")} (different scope types); ask the person which one. Nothing was changed.`,
        );
      return names.map((n) => byName.get(n.toLowerCase())![0]);
    };

    return {
      ...handlers,
      note_scopes: {
        validate: async (value) => {
          await resolveScopes(value);
        },
        apply: async (value) => {
          const picked = await resolveScopes(value);
          const res = await dispatch(
            setEntityScopes({
              entityType: "note",
              entityId: activeNoteId,
              scopeIds: picked.map((s) => s.id),
              organizationId: activeOrganizationId,
            }),
          );
          if (!res.ok) throw new Error(res.error ?? "The scopes could not be saved.");
          void dispatch(fetchAllNoteScopes());
          return {
            summary: picked.length
              ? `The note's scopes are now: ${picked.map((s) => `${s.type ? `${s.type}: ` : ""}${s.name}`).join(", ")}.`
              : "Cleared every scope from the note.",
            data: { scopes: picked },
          };
        },
      },
    };
  };
}
