import { PLACEMENT_TYPES } from "@/features/agent-shortcuts/constants";
import {
  createNotesScope,
  type NotesOpenTabSummaryEntry,
  type NotesScopeAssignmentEntry,
} from "@/features/surfaces/manifests/notes-editor.manifest";
import type { EditorMode } from "@/features/notes/components/NoteEditorCore";
import {
  countWords,
  findCurrentHeading,
} from "@/features/notes/utils/markdown-headings";

/** Placements for the notes editor (target wiring with surfaceName). */
export const NOTES_EDITOR_CONTEXT_MENU_PLACEMENTS = [
  PLACEMENT_TYPES.AI_ACTION,
  PLACEMENT_TYPES.CONTENT_BLOCK,
  PLACEMENT_TYPES.QUICK_ACTION,
] as const;

/** Shared menu props — target state for `/notes` (not legacy NoteContextMenu). */
export const NOTES_EDITOR_CONTEXT_MENU_PROPS = {
  sourceFeature: "notes" as const,
  surfaceName: "matrx-user/notes" as const,
  isEditable: true as const,
  enabledPlacements: [...NOTES_EDITOR_CONTEXT_MENU_PLACEMENTS],
};

const TEXT_NEIGHBOR_CHARS = 500;

/** Lightweight metadata of the ACTIVE note (already loaded by the page). */
export interface NotesEditorNoteRecord {
  label?: string | null;
  folder_name?: string | null;
  tags?: string[] | null;
  visibility?: string | null;
  updated_at?: string | null;
}

/** One entry of the caller's notes map (used for tab summaries + folder peers). */
export interface NotesEditorNotesMapEntry {
  id?: string;
  label?: string | null;
  folder_name?: string | null;
  updated_at?: string | null;
  is_deleted?: boolean;
}

/** Shared-with-me access metadata for the active note (absent for own notes). */
export interface NotesEditorSharedAccess {
  permission_level: "viewer" | "editor" | "admin";
  owner_email: string | null;
}

/** Find & replace state snapshot (only while the bar is open). */
export interface NotesEditorFindReplace {
  query: string;
  scope: "file" | "global";
  case_sensitive: boolean;
  use_regex: boolean;
  match_count: number;
}

export interface BuildNotesEditorContextDataArgs {
  noteId: string;
  content: string;
  selectionStart: number;
  selectionEnd: number;
  editorMode: EditorMode;
  noteRecord?: NotesEditorNoteRecord | null;
  isDirty?: boolean;
  isAutogenerated?: boolean;
  openTabs?: string[];
  splitNoteId?: string | null;
  allFolders?: string[];
  notesMap?: Record<string, NotesEditorNotesMapEntry>;
  sharedAccess?: NotesEditorSharedAccess | null;
  scopeAssignments?: NotesScopeAssignmentEntry[];
  historyOpen?: boolean;
  findReplace?: NotesEditorFindReplace | null;
}

/**
 * Canonical `contextData` for `matrx-user/notes`.
 * Pure extraction of `useNotesSurfaceScope` — demo + production share one shape.
 */
export function buildNotesEditorContextData(
  args: BuildNotesEditorContextDataArgs,
): Record<string, unknown> {
  const {
    noteId,
    content,
    selectionStart,
    selectionEnd,
    editorMode,
    noteRecord,
    isDirty = false,
    isAutogenerated = false,
    openTabs = [],
    splitNoteId = null,
    allFolders = [],
    notesMap = {},
    sharedAccess = null,
    scopeAssignments = [],
    historyOpen = false,
    findReplace = null,
  } = args;

  const text = content;
  const hasSelection = selectionEnd > selectionStart;
  const selectedText = hasSelection
    ? text.slice(selectionStart, selectionEnd)
    : "";

  const textBefore = text.slice(
    Math.max(0, selectionStart - TEXT_NEIGHBOR_CHARS),
    selectionStart,
  );
  const textAfter = text.slice(
    selectionEnd,
    Math.min(text.length, selectionEnd + TEXT_NEIGHBOR_CHARS),
  );

  const noteOpen = Boolean(noteId);
  const activeScopeKind: "selection" | "note" | "empty" = !noteOpen
    ? "empty"
    : hasSelection
      ? "selection"
      : "note";
  const { heading, sectionText } = findCurrentHeading(text, selectionStart);
  const isPersistedNote = noteOpen && !isAutogenerated;
  const currentNote = isPersistedNote
    ? {
        __kind: "resource_ref" as const,
        resource_type: "note" as const,
        resource_id: noteId,
        ...(isDirty
          ? {
              overlay: {
                content: text,
                is_dirty: true as const,
              },
            }
          : {}),
      }
    : undefined;

  const openNotesSummary: NotesOpenTabSummaryEntry[] = openTabs.map((id) => {
    const rec = notesMap[id];
    return {
      id,
      title: rec?.label ?? "",
      folder: rec?.folder_name ?? "",
      updated_at: rec?.updated_at ?? "",
    };
  });

  const currentFolder = noteRecord?.folder_name ?? "";
  const folderPeers = currentFolder
    ? Object.values(notesMap)
        .filter(
          (n): n is NotesEditorNotesMapEntry & { id: string } =>
            !n.is_deleted &&
            n.folder_name === currentFolder &&
            Boolean(n.id) &&
            n.id !== noteId,
        )
        .map((n) => n.id)
    : [];

  const wordCount = noteOpen ? countWords(text) : undefined;

  const noteSummary =
    noteOpen && noteRecord
      ? {
          id: noteId,
          title: noteRecord.label ?? "",
          folder: noteRecord.folder_name ?? "",
          tags: noteRecord.tags ?? [],
          visibility: noteRecord.visibility ?? "personal",
          word_count: wordCount ?? 0,
          updated_at: noteRecord.updated_at ?? "",
          is_dirty: isDirty,
        }
      : undefined;

  const scope = createNotesScope({
    active_scope_kind: activeScopeKind,
    open_note_ids: openTabs,
    open_notes_summary: openNotesSummary,
    all_folder_names: allFolders,
    note_scope_assignments: scopeAssignments,
    editor_mode: editorMode,
    is_split_pane_visible: splitNoteId != null,
    history_pane_open: historyOpen,

    selection: selectedText || undefined,
    text_before: textBefore || undefined,
    text_after: textAfter || undefined,
    // Persisted note content is resolved from current_note. Only a brand-new
    // client-only note needs the legacy content escape hatch.
    content: noteOpen && isAutogenerated ? text : undefined,
    active_text: selectedText || undefined,
    current_heading: heading ?? undefined,
    current_section_text: sectionText ?? undefined,
    cursor_offset: noteOpen ? selectionStart : undefined,

    current_note: currentNote,
    current_note_id: noteOpen ? noteId : undefined,
    current_note_title: noteRecord?.label || undefined,
    current_note_folder: noteRecord?.folder_name || undefined,
    current_note_tags: noteRecord?.tags ?? undefined,
    current_note_visibility: noteRecord?.visibility || undefined,
    current_note_word_count: wordCount,
    current_note_updated_at: noteRecord?.updated_at || undefined,
    current_note_is_dirty: noteOpen ? isDirty : undefined,
    current_note_summary: noteSummary,
    shared_access:
      noteOpen && sharedAccess
        ? {
            shared_with_me: true,
            permission_level: sharedAccess.permission_level,
            owner_email: sharedAccess.owner_email,
          }
        : undefined,

    current_folder_note_ids: folderPeers.length ? folderPeers : undefined,

    is_new_note: noteOpen ? isAutogenerated : undefined,
    split_note_id: splitNoteId ?? undefined,
    find_replace: findReplace ?? undefined,
  });

  return scope as Record<string, unknown>;
}
