// A NEW NOTE SAVES (2026-10-05 live walk: every new Scratch note showed
// "Save failed: null value in column "metadata" of relation "notes" violates
// not-null constraint", and a reload lost the draft).
//
// Root cause: the client-minted record carried `metadata: null`; the INSERT
// (`materializeNote`) wrote that explicit null into a NOT NULL column whose
// default is '{}'. These assert the INSERT the real factory produces, through
// the real service, against a database stand-in that enforces the column's rule.

const inserted: Record<string, unknown>[] = [];
jest.mock("@/utils/supabase/client", () => {
  const notNull = ["metadata", "custom_fields", "label"];
  const chain = {
    insert(row: Record<string, unknown>) {
      inserted.push(row);
      const bad = notNull.find((c) => c in row && row[c] === null);
      const result = bad
        ? { data: null, error: { message: `null value in column "${bad}" of relation "notes" violates not-null constraint` } }
        : { data: { ...row, metadata: row.metadata ?? {}, version: 1 }, error: null };
      return { select: () => ({ single: async () => result }) };
    },
  };
  return { supabase: { schema: () => ({ from: () => chain }) } };
});
jest.mock("@/utils/auth/getUserId", () => ({ requireUserId: () => "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa" }));
jest.mock("@/utils/supabase/claimsUser", () => ({
  getClaimsUser: async () => ({ data: { user: { id: "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa" } }, error: null }),
}));

jest.mock("../service/noteContextAssociations", () => ({
  hydrateNoteContextLinks: async (rows: unknown[]) => rows,
  syncNoteContextLinks: async () => undefined,
}));

import { materializeNote } from "../service/notesService";
import { createAutogeneratedNoteRecord, createBlankNoteRecordFromPartial } from "../redux/notes.types";
import type { Note } from "../types";

const USER = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
const ORG = "11111111-1111-4111-8111-111111111111";

describe("a new note's first save", () => {
  beforeEach(() => inserted.splice(0));

  test("the client-minted record mirrors the column default: metadata {}", () => {
    expect(createAutogeneratedNoteRecord("n1", USER, "Scratch", ORG).metadata).toEqual({});
    expect(createBlankNoteRecordFromPartial({ id: "n2", organization_id: ORG }, "list").metadata).toEqual({});
  });

  test("the INSERT never carries a null metadata, and the row is confirmed", async () => {
    const record = createAutogeneratedNoteRecord("6c1e9b2a-3f4d-4e5a-8b7c-2d1e0f9a8b72", USER, null, ORG);
    const draft = { ...record, content: "Call Harbor Dental about the x-rays" } as unknown as Note;
    const saved = await materializeNote(draft);
    expect(inserted[0]?.metadata).toEqual({});
    expect(saved.content).toBe("Call Harbor Dental about the x-rays");
  });

  test("even a record that still holds null (an older tab's state) writes the default", async () => {
    const record = { ...createAutogeneratedNoteRecord("6c1e9b2a-3f4d-4e5a-8b7c-2d1e0f9a8b73", USER, null, ORG), metadata: null };
    await materializeNote({ ...record, content: "x" } as unknown as Note);
    expect(inserted[0]?.metadata).toEqual({});
  });
});
