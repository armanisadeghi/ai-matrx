const schema = jest.fn();
const getSession = jest.fn();
const getUserId = jest.fn();
const listForSources = jest.fn();

jest.mock("@/utils/supabase/client", () => ({
  supabase: { schema, auth: { getSession } },
}));
jest.mock("@/utils/auth/getUserId", () => ({ requireUserId: getUserId }));
jest.mock("@/features/scopes/service/associationsService", () => ({
  associationsService: { listForSources },
}));
// The dialog is unrelated presentational chrome; the real picker and its
// initializer remain mounted for this control-to-store proof.
jest.mock("../components/CreateFolderDialog", () => ({
  CreateFolderDialog: () => null,
}));

import { configureStore } from "@reduxjs/toolkit";
import { enableMapSet } from "immer";
import { Provider } from "react-redux";
import { act } from "react";
import { createRoot } from "react-dom/client";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import notesReducer, { updateNoteContent } from "./slice";
import appContextReducer from "@/lib/redux/slices/appContextSlice";
import { initializeAutogeneratedNote, saveNote } from "./thunks";
import { autoSaveMiddleware } from "./autoSaveMiddleware";
import { FolderQuickPick } from "../components/FolderQuickPick";
import type { UserAuthState } from "@/lib/redux/slices/userAuthSlice";

enableMapSet();
(globalThis as typeof globalThis & { IS_REACT_ACT_ENVIRONMENT: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

const ORG_A = "11111111-1111-4111-8111-111111111111";
const ORG_B = "22222222-2222-4222-8222-222222222222";
const USER = "33333333-3333-4333-833333333333";
const FOLDER_B = "44444444-4444-4444-8444-444444444444";
const NOTE = "55555555-5555-4555-8555-555555555555";

function chain(result: unknown) {
  const value = {
    select: jest.fn(), eq: jest.fn(), is: jest.fn(), insert: jest.fn(), upsert: jest.fn(),
    single: jest.fn(), maybeSingle: jest.fn(), order: jest.fn(), update: jest.fn(),
  };
  for (const key of ["select", "eq", "is", "insert", "upsert", "update"] as const) value[key].mockReturnValue(value);
  value.single.mockResolvedValue(result);
  value.maybeSingle.mockResolvedValue(result);
  value.order.mockResolvedValue(result);
  return value;
}

function store(activeOrganizationId = ORG_A) {
  const userAuthReducer = (state: Pick<UserAuthState, "id"> = { id: USER }) => state;
  return configureStore({
    reducer: {
      notes: notesReducer,
      appContext: appContextReducer,
      userAuth: userAuthReducer,
    },
    preloadedState: {
      appContext: { organization_id: activeOrganizationId, organization_name: null, personal_organization_id: null, scope_selections: {}, active_scope_type_ids: [], project_id: null, project_name: null, task_id: null, task_name: null, conversation_id: null, orgBootstrapResolved: true },
    },
    middleware: (getDefault) => getDefault({ serializableCheck: false }).concat(autoSaveMiddleware),
  });
}

describe("autogenerated draft control admission and first save", () => {
  beforeEach(() => {
    jest.clearAllMocks();
    getUserId.mockReturnValue(USER);
    getSession.mockResolvedValue({ data: { session: { user: { id: USER } } }, error: null });
    listForSources.mockResolvedValue({ ok: true, data: { edges: [] } });
  });

  it("keeps the clicked org-B folder identity while org A is active, then inserts the same client id on first dirty save", async () => {
    const admitted = chain({ data: { id: FOLDER_B, name: "Research" }, error: null });
    const materializedFolder = chain({ data: { id: FOLDER_B, name: "Research" }, error: null });
    const inserted = chain({ data: { id: NOTE, created_by: USER, label: "New Note", content: "typed", folder_id: FOLDER_B, folder_name: "Research", organization_id: ORG_B, tags: [], metadata: {}, position: 0, visibility: "private", version: 1, updated_at: "2026-09-12T00:00:00.000Z" }, error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(admitted).mockReturnValueOnce(materializedFolder).mockReturnValueOnce(inserted) });
    const configured = store(ORG_A);

    await configured.dispatch(initializeAutogeneratedNote({
      id: NOTE, userId: USER, organizationId: ORG_B, instanceId: "control",
      destination: { kind: "existing", folder: { id: FOLDER_B, name: "same name", organizationId: ORG_B } },
    })).unwrap();

    expect(admitted.eq).toHaveBeenCalledWith("id", FOLDER_B);
    expect(admitted.eq).toHaveBeenCalledWith("organization_id", ORG_B);
    expect(configured.getState().notes.notes[NOTE]).toMatchObject({ id: NOTE, organization_id: ORG_B, folder_id: FOLDER_B, folder_name: "Research", _isAutogenerated: true });

    configured.dispatch(updateNoteContent({ id: NOTE, content: "typed" }));
    await configured.dispatch(saveNote(NOTE)).unwrap();

    expect(inserted.insert).toHaveBeenCalledWith(expect.objectContaining({ id: NOTE, organization_id: ORG_B, folder_id: FOLDER_B, folder_name: "Research", content: "typed" }));
    expect(configured.getState().notes.notes[NOTE]).toMatchObject({ id: NOTE, _isAutogenerated: false, _dirty: false });
  });

  it("stores explicit unfiled as null and never substitutes the active organization Draft folder", async () => {
    const inserted = chain({ data: { id: NOTE, created_by: USER, label: "New Note", content: "typed", folder_id: null, folder_name: null, organization_id: ORG_B, tags: [], metadata: {}, position: 0, visibility: "private", version: 1, updated_at: "2026-09-12T00:00:00.000Z" }, error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(inserted) });
    const configured = store(ORG_A);
    await configured.dispatch(initializeAutogeneratedNote({ id: NOTE, userId: USER, organizationId: ORG_B, instanceId: "control", destination: { kind: "unfiled", organizationId: ORG_B } })).unwrap();
    configured.dispatch(updateNoteContent({ id: NOTE, content: "typed" }));
    await configured.dispatch(saveNote(NOTE)).unwrap();
    expect(inserted.insert).toHaveBeenCalledWith(expect.objectContaining({ id: NOTE, organization_id: ORG_B, folder_id: null, folder_name: null }));
  });

  it("routes the real FolderQuickPick Draft click through admission before its first stable-id insert", async () => {
    const created = chain({ data: { id: FOLDER_B, deleted_at: null }, error: null });
    const admitted = chain({ data: { id: FOLDER_B, name: "Draft" }, error: null });
    const materializedFolder = chain({ data: { id: FOLDER_B, name: "Draft" }, error: null });
    const inserted = chain({ data: { id: NOTE, created_by: USER, label: "New Note", content: "typed", folder_id: FOLDER_B, folder_name: "Draft", organization_id: ORG_A, tags: [], metadata: {}, position: 0, visibility: "private", version: 1, updated_at: "2026-09-12T00:00:00.000Z" }, error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(created).mockReturnValueOnce(admitted).mockReturnValueOnce(materializedFolder).mockReturnValueOnce(inserted) });
    const configured = store();
    const host = document.createElement("div");
    const root = createRoot(host);
    await act(async () => { root.render(<Provider store={configured}><FolderQuickPick instanceId="control" /></Provider>); });
    const draftButton = [...host.querySelectorAll("button")].find((button) => button.title === "New note in Draft");
    expect(draftButton).toBeDefined();
    await act(async () => { draftButton?.dispatchEvent(new MouseEvent("click", { bubbles: true })); });
    const id = Object.keys(configured.getState().notes.notes)[0];
    expect(configured.getState().notes.notes[id]).toMatchObject({ id, organization_id: ORG_A, folder_id: FOLDER_B, folder_name: "Draft", _isAutogenerated: true });
    await act(async () => {
      configured.dispatch(updateNoteContent({ id, content: "typed" }));
      await configured.dispatch(saveNote(id)).unwrap();
    });
    expect(inserted.insert).toHaveBeenCalledWith(expect.objectContaining({ id, organization_id: ORG_A, folder_id: FOLDER_B, folder_name: "Draft" }));
    await act(async () => { root.unmount(); });
  });

  it("keeps every production draft producer on the typed initializer boundary", () => {
    for (const path of [
      "features/notes/components/FolderQuickPick.tsx",
      "features/notes/components/NoteTabBar.tsx",
      "features/notes/components/NoteSidebar.tsx",
      "features/window-panels/windows/notes/NotesWindow.tsx",
    ]) {
      const source = readFileSync(resolve(process.cwd(), path), "utf8");
      expect(source).toContain("initializeAutogeneratedNote");
      expect(source).toContain("destination:");
      expect(source).not.toMatch(/createAutogeneratedNote\s*\(/);
    }
  });
});
