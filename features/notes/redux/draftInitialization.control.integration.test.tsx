/**
 * A `workbench.notes` stub that answers by INTENT — table + filters +
 * operation — never by call ORDER.
 *
 * WHY, and never go back to a queue: the order-keyed
 * `mockReturnValueOnce` queue this replaced was a forcing-function defect. A
 * mounted editor reads `workbench.notes` on a timeline of its own — the share
 * surface's `useIsOwner` → `resolveResourceOwnership`
 * (`utils/permissions/service.ts`) fires one `select("created_by")` from an
 * effect — so under the full battery's workers it lands before, between, or
 * after the clicks the test drives. Every answer after it shifted by one, and
 * the suite read `remote N+2` where it expected `remote N+1` or the reverse:
 * RED while the system was right, and it would have gone GREEN had the code
 * read the wrong row, since the queue never looked at what was asked for.
 *
 * This models the ONE row the flow touches, CAS included: a filtered UPDATE
 * whose filters do not match the stored row returns `{ data: null }`, exactly
 * as PostgREST does, so a wrong expected version produces a real miss instead
 * of a rehearsed acknowledgement. `advance()` is the other device writing.
 */
function notesRowsByIntent(initial: Record<string, unknown>) {
  let row: Record<string, unknown> = { ...initial };
  const from = jest.fn((table: string) => {
    if (table !== "notes") {
      throw new Error(`This stub models workbench.notes only; \`${table}\` was read.`);
    }
    const filters: Array<[string, unknown]> = [];
    let writes: Record<string, unknown> | null = null;
    const matches = () =>
      filters.every(([column, value]) => (row[column] ?? null) === (value ?? null));
    const answer = async () => {
      if (!matches()) return { data: null, error: null };
      if (writes) row = { ...row, ...writes };
      return { data: { ...row }, error: null };
    };
    const builder = {
      select: () => builder,
      eq: (column: string, value: unknown) => { filters.push([column, value]); return builder; },
      is: (column: string, value: unknown) => { filters.push([column, value]); return builder; },
      update: (values: Record<string, unknown>) => { writes = { ...values }; return builder; },
      single: answer,
      maybeSingle: answer,
      // A list read is not modelled — say so rather than hand back one row
      // dressed as a result set.
      order: () => { throw new Error("This stub models single-row reads of workbench.notes only; a list read reached it."); },
    };
    return builder;
  });
  return {
    from,
    /** The stored row, as the database would hold it right now. */
    row: () => ({ ...row }),
    /** Another device wrote: move the stored row on. */
    advance: (patch: Record<string, unknown>) => { row = { ...row, ...patch }; },
  };
}

