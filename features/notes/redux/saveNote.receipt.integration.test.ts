const schema = jest.fn();
const getSession = jest.fn();
const listForSources = jest.fn();
const setTargets = jest.fn();
const invalidate = jest.fn();

jest.mock("@/utils/supabase/client", () => ({ supabase: { schema, auth: { getSession } } }));
jest.mock("@/utils/auth/getUserId", () => ({ requireUserId: () => "user-1" }));
jest.mock("@/features/scopes/service/associationsService", () => ({
  associationsService: { listForSources, setTargets },
}));
jest.mock("@/features/scopes/host/associationsStore", () => ({
  getAssociationsStore: () => ({ invalidate }),
}));

import { configureStore, type Middleware } from "@reduxjs/toolkit";
import { enableMapSet } from "immer";
import type { Note } from "../types";
import notesReducer, {
  createAutogeneratedNote,
  setNoteField,
  setNoteFields,
  updateNoteFolder,
  upsertNoteFromServer,
} from "./slice";
import { saveNote } from "./thunks";

enableMapSet();

const ORG = "11111111-1111-4111-8111-111111111111";
const NOTE_ID = "22222222-2222-4222-8222-222222222222";
const FOLDER_ID = "33333333-3333-4333-8333-333333333333";
const PROJECT_ID = "44444444-4444-4444-8444-444444444444";
const TASK_ID = "55555555-5555-4555-8555-555555555555";

function note(overrides: Partial<Note> = {}): Note {
  return {
    id: NOTE_ID, content: "before", content_hash: null,
    created_at: "2026-09-12T00:00:00.000Z", created_by: "user-1", deleted_at: null,
    file_path: null, folder_id: null, folder_name: null, label: "Original", last_device_id: null,
    metadata: {}, organization_id: ORG, position: 0, project_id: null, sync_version: 0,
    tags: [], task_id: null, updated_at: "2026-09-12T00:00:00.000Z", updated_by: null,
    version: 7, visibility: "personal", ...overrides,
  };
}

function query(result: unknown) {
  const chain = { select: jest.fn(), eq: jest.fn(), is: jest.fn(), maybeSingle: jest.fn(), single: jest.fn(), update: jest.fn(), insert: jest.fn() };
  chain.select.mockReturnValue(chain);
  chain.eq.mockReturnValue(chain);
  chain.is.mockReturnValue(chain);
  chain.update.mockReturnValue(chain);
  chain.insert.mockReturnValue(chain);
  chain.maybeSingle.mockResolvedValue(result);
  chain.single.mockResolvedValue(result);
  return chain;
}

type NotesTestState = { notes: ReturnType<typeof notesReducer>; userAuth: { id: string } };

function storeWithNote(options: { middleware?: Middleware<unknown, NotesTestState>; userId?: () => string } = {}) {
  const store = configureStore({
    reducer: { notes: notesReducer, userAuth: () => ({ id: options.userId?.() ?? "user-1" }) },
    middleware: (getDefaultMiddleware) => {
      const base = getDefaultMiddleware({ serializableCheck: false });
      return options.middleware ? base.concat(options.middleware) : base;
    },
  });
  store.dispatch(upsertNoteFromServer({ note: note(), fetchStatus: "full" }));
  return store;
}

describe("saveNote receipt integration", () => {
  beforeEach(() => {
    jest.clearAllMocks();
    getSession.mockResolvedValue({ data: { session: { user: { id: "user-1" } } }, error: null });
    listForSources.mockResolvedValue({ ok: true, data: { edges: [] } });
    setTargets.mockResolvedValue({ ok: true, data: null });
  });

  it("accepts a paired folder display name while persisting only its admitted ID", async () => {
    const existing = query({ data: note(), error: null });
    const folder = query({ data: { id: FOLDER_ID, name: "Archive" }, error: null });
    const updated = query({ data: note({ folder_id: FOLDER_ID, folder_name: "Authoritative Archive", version: 8 }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(folder).mockReturnValueOnce(updated) });
    const store = storeWithNote();
    store.dispatch(setNoteFields({ id: NOTE_ID, updates: { folder_id: FOLDER_ID, folder_name: "Archive" } }));

    const action = await store.dispatch(saveNote(NOTE_ID));

    expect(saveNote.fulfilled.match(action)).toBe(true);
    expect(updated.update).toHaveBeenCalledWith({ folder_id: FOLDER_ID, folder_name: "Archive", version: 8 });
    expect(store.getState().notes.notes[NOTE_ID].folder_name).toBe("Authoritative Archive");
    expect(store.getState().notes.notes[NOTE_ID]._dirtyFields.size).toBe(0);
  });

  it("refuses a name-only persisted folder mutation", async () => {
    const store = storeWithNote();
    store.dispatch(updateNoteFolder({ id: NOTE_ID, folder: "Archive" }));

    const action = await store.dispatch(saveNote(NOTE_ID));

    expect(saveNote.rejected.match(action)).toBe(true);
    expect(schema).not.toHaveBeenCalled();
  });

  it("does not advance a context-only readback over a physical edit typed while edges settle", async () => {
    const existing = query({ data: note({ version: 8, updated_at: "2026-09-12T01:00:00.000Z" }), error: null });
    const unchanged = query({ data: note({ version: 8, updated_at: "2026-09-12T01:00:00.000Z" }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(unchanged) });
    let release: ((value: { ok: true; data: null }) => void) | undefined;
    let started: (() => void) | undefined;
    const startedPromise = new Promise<void>((resolve) => { started = resolve; });
    setTargets.mockImplementation(() => new Promise((resolve) => { release = resolve; started?.(); }));
    const store = storeWithNote();
    store.dispatch(setNoteField({ id: NOTE_ID, field: "project_id", value: PROJECT_ID }));
    const pending = store.dispatch(saveNote(NOTE_ID));
    await startedPromise;
    store.dispatch(setNoteField({ id: NOTE_ID, field: "content", value: "later physical edit" }));
    release?.({ ok: true, data: null });
    await pending;

    const record = store.getState().notes.notes[NOTE_ID];
    expect(record).toMatchObject({ version: 7, updated_at: "2026-09-12T00:00:00.000Z", content: "later physical edit" });
    expect(record._dirtyFields).toEqual(new Set(["content"]));
  });

  it("keeps newer physical dirt through a partial context receipt", async () => {
    const existing = query({ data: note({ version: 8, updated_at: "2026-09-12T01:00:00.000Z" }), error: null });
    const unchanged = query({ data: note({ version: 8, updated_at: "2026-09-12T01:00:00.000Z" }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(unchanged) });
    let release: ((value: { ok: true; data: null }) => void) | undefined;
    let started: (() => void) | undefined;
    const startedPromise = new Promise<void>((resolve) => { started = resolve; });
    setTargets.mockImplementation(({ targetType }: { targetType: string }) => targetType === "project"
      ? new Promise((resolve) => { release = resolve; started?.(); })
      : Promise.resolve({ ok: false, error: { message: "task denied" } }));
    const store = storeWithNote();
    store.dispatch(setNoteFields({ id: NOTE_ID, updates: { project_id: PROJECT_ID, task_id: TASK_ID } }));
    const pending = store.dispatch(saveNote(NOTE_ID));
    await startedPromise;
    store.dispatch(setNoteField({ id: NOTE_ID, field: "content", value: "later physical edit" }));
    release?.({ ok: true, data: null });
    await pending;

    const record = store.getState().notes.notes[NOTE_ID];
    expect(record).toMatchObject({ version: 7, content: "later physical edit", project_id: PROJECT_ID, task_id: TASK_ID });
    expect(record._dirtyFields).toEqual(new Set(["content", "task_id"]));
    expect(record._saving).toBe(false);
  });

  it("does not regress a clean newer remote base after an unchanged receipt", async () => {
    const existing = query({ data: note({ version: 8, updated_at: "2026-09-12T01:00:00.000Z" }), error: null });
    const unchanged = query({ data: note({ version: 8, updated_at: "2026-09-12T01:00:00.000Z" }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(unchanged) });
    let release: ((value: { ok: true; data: null }) => void) | undefined;
    let started: (() => void) | undefined;
    const startedPromise = new Promise<void>((resolve) => { started = resolve; });
    setTargets.mockImplementation(() => new Promise((resolve) => { release = resolve; started?.(); }));
    const store = storeWithNote();
    store.dispatch(setNoteField({ id: NOTE_ID, field: "project_id", value: PROJECT_ID }));
    const pending = store.dispatch(saveNote(NOTE_ID));
    await startedPromise;
    store.dispatch(upsertNoteFromServer({ note: note({ version: 9, updated_at: "2026-09-12T02:00:00.000Z" }), fetchStatus: "full" }));
    release?.({ ok: true, data: null });
    await pending;

    expect(store.getState().notes.notes[NOTE_ID]).toMatchObject({ version: 9, updated_at: "2026-09-12T02:00:00.000Z" });
  });

  it("joins a subscriber reentry while the inner thunk is still dispatching pending", async () => {
    const existing = query({ data: note(), error: null });
    let release: ((value: { data: Note; error: null }) => void) | undefined;
    const updated = query(new Promise((resolve) => { release = resolve; }));
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(updated) });
    let subscriberSave: unknown;
    let reenterSave: (() => unknown) | undefined;
    const store = storeWithNote({
      middleware: () => (next) => (action) => {
        if (typeof action === "object" && action !== null && "type" in action && action.type === "notes/saveNote/pending") subscriberSave = reenterSave?.();
        return next(action);
      },
    });
    reenterSave = () => store.dispatch(saveNote(NOTE_ID));
    store.dispatch(setNoteField({ id: NOTE_ID, field: "content", value: "queued" }));

    const first = store.dispatch(saveNote(NOTE_ID));
    expect(subscriberSave).toBe(first);
    release?.({ data: note({ content: "queued", version: 8 }), error: null });
    await first;
    expect(updated.update).toHaveBeenCalledTimes(1);
  });

  it("drains an edit made by a fulfilled subscriber before releasing its queue entry", async () => {
    const firstExisting = query({ data: note(), error: null });
    const firstUpdate = query({ data: note({ content: "first", version: 8 }), error: null });
    const secondExisting = query({ data: note({ content: "first", version: 8 }), error: null });
    const secondUpdate = query({ data: note({ content: "second", version: 9 }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(firstExisting).mockReturnValueOnce(firstUpdate).mockReturnValueOnce(secondExisting).mockReturnValueOnce(secondUpdate) });
    let edited = false;
    let applySecondEdit: (() => unknown) | undefined;
    const store = storeWithNote({
      middleware: () => (next) => (action) => {
        const result = next(action);
        if (!edited && typeof action === "object" && action !== null && "type" in action && action.type === "notes/saveNote/fulfilled") {
          edited = true;
          applySecondEdit?.();
        }
        return result;
      },
    });
    applySecondEdit = () => store.dispatch(setNoteField({ id: NOTE_ID, field: "content", value: "second" }));
    store.dispatch(setNoteField({ id: NOTE_ID, field: "content", value: "first" }));
    await store.dispatch(saveNote(NOTE_ID));
    expect(firstUpdate.update.mock.calls.length + secondUpdate.update.mock.calls.length).toBe(2);
    expect(store.getState().notes.notes[NOTE_ID]._dirty).toBe(false);
  });

  it("keeps queues isolated for two configured stores holding the same note ID", async () => {
    const sharedQuery = query({ data: note({ version: 8 }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValue(sharedQuery) });
    const firstStore = storeWithNote();
    const secondStore = storeWithNote();
    firstStore.dispatch(setNoteField({ id: NOTE_ID, field: "content", value: "one" }));
    secondStore.dispatch(setNoteField({ id: NOTE_ID, field: "content", value: "two" }));
    const [first, second] = await Promise.all([firstStore.dispatch(saveNote(NOTE_ID)), secondStore.dispatch(saveNote(NOTE_ID))]);
    expect(saveNote.fulfilled.match(first)).toBe(true);
    expect(saveNote.fulfilled.match(second)).toBe(true);
    expect(sharedQuery.update).toHaveBeenCalledTimes(2);
  });

  it("refuses stale settlement after authentication changes before the response", async () => {
    const existing = query({ data: note(), error: null });
    let release: ((value: { data: Note; error: null }) => void) | undefined;
    const updated = query(new Promise((resolve) => { release = resolve; }));
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(updated) });
    const store = storeWithNote();
    store.dispatch(setNoteField({ id: NOTE_ID, field: "content", value: "local" }));
    const pending = store.dispatch(saveNote(NOTE_ID));
    getSession.mockResolvedValue({ data: { session: { user: { id: "user-2" } } }, error: null });
    release?.({ data: note({ content: "local", version: 8 }), error: null });
    const action = await pending;
    expect(saveNote.rejected.match(action)).toBe(true);
    expect(store.getState().notes.notes[NOTE_ID]._dirty).toBe(true);
  });

  it("retains an autogenerated draft after a lost insert acknowledgement and retries its stable ID", async () => {
    const lostAcknowledgement = query({ data: null, error: { message: "connection lost" } });
    const confirmed = query({ data: note({ id: "66666666-6666-4666-8666-666666666666", content: "draft" }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(lostAcknowledgement).mockReturnValueOnce(confirmed) });
    const store = storeWithNote();
    const generatedId = "66666666-6666-4666-8666-666666666666";
    store.dispatch(createAutogeneratedNote({ id: generatedId, userId: "user-1", folder: "Draft", organizationId: ORG, instanceId: "main" }));
    store.dispatch(setNoteField({ id: generatedId, field: "content", value: "draft" }));
    const first = await store.dispatch(saveNote(generatedId));
    expect(saveNote.rejected.match(first)).toBe(true);
    expect(store.getState().notes.notes[generatedId]._isAutogenerated).toBe(true);
    expect(store.getState().notes.notes[generatedId]._dirty).toBe(true);
    const second = await store.dispatch(saveNote(generatedId));
    expect(saveNote.fulfilled.match(second)).toBe(true);
    expect(lostAcknowledgement.insert).toHaveBeenCalledWith(expect.objectContaining({ id: generatedId }));
    expect(confirmed.insert).toHaveBeenCalledWith(expect.objectContaining({ id: generatedId }));
    expect(confirmed.update).not.toHaveBeenCalled();
  });

  it("does not automatically retry an insert whose acknowledgement was lost", async () => {
    const lostAcknowledgement = query({ data: null, error: { message: "network response lost after commit" } });
    schema.mockReturnValue({ from: jest.fn().mockReturnValue(lostAcknowledgement) });
    const store = storeWithNote();
    const generatedId = "77777777-7777-4777-8777-777777777777";
    store.dispatch(createAutogeneratedNote({ id: generatedId, userId: "user-1", folder: "Draft", organizationId: ORG, instanceId: "main" }));
    store.dispatch(setNoteField({ id: generatedId, field: "content", value: "draft" }));
    const action = await store.dispatch(saveNote(generatedId));
    expect(saveNote.rejected.match(action)).toBe(true);
    expect(lostAcknowledgement.insert).toHaveBeenCalledTimes(1);
    expect(lostAcknowledgement.insert).toHaveBeenCalledWith(expect.objectContaining({ id: generatedId }));
    expect(lostAcknowledgement.update).not.toHaveBeenCalled();
    expect(store.getState().notes.notes[generatedId]).toMatchObject({ id: generatedId, _isAutogenerated: true, _dirty: true });
    expect(action.error.message).toContain("Keep the draft open and retry");
  });
});
