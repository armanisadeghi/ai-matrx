type NotesTestState = { notes: ReturnType<typeof notesReducer>; userAuth: { id: string } };

function storeWithNote(options: {
  middleware?: Middleware<unknown, NotesTestState>;
  autoSave?: boolean;
  userAuthReducer?: (state: { id: string } | undefined, action: UnknownAction) => { id: string };
  userId?: () => string;
} = {}) {
  const store = configureStore({
    reducer: { notes: notesReducer, userAuth: options.userAuthReducer ?? (() => ({ id: options.userId?.() ?? "user-1" })) },
    middleware: (getDefaultMiddleware) => {
      const base = getDefaultMiddleware({ serializableCheck: false });
      if (options.autoSave) {
        return options.middleware
          ? base.concat(autoSaveMiddleware, options.middleware)
          : base.concat(autoSaveMiddleware);
      }
      return options.middleware ? base.concat(options.middleware) : base;
    },
  });
  store.dispatch(upsertNoteFromServer({ note: note(), fetchStatus: "full" }));
  return store;
}

