function getUserId(getState: () => unknown): string {
  const state = getState() as RootState;
  const userId = state.userAuth.id;
  if (!userId) throw new SessionUnavailableError();
  return userId;
}

type WritablePhysicalKey = "content" | "label" | "folder_id" | "tags" | "visibility";
type ContextKey = "project_id" | "task_id";
type ReviewedFieldKey = WritablePhysicalKey | ContextKey | "folder_name";
export type NoteReviewedSavePermit = object;
export type NoteReviewedCapture =
  | { status: "captured"; permit: NoteReviewedSavePermit }
  | { status: "refused"; reason: "invalid-permit" | "source-changed" | "session-changed" | "not-persisted" | "unsupported-fields" };

interface ReviewedPermitState {
  getState: () => unknown;
  source: NoteEditableContentSource;
  actorId: string;
  noteId: string;
  organizationId: string;
  version: number;
  fields: readonly ReviewedFieldKey[];
  sent: NoteReviewedSentFields;
  attempt?: SaveAttempt;
  result?: NoteReviewedSaveResult;
}

const reviewedSavePermits = new WeakMap<object, ReviewedPermitState>();
const writablePhysicalKeys: readonly WritablePhysicalKey[] = ["content", "label", "folder_id", "tags", "visibility"];
const contextKeys: readonly ContextKey[] = ["project_id", "task_id"];

function reviewedFields(source: NoteEditableContentSource): readonly ReviewedFieldKey[] | null {
  const acknowledged = source.acknowledgedPhysicalSnapshot;
  const displayed = source.displayedPhysicalSnapshot;
  if (!equalNoteSnapshotValue(acknowledged.metadata, displayed.metadata) || acknowledged.position !== displayed.position || acknowledged.organization_id !== displayed.organization_id) return null;
  const fields: ReviewedFieldKey[] = [];
  for (const key of writablePhysicalKeys) if (!equalNoteSnapshotValue(acknowledged[key], displayed[key])) fields.push(key);
  for (const key of contextKeys) if (!equalNoteSnapshotValue(acknowledged[key], displayed[key])) fields.push(key);
  if ((acknowledged.folder_name || "Draft") !== (displayed.folder_name || "Draft")) {
    if (!fields.includes("folder_id")) return null;
    fields.push("folder_name");
  }
  return fields;
}

/** Captures one synchronous, store-owned reviewed save admission. */
export const captureReviewedNoteSave = (source: NoteEditableContentSource) => (
  _dispatch: ThunkDispatch<RootState, unknown, UnknownAction>,
  getState: () => RootState,
): NoteReviewedCapture => {
  try { canonicalNoteSnapshotValue(source); }
  catch { return { status: "refused", reason: "invalid-permit" }; }
  if (!isPreparedEditableNoteSource(source)) return { status: "refused", reason: "invalid-permit" };
  let actorId: string;
  try { actorId = getUserId(getState); } catch { return { status: "refused", reason: "session-changed" }; }
  if (actorId !== source.editBase.actorId) return { status: "refused", reason: "session-changed" };
  const record = getState().notes.notes[source.noteId] as NoteRecord | undefined;
  if (!record || record._isAutogenerated) return { status: "refused", reason: "not-persisted" };
  if (record.organization_id !== source.editBase.organizationId || !record._acknowledgedPhysicalSnapshot) return { status: "refused", reason: "source-changed" };
  let current: NoteEditableContentSource;
  try { current = captureNoteEditSourceFromRecord({ record, displayedNote: record, actorId, sourceId: source.sourceId, snapshotId: source.snapshotId, ...(source.actingSelection === undefined ? {} : { actingSelection: source.actingSelection }) }); }
  catch { return { status: "refused", reason: "source-changed" }; }
  if (!equalNoteSnapshotValue(current, source)) return { status: "refused", reason: "source-changed" };
  const fields = reviewedFields(source);
  if (fields === null) return { status: "refused", reason: "unsupported-fields" };
  if (!equalNoteSnapshotValue([...record._dirtyFields].sort(), [...fields].sort()) || record._dirty !== (fields.length > 0)) return { status: "refused", reason: "source-changed" };
  const permit: NoteReviewedSavePermit = Object.freeze({});
  reviewedSavePermits.set(permit, { getState, source: immutableCopy(source), actorId, noteId: source.noteId, organizationId: source.editBase.organizationId, version: source.editBase.version, fields: Object.freeze([...fields]), sent: sentFields(record) });
  return { status: "captured", permit };
};

async function assertCurrentNotesUser(expectedUserId: string): Promise<void> {
  const { data, error } = await supabase.auth.getSession();
  if (error || data.session?.user.id !== expectedUserId) {
    throw new SessionUnavailableError();
  }
}

