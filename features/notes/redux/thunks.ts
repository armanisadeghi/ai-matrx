/**
 * Force-refetch the full note from the server, bypassing the cache guard in
 * fetchNoteContent. Used by the explicit "Refresh" action so users can pull
 * the latest server state for currently-open tabs (e.g. after a sibling
 * device edited the note).
 *
 * Skips notes that have unsaved local changes to avoid clobbering the user's
 * work — the user must save or discard before the server copy overwrites them.
 */
export const refreshNoteContent = createAsyncThunk<Note | null, string>(
  "notes/refreshNoteContent",
  async (noteId, { dispatch, getState }) => {
    const state = getState() as RootState;
    const existing = state.notes?.notes?.[noteId] as NoteRecord | undefined;

    // Guard: never overwrite dirty local state with a forced refresh.
    if (existing?._dirty) {
      return null;
    }

    const { data, error } = await supabase
      .schema("workbench")
      .from("notes")
      .select("*")
      .eq("id", noteId)
      .maybeSingle();

    if (error) throw error;
    if (!data) {
      throw recordUnavailable({
        entity: "note",
        reason: "unknown",
        recordId: noteId,
        token: "note",
        relation: "workbench.notes",
      });
    }

    const [note] = await hydrateNoteContextLinks([data]);
    dispatch(
      upsertNoteFromServer({
        note,
        fetchStatus: "full",
      }),
    );

    return note;
  },
);

/**
 * Conflict refresh is deliberately separate from the normal content cache.
 * It reads the captured record organization under the initiating actor, then
 * rechecks the session after transport before the editor may review the row.
 */
export const refreshNoteConflict = createAsyncThunk<Note, { noteId: string; organizationId: string; actorId: string }>(
  "notes/refreshNoteConflict",
  async ({ noteId, organizationId, actorId }, { getState }) => {
    const current = (getState() as RootState).notes.notes[noteId] as NoteRecord | undefined;
    if (!current || current.organization_id !== organizationId) {
      throw recordUnavailable({ entity: "note", reason: "unknown", recordId: noteId, token: "note", relation: "workbench.notes" });
    }
    requireOrganizationContext(organizationId);
    await assertCurrentNotesUser(actorId);
    if (getUserId(getState) !== actorId) throw new SessionUnavailableError();
    const { data, error } = await supabase
      .schema("workbench")
      .from("notes")
      .select("*")
      .eq("id", noteId)
      .eq("organization_id", organizationId)
      .is("deleted_at", null)
      .maybeSingle();
    if (error) throw error;
    if (!data) {
      throw recordUnavailable({ entity: "note", reason: "unknown", recordId: noteId, token: "note", relation: "workbench.notes" });
    }
    await assertCurrentNotesUser(actorId);
    if (getUserId(getState) !== actorId) throw new SessionUnavailableError();
    const [note] = await hydrateNoteContextLinks([data]);
    // Hydration can await association reads. Do not admit its result into a
    // reviewed comparison after its original session/principal has changed.
    await assertCurrentNotesUser(actorId);
    if (getUserId(getState) !== actorId) throw new SessionUnavailableError();
    return note;
  },
);

type ConflictChoice = "mine" | "theirs";
export type ConflictResolutionOutcome =
  | { status: "applied"; content: string }
  | { status: "refused"; reason: string };

const conflictId = () => `${Date.now()}-${Math.random().toString(36).slice(2)}`;

/**
 * The only resolution entry point. It validates the retained CAS principal
 * after the auth await, then reads the reducer's request-scoped receipt before
 * returning. UI code must not infer success from dispatch(action).
 */
export const resolveNoteConflict = (args: {
  noteId: string;
  decisionId: string;
  reviewId: string;
  choice: ConflictChoice;
  proposedContent: string;
  getLiveBuffer: () => string | null;
}) => async (dispatch: ThunkDispatch<RootState, unknown, UnknownAction>, getState: () => RootState): Promise<ConflictResolutionOutcome> => {
  const first = getState().notes.notes[args.noteId] as NoteRecord | undefined;
  const decision = first?._conflictDecision;
  if (!first || !decision || decision.decisionId !== args.decisionId || decision.reviewId !== args.reviewId) {
    return { status: "refused", reason: "This comparison changed. Refresh before applying a choice." };
  }
  try {
    await assertCurrentNotesUser(decision.actorId);
  } catch {
    return { status: "refused", reason: "Your session changed. Refresh the note before applying a choice." };
  }
  const current = getState().notes.notes[args.noteId] as NoteRecord | undefined;
  const currentDecision = current?._conflictDecision;
  const liveBuffer = args.getLiveBuffer();
  if (!current || !currentDecision || currentDecision.decisionId !== args.decisionId || currentDecision.reviewId !== args.reviewId || current.organization_id !== currentDecision.organizationId || getUserId(getState) !== currentDecision.actorId) {
    return { status: "refused", reason: "This comparison changed. Refresh before applying a choice." };
  }
  if (liveBuffer === null) return { status: "refused", reason: "The editor is no longer mounted. Reopen the note before applying a choice." };
  const requestId = conflictId();
  dispatch(applyNoteConflictResolution({
    id: args.noteId,
    decisionId: args.decisionId,
    reviewId: args.reviewId,
    requestId,
    choice: args.choice,
    proposedContent: args.proposedContent,
    reviewedLiveContent: liveBuffer,
  }));
  const receipt = getState().notes.conflictResolutionReceipts[requestId];
  dispatch(clearNoteConflictResolutionReceipt(requestId));
  if (!receipt || receipt.status === "refused") {
    return { status: "refused", reason: receipt?.reason ?? "The conflict could not be applied. Refresh before trying again." };
  }
  return { status: "applied", content: receipt.content };
};

/** Refresh is bound to the stored decision principal, never current UI state. */
export const refreshNoteConflictReview = (args: { noteId: string; decisionId: string; reviewId: string; getLiveBuffer: () => string | null }) => async (dispatch: ThunkDispatch<RootState, unknown, UnknownAction>, getState: () => RootState): Promise<ConflictResolutionOutcome> => {
  const before = getState().notes.notes[args.noteId] as NoteRecord | undefined;
  const decision = before?._conflictDecision;
  if (!before || !decision || decision.decisionId !== args.decisionId || decision.reviewId !== args.reviewId) return { status: "refused", reason: "This comparison changed. Refresh the note again." };
  const live = args.getLiveBuffer();
  if (live === null) return { status: "refused", reason: "The editor is no longer mounted. Reopen the note before refreshing." };
  dispatch(captureNoteConflictLiveBuffer({ id: args.noteId, content: live }));
  try {
    const remote = await dispatch(refreshNoteConflict({ noteId: args.noteId, organizationId: decision.organizationId, actorId: decision.actorId })).unwrap();
    const after = getState().notes.notes[args.noteId] as NoteRecord | undefined;
    const afterDecision = after?._conflictDecision;
    if (!after || !afterDecision || afterDecision.decisionId !== args.decisionId || afterDecision.reviewId !== args.reviewId || after.organization_id !== decision.organizationId || getUserId(getState) !== decision.actorId) return { status: "refused", reason: "This comparison changed. Refresh the note again." };
    const currentLive = args.getLiveBuffer();
    if (currentLive === null) return { status: "refused", reason: "The editor is no longer mounted. Reopen the note before refreshing." };
    const requestId = conflictId();
    dispatch(refreshNoteConflictComparison({ id: args.noteId, decisionId: args.decisionId, reviewId: args.reviewId, currentRow: remote, nextReviewId: conflictId(), requestId, liveContent: currentLive }));
    const receipt = getState().notes.conflictResolutionReceipts[requestId];
    dispatch(clearNoteConflictResolutionReceipt(requestId));
    if (!receipt || receipt.status === "refused") return { status: "refused", reason: receipt?.reason ?? "The refresh could not be applied. Refresh again." };
    return { status: "applied", content: receipt.content };
  } catch (error) {
    return { status: "refused", reason: error instanceof Error ? error.message : "Could not refresh the saved note." };
  }
};

