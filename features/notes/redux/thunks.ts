/**
 * Save dirty fields with atomic concurrency check.
 * - Reads note from state, checks _dirty and _dirtyFields
 * - Delegates revision CAS and association settlement to the Notes service
 * - markNoteSaved gets a savedSnapshot so mid-save keystrokes stay dirty
 * - Label change: dispatch custom event "notes:labelChange"
 */
/**
 * Record the failure, toast once per burst, and — once the streak reaches
 * NOTE_SAVE_FAILURE_BLOCK_THRESHOLD — snapshot the buffer to a local draft and
 * scream. The blocking banner reads the streak from Redux.
 */
function failNoteSave(
  dispatch: (action: ReturnType<typeof markNoteSaveError>) => unknown,
  getState: () => unknown,
  noteId: string,
  message: string,
): void {
  dispatch(markNoteSaveError({ id: noteId, error: message }));
  toastNoteWriteBlocked(noteId, message);
  const record = (getState() as RootState).notes?.notes?.[noteId];
  reportNoteSaveFailure({
    noteId,
    failureCount: record?._consecutiveSaveFailures ?? 1,
    message,
    label: record?.label ?? null,
  });
}

function hasDirtyPhysicalField(record: NoteRecord): boolean {
  return Array.from(record._dirtyFields).some(
    (field) => field !== "project_id" && field !== "task_id",
  );
}

function receiptBaseSettlement(
  getState: () => unknown,
  noteId: string,
  receipt: { databaseWrite: "saved" | "unchanged"; note: Pick<Note, "updated_at" | "version"> },
): Pick<Note, "updated_at" | "version"> {
  if (receipt.databaseWrite === "saved") {
    return receipt.note;
  }
  const currentRecord = (getState() as RootState).notes.notes[noteId] as NoteRecord | undefined;
  // A context-only write does not create a new physical revision. If the user
  // typed a physical field while its edges were settling, retain the base that
  // edit was built on rather than adopting the service's earlier readback.
  return currentRecord && (hasDirtyPhysicalField(currentRecord) || currentRecord.version > receipt.note.version)
    ? { updated_at: currentRecord.updated_at, version: currentRecord.version }
    : receipt.note;
}

const saveNotePayload = createAsyncThunk<NoteSaveReceipt | undefined, { noteId: string; expectedQueueUserId: string; operationId: string }>(
  "notes/saveNote",
  async ({ noteId, expectedQueueUserId, operationId }, { dispatch, getState }) => {
    const attempt = saveQueues.get(getState)?.get(noteId)?.attempt;
    if (!attempt || attempt.operationId !== operationId) throw new Error("The Notes save attempt is no longer registered.");
    try {
    const record = attempt.record;
    const expectedUserId = getUserId(getState);
    const expectedOrganizationId = record?.organization_id;
    if (expectedUserId !== expectedQueueUserId) throw new SessionUnavailableError();
    await assertCurrentNotesUser(expectedQueueUserId);
    if (getUserId(getState) !== expectedQueueUserId) throw new SessionUnavailableError();

    if (!record || !record._dirty || record._dirtyFields.size === 0) {
      return;
    }

    if (record._isAutogenerated) {
      const expectedUserId = getUserId(getState);
      const savedSnapshot: Partial<Record<NoteUndoableField, Note[NoteUndoableField]>> = {};
      for (const field of record._dirtyFields) savedSnapshot[field] = record[field];
      dispatch(recordNoteWriteAttempt({ id: noteId, values: savedSnapshot }));
      dispatch(markNoteSaving(noteId));
      try {
        const note = await materializePersistedNote(record);
        await assertCurrentNotesUser(expectedUserId);
        if (getUserId(getState) !== expectedUserId) throw new SessionUnavailableError();
        dispatch(materializeNote(noteId));
        dispatch(upsertNoteFromServer({ note, fetchStatus: "full" }));
        dispatch(markNoteSaved({
          id: noteId,
          updatedAt: note.updated_at ?? undefined,
          version: note.version,
          savedSnapshot,
        }));
      } catch (error) {
        if (error instanceof SessionUnavailableError) throw error;
        const friendly = error instanceof Error ? error.message : "Could not save this new note.";
        failNoteSave(dispatch, getState, noteId, friendly);
        throw error;
      } finally {
        // An acknowledgement can arrive after auth changed. Never use receipt
        // settlement to clear that state: only clear this payload's busy flag.
        dispatch(clearSavingNoteId(noteId));
      }
      return;
    }

    // Build update object from only dirty fields (snapshot for mid-save safety)
    const updates: UpdateNoteInput = {};
    let projectId: string | null | undefined;
    let taskId: string | null | undefined;
    const savedSnapshot: Partial<
      Record<NoteUndoableField, Note[NoteUndoableField]>
    > = {};
    const dirtyFields = Array.from(record._dirtyFields);
    const hasPairedFolderId = dirtyFields.includes("folder_id");
    const hasLabelChange = dirtyFields.includes("label");

    for (const field of dirtyFields) {
      if (field === "project_id") {
        projectId = record.project_id;
      } else if (field === "task_id") {
        taskId = record.task_id;
      } else if (field === "content") {
        updates.content = record.content;
      } else if (field === "label") {
        updates.label = record.label;
      } else if (field === "folder_id") {
        updates.folder_id = record.folder_id;
      } else if (field === "tags") {
        updates.tags = record.tags;
      } else if (field === "visibility") {
        updates.visibility = record.visibility;
      } else if (field === "folder_name") {
        if (hasPairedFolderId) {
          // folder_name is display projection. The admitted folder ID is the
          // only persisted move input, but both local dirty values settle.
        } else {
          const error = new Error("A persisted note can only move through an admitted folder ID and cannot change organization.");
          failNoteSave(dispatch, getState, noteId, error.message);
          throw error;
        }
      } else if (field === "organization_id") {
        const error = new Error("A persisted note can only move through an admitted folder ID and cannot change organization.");
        failNoteSave(dispatch, getState, noteId, error.message);
        throw error;
      }
      savedSnapshot[field] = record[field];
    }

    // Proceed with save. Record what we are about to send BEFORE sending it —
    // the realtime echo of this write can arrive before the REST response does,
    // and the conflict check must be able to recognize our own values.
    dispatch(recordNoteWriteAttempt({ id: noteId, values: savedSnapshot }));
    dispatch(markNoteSaving(noteId));

    let acknowledgedReceipt: NoteSaveReceipt | undefined;
    try {
      const receipt = await persistNoteUpdate(noteId, {
        ...updates,
        ...(projectId === undefined ? {} : { project_id: projectId }),
        ...(taskId === undefined ? {} : { task_id: taskId }),
      }, {
        expectedVersion: record.version,
        expectedOrganizationId: record.organization_id,
      });
      retainAttemptReceipt(attempt, receipt);
      if (receipt.failedFields.length > 0) throw new NoteContextPartialSaveError(receipt);
      await assertCurrentNotesUser(expectedUserId);
      if (getUserId(getState) !== expectedUserId) throw new SessionUnavailableError();
      if (receipt.postSaveRecoveryError) {
        console.error("Saved note context links need a cache recovery", receipt.postSaveRecoveryError);
      }

      clearNoteWriteBlockedToast(noteId);
      const settledBase = receiptBaseSettlement(getState, noteId, receipt);
      const currentRecord = (getState() as RootState).notes.notes[noteId] as NoteRecord | undefined;
      const acknowledgedValues = receipt.databaseWrite === "saved" && currentRecord?.folder_id === savedSnapshot.folder_id && currentRecord?.folder_name === savedSnapshot.folder_name
        ? { ...(savedSnapshot.folder_id !== undefined && savedSnapshot.folder_name !== undefined ? { folder_name: receipt.note.folder_name } : {}) }
        : {};
      dispatch(
        markNoteSaved({
          id: noteId,
          updatedAt: settledBase.updated_at ?? undefined,
          version: settledBase.version,
          savedSnapshot,
          acknowledgedValues,
          acknowledgedPhysicalSnapshot: receipt.note,
        }),
      );
      acknowledgedReceipt = receipt;
    } catch (error) {
      attempt.error = error;
      if (error instanceof NoteContextPartialSaveError) {
        retainAttemptReceipt(attempt, error.receipt);
        await assertCurrentNotesUser(expectedUserId);
        if (getUserId(getState) !== expectedUserId) throw new SessionUnavailableError();
        const acknowledgedSnapshot = { ...savedSnapshot };
        for (const field of error.failedFields) {
          delete acknowledgedSnapshot[field];
        }
        const settledBase = receiptBaseSettlement(getState, noteId, error.receipt);
        const currentRecord = (getState() as RootState).notes.notes[noteId] as NoteRecord | undefined;
        const acknowledgedValues = error.databaseWrite === "saved" && currentRecord?.folder_id === acknowledgedSnapshot.folder_id && currentRecord?.folder_name === acknowledgedSnapshot.folder_name
          ? { ...(acknowledgedSnapshot.folder_id !== undefined && acknowledgedSnapshot.folder_name !== undefined ? { folder_name: error.actualStoredNote.folder_name } : {}) }
          : {};
        dispatch(markNoteSaved({
          id: noteId,
          updatedAt: settledBase.updated_at ?? undefined,
          version: settledBase.version,
          savedSnapshot: acknowledgedSnapshot,
          acknowledgedValues,
          acknowledgedPhysicalSnapshot: acknowledgedReceiptSnapshot(attempt, error.receipt),
        }));
        if (error.receipt.postSaveRecoveryError) {
          console.error("Partial note context save needs a cache recovery", error.receipt.postSaveRecoveryError);
        }
      }
      if (error instanceof NoteUpdateConflictError) {
        // The service's CAS error is the authoritative full comparison row.
        // Record it before rejection; the editor must never issue a second
        // content/timestamp SELECT or infer conflict state from realtime.
        await assertCurrentNotesUser(expectedQueueUserId);
        if (!expectedOrganizationId || getUserId(getState) !== expectedQueueUserId) throw new SessionUnavailableError();
        dispatch(recordNoteConflict({
          id: noteId,
          expectedVersion: error.expectedVersion,
          currentVersion: error.currentVersion,
          currentRow: {
            ...error.actualStoredNote,
            project_id: record.project_id,
            task_id: record.task_id,
          },
          sentSnapshot: savedSnapshot,
          actorId: expectedQueueUserId,
          organizationId: expectedOrganizationId,
          decisionId: conflictId(),
          reviewId: conflictId(),
        }));
        throw error;
      }
      if (error instanceof SessionUnavailableError) throw error;
      const friendly =
        error instanceof Error ? error.message : "Could not save note context.";
      failNoteSave(dispatch, getState, noteId, friendly);
      throw error;
    } finally {
      // This is deliberately independent of receipt/error settlement. An auth
      // boundary can throw while handling a partial receipt, and stale receipt
      // data must never be used merely to release the local save indicator.
      dispatch(clearSavingNoteId(noteId));
    }

    // Dispatch label change event if label was dirty
    if (hasLabelChange) {
      dispatchCustomEvent("notes:labelChange", {
        noteId,
        label: savedSnapshot.label,
      });
    }
    return acknowledgedReceipt;
    } catch (error) {
      // Includes session refusals before transport and inside partial receipt
      // settlement, where the inner catch initially held the partial error.
      attempt.error = error;
      throw error;
    }
  },
);

type SaveResultAction = Awaited<ReturnType<ReturnType<typeof saveNotePayload>>>;
type QueuedSaveResult = Promise<SaveResultAction> & { unwrap: () => Promise<void> };

type QueuedSaveThunk = ThunkAction<QueuedSaveResult, unknown, unknown, UnknownAction>;

type ReviewedRefusalReason = "invalid-permit" | "source-changed" | "session-changed" | "not-persisted" | "queue-busy" | "snapshot-changed" | "unsupported-fields" | "conflict" | "unavailable" | "invalid-receipt";
interface NoteReviewedBaseSentFields {
  physical: Partial<Pick<Note, WritablePhysicalKey>>;
  context: Partial<Pick<Note, ContextKey>>;
}
export type NoteReviewedSentFields =
  | (NoteReviewedBaseSentFields & { folderName?: never })
  | (NoteReviewedBaseSentFields & { physical: Pick<Note, "folder_id">; folderName: Note["folder_name"] });
interface ReviewedResultIdentity {
  operationId: string;
  sourceId: string;
  snapshotId: string;
  actorId: string;
  noteId: string;
  organizationId: string;
  attemptedFields: NoteReviewedSentFields;
}
type ReviewedRefusedIdentity = { [K in keyof ReviewedResultIdentity]: K extends "attemptedFields" ? NoteReviewedSentFields : string | null };
type NonemptyContext = { project_id: Note["project_id"]; task_id?: Note["task_id"] } | { task_id: Note["task_id"]; project_id?: Note["project_id"] };
export type NoteReviewedSaveResult = (ReviewedResultIdentity & (
  | { status: "physical-saved"; receipt: NoteSaveReceipt & { databaseWrite: "saved"; failedFields: [] } }
  | { status: "context-settled"; attemptedFields: { physical: Record<string, never>; context: NonemptyContext }; receipt: NoteSaveReceipt & { databaseWrite: "unchanged"; failedFields: [] } }
  | { status: "partial"; receipt: NoteSaveReceipt & { failedFields: [ContextKey, ...ContextKey[]] } }
  | { status: "recovery-required"; receipt: NoteSaveReceipt; reason: "session-changed" | "cache-recovery" }
  | { status: "no-write"; reason: "clean"; receipt?: never }
  | { status: "observation-released"; receipt?: never }
)) | (ReviewedRefusedIdentity & { status: "refused"; reason: ReviewedRefusalReason; receipt?: never });
export interface NoteSaveObservation { result: Promise<NoteReviewedSaveResult>; release(): void; }
interface SaveAttempt {
  operationId: string;
  actorId: string;
  record: NoteRecord | undefined;
  sent: NoteReviewedSentFields;
  permit?: ReviewedPermitState;
  phase: "captured" | "settling" | "settled";
  receipt?: NoteSaveReceipt;
  error?: unknown;
  invalidReceipt?: boolean;
  observers: Set<(result: NoteReviewedSaveResult) => void>;
}
interface SaveQueueEntry {
  result: QueuedSaveResult;
  resolve: (action: SaveResultAction) => void;
  expectedUserId: string;
  attempt?: SaveAttempt;
}
const saveQueues = new WeakMap<() => unknown, Map<string, SaveQueueEntry>>();

function immutableCopy<T>(value: T): T {
  const copy = structuredClone(value);
  const freeze = (item: unknown): void => {
    if (!item || typeof item !== "object" || Object.isFrozen(item)) return;
    for (const child of Object.values(item)) freeze(child);
    Object.freeze(item);
  };
  freeze(copy);
  return copy;
}
function sentFields(record: NoteRecord | undefined): NoteReviewedSentFields {
  const physical: NoteReviewedSentFields["physical"] = {};
  const context: NoteReviewedSentFields["context"] = {};
  if (record?._dirty) {
    for (const field of writablePhysicalKeys) {
      if (record._dirtyFields.has(field)) Object.assign(physical, { [field]: record[field] });
    }
    for (const field of contextKeys) {
      if (record._dirtyFields.has(field)) Object.assign(context, { [field]: record[field] });
    }
  }
  if (record?._dirtyFields.has("folder_name") && record._dirtyFields.has("folder_id")) {
    return immutableCopy({ physical: { ...physical, folder_id: record.folder_id }, context, folderName: record.folder_name });
  }
  return immutableCopy({ physical, context });
}
function resultIdentity(permit: ReviewedPermitState, attempt: SaveAttempt): ReviewedResultIdentity;
function resultIdentity(permit?: ReviewedPermitState, attempt?: SaveAttempt): ReviewedRefusedIdentity;
function resultIdentity(permit?: ReviewedPermitState, attempt?: SaveAttempt): ReviewedRefusedIdentity {
  return { operationId: attempt?.operationId ?? null, sourceId: permit?.source.sourceId ?? null, snapshotId: permit?.source.snapshotId ?? null, actorId: permit?.actorId ?? null, noteId: permit?.noteId ?? null, organizationId: permit?.organizationId ?? null, attemptedFields: attempt?.sent ?? permit?.sent ?? { physical: {}, context: {} } };
}
function reviewedRefusal(reason: ReviewedRefusalReason, permit?: ReviewedPermitState): NoteSaveObservation {
  return { result: Promise.resolve(immutableCopy({ ...resultIdentity(permit), status: "refused", reason })), release() {} };
}
function observeAttempt(permit: ReviewedPermitState): NoteSaveObservation {
  if (permit.result) return { result: Promise.resolve(permit.result), release() {} };
  const attempt = permit.attempt;
  if (!attempt) return reviewedRefusal("unavailable", permit);
  let finish: ((value: NoteReviewedSaveResult) => void) | undefined;
  let pending = true;
  const result = new Promise<NoteReviewedSaveResult>((resolve) => { finish = resolve; });
  if (!finish) throw new Error("Could not initialize Notes save observation.");
  const resolve = finish;
  const subscriber = (value: NoteReviewedSaveResult) => { if (!pending) return; pending = false; attempt.observers.delete(subscriber); resolve(value); };
  attempt.observers.add(subscriber);
  return { result, release() { subscriber(immutableCopy({ ...resultIdentity(permit, attempt), status: "observation-released" })); } };
}
function captureSaveAttempt(getState: () => unknown, noteId: string, actorId: string, permit?: ReviewedPermitState): SaveAttempt {
  const current = (getState() as RootState).notes.notes[noteId] as NoteRecord | undefined;
  const record = current ? immutableCopy({ ...current, version: permit?.version ?? current.version }) : undefined;
  const attempt: SaveAttempt = { operationId: crypto.randomUUID(), actorId, record, sent: sentFields(record), permit, phase: "captured", observers: new Set() };
  if (permit) permit.attempt = attempt;
  return attempt;
}
function retainAttemptReceipt(attempt: SaveAttempt, receipt: NoteSaveReceipt): void {
  if (!attempt.permit) return;
  try {
    const validated = validateNoteSaveReceipt({ base: attempt.permit.source.editBase, receipt, submittedPhysical: attempt.sent.physical, submittedContext: attempt.sent.context, requirePhysicalWrite: true });
    const base = attempt.permit.source.acknowledgedPhysicalSnapshot;
    const expected = { ...base, ...attempt.sent.physical };
    for (const field of [...writablePhysicalKeys, "metadata", "position"] as const) {
      const actual = field === "content" ? validated.note.content ?? "" : validated.note[field];
      if (!equalNoteSnapshotValue(actual, expected[field])) throw new Error("The note acknowledgement changed an unsubmitted physical field.");
    }
    if (!Object.hasOwn(attempt.sent.physical, "folder_id") && (validated.note.folder_name || "Draft") !== (base.folder_name || "Draft")) throw new Error("The note acknowledgement changed the unsubmitted folder projection.");
    for (const field of validated.failedFields) {
      if (!equalNoteSnapshotValue(validated.note[field], base[field])) throw new Error("The note acknowledgement changed a failed context field.");
    }
    attempt.receipt = immutableCopy(validated);
    attempt.phase = "settling";
  } catch (error) { attempt.invalidReceipt = true; throw error; }
}
function acknowledgedReceiptSnapshot(attempt: SaveAttempt, receipt: NoteSaveReceipt): Note {
  if (!attempt.permit || receipt.failedFields.length === 0) return receipt.note;
  const snapshot = { ...receipt.note };
  for (const field of receipt.failedFields) snapshot[field] = attempt.permit.source.acknowledgedPhysicalSnapshot[field];
  return snapshot;
}
function settleAttempt(attempt: SaveAttempt, rejected: boolean, getState: () => unknown): void {
  attempt.phase = "settled";
  const permit = attempt.permit;
  if (!permit) return;
  const identity = resultIdentity(permit, attempt);
  let result: NoteReviewedSaveResult;
  let actorChanged = attempt.error instanceof SessionUnavailableError;
  try { actorChanged ||= getUserId(getState) !== attempt.actorId; } catch { actorChanged = true; }
  const receipt = attempt.receipt;
  if (receipt && actorChanged) result = { ...identity, status: "recovery-required", receipt, reason: "session-changed" };
  else if (receipt && (receipt.postSaveRecoveryError || rejected && !(attempt.error instanceof NoteContextPartialSaveError))) result = { ...identity, status: "recovery-required", receipt, reason: "cache-recovery" };
  else if (receipt?.failedFields[0]) result = { ...identity, status: "partial", receipt: { ...receipt, failedFields: [receipt.failedFields[0], ...receipt.failedFields.slice(1)] } };
  else if (receipt?.databaseWrite === "saved") result = { ...identity, status: "physical-saved", receipt: { ...receipt, databaseWrite: "saved", failedFields: [] } };
  else if (receipt?.databaseWrite === "unchanged" && Object.keys(attempt.sent.physical).length === 0 && (attempt.sent.context.project_id !== undefined || attempt.sent.context.task_id !== undefined)) {
    const context: NonemptyContext = attempt.sent.context.project_id !== undefined
      ? { ...attempt.sent.context, project_id: attempt.sent.context.project_id }
      : { task_id: attempt.sent.context.task_id ?? null };
    result = { ...identity, attemptedFields: { physical: {}, context }, status: "context-settled", receipt: { ...receipt, databaseWrite: "unchanged", failedFields: [] } };
  }
  else if (!rejected && !attempt.record?._dirty) result = { ...identity, status: "no-write", reason: "clean" };
  else result = { ...identity, status: "refused", reason: actorChanged ? "session-changed" : attempt.invalidReceipt ? "invalid-receipt" : attempt.error instanceof NoteUpdateConflictError ? "conflict" : "unavailable" };
  permit.result = immutableCopy(result);
  for (const subscriber of attempt.observers) subscriber(permit.result);
  attempt.observers.clear();
}

/** Reviewed observers subscribe to an exact captured attempt, never the drain. */
export const saveReviewedNoteSnapshot = (args: { permit: NoteReviewedSavePermit; currentSource: NoteEditableContentSource }) => (
  dispatch: ThunkDispatch<RootState, unknown, UnknownAction>, getState: () => RootState,
): NoteSaveObservation => {
  const permit = reviewedSavePermits.get(args.permit);
  if (!permit || permit.getState !== getState) return reviewedRefusal("invalid-permit");
  try {
    canonicalNoteSnapshotValue(args.currentSource);
    if (!isPreparedEditableNoteSource(args.currentSource) || !equalNoteSnapshotValue(permit.source, args.currentSource)) return reviewedRefusal("source-changed", permit);
    if (getUserId(getState) !== permit.actorId) return reviewedRefusal("session-changed", permit);
  } catch { return reviewedRefusal("invalid-permit", permit); }
  if (permit.attempt || permit.result) return observeAttempt(permit);
  if (saveQueues.get(getState)?.has(permit.noteId)) return reviewedRefusal("queue-busy", permit);
  const admitted = captureReviewedNoteSave(args.currentSource)(dispatch, getState);
  if (admitted.status === "refused") return reviewedRefusal(admitted.reason, permit);
  reviewedSavePermits.delete(admitted.permit);
  beginSaveQueue(permit.noteId, dispatch, getState, permit);
  return observeAttempt(permit);
};

function isUnknownRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function hasQueuedDirtyNote(getState: () => unknown, noteId: string): boolean {
  const state = getState();
  if (!isUnknownRecord(state) || !("notes" in state)) return false;
  const notesState = state.notes;
  if (!isUnknownRecord(notesState) || !("notes" in notesState)) return false;
  const records = notesState.notes;
  if (!isUnknownRecord(records) || !(noteId in records)) return false;
  const record = records[noteId];
  if (!isUnknownRecord(record) || record._dirty !== true) return false;
  const dirtyFields = record._dirtyFields;
  return dirtyFields instanceof Set && dirtyFields.size > 0;
}

function createQueuedSaveResult(): SaveQueueEntry {
  let resolver: ((action: SaveResultAction) => void) | undefined;
  const promise = new Promise<SaveResultAction>((resolve) => {
    resolver = resolve;
  });
  if (!resolver) throw new Error("Could not initialize the Notes save queue.");
  return {
    result: Object.assign(promise, {
      unwrap: () => promise.then(unwrapResult).then(() => undefined),
    }),
    resolve: resolver,
    expectedUserId: "",
  };
}

/**
 * One serialized write turn per actual Redux store and note. The queue entry
 * exists before the inner RTK thunk emits `pending`, so synchronous
 * subscribers cannot issue a second CAS against the same revision.
 */
function beginSaveQueue(
  noteId: string, dispatch: ThunkDispatch<unknown, unknown, UnknownAction>, getState: () => unknown, permit?: ReviewedPermitState,
): QueuedSaveResult {
  let queue = saveQueues.get(getState);
  if (!queue) { queue = new Map(); saveQueues.set(getState, queue); }
  const existing = queue.get(noteId);
  if (existing) return existing.result;
  const entry = createQueuedSaveResult();
  entry.expectedUserId = getUserId(getState);
  queue.set(noteId, entry);
  void (async () => {
    let finalAction: SaveResultAction | undefined;
    try {
      do {
        // Capture synchronously before RTK emits pending and any subscriber
        // can re-enter. The payload looks up this immutable private attempt.
        entry.attempt = captureSaveAttempt(getState, noteId, entry.expectedUserId, permit);
        permit = undefined;
        finalAction = await dispatch(saveNotePayload({ noteId, expectedQueueUserId: entry.expectedUserId, operationId: entry.attempt.operationId }));
        settleAttempt(entry.attempt, saveNotePayload.rejected.match(finalAction), getState);
        if (saveNotePayload.rejected.match(finalAction)) break;
      } while (hasQueuedDirtyNote(getState, noteId));
    } catch (error) {
      if (entry.attempt) { entry.attempt.error = error; settleAttempt(entry.attempt, true, getState); }
      const rejection = saveNotePayload.rejected(error instanceof Error ? error : new Error("Notes save queue failed."), "notes-save-queue", { noteId, expectedQueueUserId: entry.expectedUserId, operationId: entry.attempt?.operationId ?? "uncaptured" });
      finalAction = rejection;
      try { dispatch(rejection); } catch { /* The deferred result retains the rejection. */ }
    } finally {
      queue.delete(noteId);
      if (queue.size === 0) saveQueues.delete(getState);
      if (finalAction) entry.resolve(finalAction);
    }
  })();
  return entry.result;
}
export const saveNote = Object.assign(
  (noteId: string): QueuedSaveThunk => (dispatch, getState) => beginSaveQueue(noteId, dispatch, getState),
  { fulfilled: saveNotePayload.fulfilled, rejected: saveNotePayload.rejected },
);

