// Audit N-21 — deleting a note threw the last few seconds of typing away in
// silence. `removeNote` drops the record, the pending autosave timer then
// finds nothing and returns, and Undo restores the SERVER's older text with no
// mention that newer words went with it. The delete now snapshots the browser
// draft first, so the typed text is recoverable either way.

import { deleteNote, noteHasUnsavedEdits } from "./thunks";
import { supabase } from "@/utils/supabase/client";
import { NOTE_DELETED_DRAFT_REASON, captureNoteDrafts } from "../utils/notesDrafts";
import { setNoteLiveContent } from "../utils/noteLiveContent";

jest.mock("@/utils/supabase/client", () => ({
  supabase: { auth: { getSession: jest.fn() }, schema: jest.fn() },
}));

jest.mock("../utils/notesDrafts", () => ({
  ...jest.requireActual("../utils/notesDrafts"),
  captureNoteDrafts: jest.fn(() => []),
}));

function deleteQuery(rows: unknown[]) {
  const chain = {
    from: jest.fn(),
    update: jest.fn(),
    eq: jest.fn(),
    select: jest.fn(async () => ({ data: rows, error: null })),
  };
  chain.from.mockReturnValue(chain);
  chain.update.mockReturnValue(chain);
  chain.eq.mockReturnValue(chain);
  return chain;
}

type Record_ = Record<string, unknown>;

function stateWith(record: Record_) {
  return {
    userAuth: { id: "user-1" },
    notes: { notes: { [record.id as string]: record } },
  };
}

async function runDelete(record: Record_) {
  jest.mocked(supabase.schema).mockReturnValue(deleteQuery([{ id: record.id }]) as never);
  const dispatch = jest.fn((action) => action);
  await deleteNote(record.id as string)(
    dispatch,
    () => stateWith(record) as never,
    undefined,
  );
  return dispatch;
}

describe("deleteNote and unsaved edits", () => {
  beforeEach(() => {
    jest.clearAllMocks();
    setNoteLiveContent("note-1", null);
  });

  it("captures the draft BEFORE the record is removed", async () => {
    const dispatch = await runDelete({
      id: "note-1",
      content: "the paragraph I just typed",
      _dirty: true,
    });

    expect(captureNoteDrafts).toHaveBeenCalledWith(NOTE_DELETED_DRAFT_REASON);
    const captureOrder = jest.mocked(captureNoteDrafts).mock.invocationCallOrder[0];
    const removeCall = dispatch.mock.calls.findIndex(
      ([action]) => (action as { type?: string })?.type === "notes/removeNote",
    );
    expect(removeCall).toBeGreaterThanOrEqual(0);
    // The capture reads Redux + the live buffer; it has to run while they
    // still hold the note.
    expect(captureOrder).toBeLessThan(
      (dispatch.mock.invocationCallOrder ?? [])[removeCall] ?? Infinity,
    );
  });

  it("captures text that exists ONLY in the editor's pre-debounce buffer", async () => {
    setNoteLiveContent("note-1", "typed half a second ago");

    await runDelete({ id: "note-1", content: "saved text", _dirty: false });

    expect(captureNoteDrafts).toHaveBeenCalledWith(NOTE_DELETED_DRAFT_REASON);
  });

  it("captures before removing a never-persisted autogenerated note too", async () => {
    await runDelete({
      id: "note-1",
      content: "a brand new thought",
      _dirty: true,
      _isAutogenerated: true,
    });

    expect(captureNoteDrafts).toHaveBeenCalledWith(NOTE_DELETED_DRAFT_REASON);
  });

  it("captures nothing when the database already holds the note", async () => {
    await runDelete({ id: "note-1", content: "saved text", _dirty: false });

    expect(captureNoteDrafts).not.toHaveBeenCalled();
  });

  it("noteHasUnsavedEdits reads Redux AND the live buffer", () => {
    expect(noteHasUnsavedEdits({ id: "note-1", _dirty: true, content: "x" })).toBe(true);
    expect(noteHasUnsavedEdits({ id: "note-1", _dirty: false, content: "x" })).toBe(false);
    setNoteLiveContent("note-1", "x plus one more word");
    expect(noteHasUnsavedEdits({ id: "note-1", _dirty: false, content: "x" })).toBe(true);
    expect(noteHasUnsavedEdits(undefined)).toBe(false);
  });
});
