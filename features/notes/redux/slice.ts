/**
 * `Array.prototype.pop` is always typed `T | undefined` — TS can't correlate
 * a preceding `.length > 0` guard with the pop that follows. Centralizing the
 * "pop after a proven-non-empty check" call here confines that one honest
 * assertion to a single reviewed line instead of a `!` at every call site.
 */
function popNonEmpty<T>(stack: T[]): T {
  const entry = stack.pop();
  if (entry === undefined) {
    throw new Error("popNonEmpty called on an empty stack");
  }
  return entry;
}

/** A revision is a database CAS value, never a loosely parsed counter. */
function isCanonicalNoteRevision(value: unknown): value is number {
  return typeof value === "number" && Number.isSafeInteger(value) && value >= 0;
}

function hasMalformedNoteRevision(value: unknown): boolean {
  return value !== null && value !== undefined && !isCanonicalNoteRevision(value);
}

// ── Byte estimation ─────────────────────────────────────────────────────────

function estimateBytes(value: unknown): number {
  if (value == null) return 0;
  if (typeof value === "string") return value.length * 2;
  if (typeof value === "number" || typeof value === "boolean") return 8;
  try {
    return JSON.stringify(value).length * 2;
  } catch {
    return 256;
  }
}

function totalStackBytes(stack: NoteUndoEntry[]): number {
  let total = 0;
  for (const entry of stack) total += entry.byteEstimate;
  return total;
}

// ── Stack compression ───────────────────────────────────────────────────────

function compressStack(stack: NoteUndoEntry[]): NoteUndoEntry[] {
  if (
    stack.length <= NOTE_UNDO_MAX_ENTRIES &&
    totalStackBytes(stack) <= NOTE_UNDO_MAX_BYTES
  ) {
    return stack;
  }

  const protectedHead = 1;
  const protectedTail = Math.min(20, Math.floor(stack.length * 0.4));

  if (stack.length <= protectedHead + protectedTail) return stack;

  const head = stack.slice(0, protectedHead);
  const tail = stack.slice(-protectedTail);
  let middle = stack.slice(protectedHead, stack.length - protectedTail);

  // Phase 1: merge consecutive same-field entries (keep oldest value)
  const merged: NoteUndoEntry[] = [];
  for (const entry of middle) {
    const prev = merged[merged.length - 1];
    if (prev && prev.field === entry.field) continue;
    merged.push(entry);
  }
  middle = merged;

  // Phase 2: thin every other entry if still over count
  let result = [...head, ...middle, ...tail];
  if (result.length > NOTE_UNDO_MAX_ENTRIES) {
    const thinned: NoteUndoEntry[] = [];
    for (let i = 0; i < middle.length; i++) {
      if (i % 2 === 0) thinned.push(middle[i]);
    }
    result = [...head, ...thinned, ...tail];
  }

  // Phase 3: drop from oldest middle if still over byte budget
  while (
    result.length > protectedHead + protectedTail + 1 &&
    totalStackBytes(result) > NOTE_UNDO_MAX_BYTES
  ) {
    result.splice(protectedHead, 1);
  }

  return result;
}

// ── Undo entry push with coalescing ─────────────────────────────────────────

function pushUndoEntry(
  record: NoteRecord,
  field: NoteUndoableField,
  previousValue: Note[NoteUndoableField],
): void {
  const now = Date.now();
  const bytes = estimateBytes(previousValue);
  const top = record._undoPast[record._undoPast.length - 1];

  if (
    top &&
    top.field === field &&
    now - top.timestamp < NOTE_UNDO_COALESCE_MS
  ) {
    top.timestamp = now;
  } else {
    record._undoPast.push({
      field,
      value: previousValue,
      timestamp: now,
      byteEstimate: bytes,
    });
  }

  record._undoFuture = [];
  record._undoPast = compressStack(record._undoPast);
}

// ── Generic-indexed field write ──────────────────────────────────────────────
// `record[field] = value` doesn't type-check for a generic `K extends
// NoteUndoableField`: TS correlates `field: K` and `value: Note[K]` fine for
// reads, but not for a write through a generic index (a known TS limitation,
// not a real unsoundness — `field`/`value` are always introduced together
// from the same `K` at every call site below). Centralizing the write here,
// once, keeps the honest generic signature everywhere else and confines the
// necessary widening to a single reviewed line.
function writeNoteUndoableField<K extends NoteUndoableField>(
  record: NoteRecord,
  field: K,
  value: Note[K],
): void {
  // MATRX-EXCEPTION: TS can't correlate a generic index write even though
  // `field`/`value` share the same `K` at every call site (read-side
  // correlation works; write-side doesn't — known TS limitation, not a real
  // unsoundness here). Confined to this one reviewed line.
  const fields = record as unknown as Record<NoteUndoableField, Note[K]>;
  fields[field] = value;
}

/** Same generic-index write limitation as above, for the full `Note` field
 * set (server-merge path, not just the undoable subset). */
function writeNoteField<K extends keyof Note>(
  record: NoteRecord,
  field: K,
  value: Note[K],
): void {
  // MATRX-EXCEPTION: see writeNoteUndoableField above — same generic-index
  // write limitation, over the full `Note` key set instead of the undoable
  // subset.
  const fields = record as unknown as Record<K, Note[K]>;
  fields[field] = value;
}

// ── Apply field edit with dirty tracking ─────────────────────────────────────

function applyFieldEdit<K extends NoteUndoableField>(
  record: NoteRecord,
  field: K,
  value: Note[K],
): void {
  const previousValue = record[field] as Note[K];

  // Capture clean baseline once per field per clean cycle
  if (!record._dirtyFields.has(field)) {
    (record._fieldHistory as NoteFieldSnapshot)[field] = previousValue;
  }

  pushUndoEntry(record, field, previousValue);

  writeNoteUndoableField(record, field, value);
  record._dirtyFields.add(field);
  record._dirty = true;
}

// ── Mark record clean ───────────────────────────────────────────────────────

function markRecordClean(record: NoteRecord): void {
  record._dirty = false;
  record._dirtyFields = new Set();
  record._fieldHistory = {};
  // Undo stacks are preserved across saves (user can still undo after save)
}

/**
 * Clear dirty only for fields whose current value still matches what we wrote.
 * Edits that landed mid-save stay dirty so the next autosave persists them.
 */
function markSavedSnapshotClean(
  record: NoteRecord,
  savedSnapshot: Partial<Record<NoteUndoableField, Note[NoteUndoableField]>>,
): void {
  for (const field of Object.keys(savedSnapshot) as NoteUndoableField[]) {
    if (!record._dirtyFields.has(field)) continue;
    if (record[field] === savedSnapshot[field]) {
      record._dirtyFields.delete(field);
    }
  }
  record._dirty = record._dirtyFields.size > 0;
  if (!record._dirty) {
    record._fieldHistory = {};
  }
}

// ── Apply fetch status (never downgrades) ───────────────────────────────────

function applyFetchStatus(record: NoteRecord, status: NoteFetchStatus): void {
  if (shouldUpgradeNoteFetchStatus(record._fetchStatus, status)) {
    record._fetchStatus = status;
  }
}

/** The fields of the stored row a person edits (context links are separate writes). */
const STORED_PHYSICAL_FIELDS = [
  "content",
  "label",
  "folder_name",
  "folder_id",
  "tags",
  "shown_to",
  "published_to_web",
] as const satisfies readonly NoteUndoableField[];

/** The observed stored row is now this record's edit base (its version, its acknowledged snapshot). */
function settleStoredBase(record: NoteRecord, remote: Partial<Note> & { id: string }): void {
  if (isCanonicalNoteRevision(remote.version)) record.version = remote.version;
  if (remote.updated_at) record.updated_at = remote.updated_at;
  const acknowledged = acknowledgedSnapshotFromFullRead(isDraft(remote) ? current(remote) : remote, "full");
  if (acknowledged) record._acknowledgedPhysicalSnapshot = acknowledged;
}

/**
 * Back to what is stored: the observed stored row when there is one (a
 * refused save brought it), else each edited field's value before the edit.
 * `content` is the body the person's working copy now shows.
 */
function adoptStoredRow(record: NoteRecord, content: string): void {
  const observed = record._remoteObservation;
  const remote = observed?.complete ? observed.note : null;
  if (remote) {
    for (const [key, value] of Object.entries(remote)) {
      if (key.startsWith("_")) continue;
      const field = key as keyof Note;
      if (field === "project_id" || field === "task_id") continue;
      writeNoteField(record, field, value as Note[typeof field]);
    }
    settleStoredBase(record, remote);
  } else {
    for (const field of STORED_PHYSICAL_FIELDS) {
      if (!record._dirtyFields.has(field)) continue;
      const before = (record._fieldHistory as NoteFieldSnapshot)[field];
      if (before !== undefined) writeNoteUndoableField(record, field, before as Note[typeof field]);
    }
  }
  writeNoteField(record, "content", content);
  for (const field of STORED_PHYSICAL_FIELDS) {
    record._dirtyFields.delete(field);
    delete (record._fieldHistory as NoteFieldSnapshot)[field];
  }
  record._dirty = record._dirtyFields.size > 0;
  record._remoteObservation = null;
  record._error = null;
  record._consecutiveSaveFailures = 0;
  record._firstSaveFailureAt = null;
}

// ── Server upsert (shared by single + batch reducers) ───────────────────────

export interface ServerNoteUpsert {
  note: Partial<Note> & { id: string };
  fetchStatus: NoteFetchStatus;
  /** Present when this upsert came from the shared-with-me list —
   *  flags the record so owner-list selectors exclude it. */
  sharedMeta?: SharedNoteMeta;
}

function applyServerNoteUpsert(
  notes: Record<string, NoteRecord>,
  { note, fetchStatus, sharedMeta }: ServerNoteUpsert,
): void {
  // Partial list evidence may omit a revision, but a supplied malformed
  // revision must never enter the record or become highest remote evidence.
  if (hasMalformedNoteRevision(note.version)) return;
  const existing = notes[note.id];

  if (!existing) {
    // `workbench.notes.organization_id` is NOT NULL. A first-time record
    // MUST carry a real org id — building one with a fabricated ""-value
    // would write an invalid row into the store and hide the real bug: an
    // incomplete server payload reaching this reducer. Scream and skip
    // rather than persisting garbage. (Loud recovery: this firing means a
    // `Partial<Note>` without `organization_id` got past its producer.)
    if (!note.organization_id) {
      captureError({
        source: "supabase-postgrest",
        operation: "upsert",
        schema: "workbench",
        relation: "notes",
        message:
          "upsertNoteFromServer: server note is missing organization_id (NOT NULL) — skipped creating the record to avoid storing an invalid org id",
        details: `note id: ${note.id}, fetchStatus: ${fetchStatus}`,
        raw: note,
      });
      return;
    }
    const record = createBlankNoteRecordFromPartial(
      { ...note, organization_id: note.organization_id },
      fetchStatus,
    );
    if (sharedMeta) {
      record._sharedWithMe = true;
      record._sharedMeta = sharedMeta;
    }
    notes[note.id] = record;
    return;
  }

  const incomingVersion = isCanonicalNoteRevision(note.version) ? note.version : null;
  const heldVersion = isCanonicalNoteRevision(existing.version) ? existing.version : null;
  const isNewerVersion =
    incomingVersion !== null && heldVersion !== null
      ? incomingVersion > heldVersion
      : false;
  const incomingTimestamp = Date.parse(note.updated_at ?? "");
  const heldTimestamp = Date.parse(existing.updated_at ?? "");
  const isNewerTimestamp =
    Number.isFinite(incomingTimestamp) &&
    Number.isFinite(heldTimestamp) &&
    incomingTimestamp > heldTimestamp;

  // Version is authoritative when available. A newer timestamp on a lower
  // revision is an out-of-order event and cannot regress a clean record.
  if (incomingVersion !== null && heldVersion !== null && incomingVersion < heldVersion) {
    return;
  }

  // ── Monotonic updated_at guard ─────────────────────────────────────
  // Realtime echoes and list-fetch races can deliver payloads OLDER than
  // the state we already hold (our own save's echo lands after
  // markNoteSaved stored the fresh updated_at; two in-flight saves can
  // land out of order). Merging a stale payload reverts content and
  // regresses updated_at — which then fails the next save's optimistic
  // lock and produces a sticky false conflict (part of the 2026-07 /notes
  // freeze class — see FEATURE.md § Realtime echo doctrine).
  {
    const incomingTs = Date.parse(note.updated_at ?? "");
    const heldTs = Date.parse(existing.updated_at ?? "");
    if (
      Number.isFinite(incomingTs) &&
      Number.isFinite(heldTs) &&
      incomingTs < heldTs
    ) {
      return;
    }
  }

  // Never downgrade fetch status
  applyFetchStatus(existing, fetchStatus);

  // Refresh shared-with-me metadata (a re-fetch may carry a changed grant
  // level). Never CLEAR the flag from an unrelated upsert — only the
  // shared list sets or updates it.
  if (sharedMeta) {
    existing._sharedWithMe = true;
    existing._sharedMeta = sharedMeta;
  }

  // A list projection cannot establish whether a legacy physical preference
  // exists. Only a full row initializes it, and a real local choice always
  // wins over later server evidence.
  if (fetchStatus === "full" && existing._editorModeSource === "uninitialized") {
    existing._editorMode = editorModeFromPhysicalMetadata(note.metadata);
    existing._editorModeSource = "persisted";
  }

  // A dirty editor retains its acknowledged base and local fields. Realtime is
  // only evidence: it cannot manufacture a conflict dialog or silently rebase
  // a draft. A full CAS rejection is the sole source of a decision package.
  const hasDirtyPhysicalField = Array.from(existing._dirtyFields).some(
    (field) => field !== "project_id" && field !== "task_id",
  );
  // THE FAST-FORWARD. A complete newer row whose user-edited fields still
  // equal this record's acknowledged base is a version bump for a column
  // nobody edits (the desktop sync stamping `file_path`, an ingest job writing
  // metadata). Nothing the user is editing moved, so there is nothing to
  // observe and nothing to review: adopt the number now, so the next save
  // CAS's on the version the row actually holds. The merge loop below skips
  // every dirty field, so the draft is untouched. Root cause of the recurring
  // Note Conflict dialog, 2026-09-13.
  // Completeness is PROVEN from the payload's keys, never taken from the
  // caller's declared fetchStatus, and the base is rebuilt from field history
  // when the record never received a snapshot.
  const fastForwardable =
    existing._dirty &&
    hasDirtyPhysicalField &&
    acknowledgedSnapshotFromFullRead(note, fetchStatus) !== null &&
    incomingVersion !== null &&
    heldVersion !== null &&
    incomingVersion > heldVersion &&
    noteEditedFieldsEqual(note, noteEditBaseFromRecord(existing));
  if (fastForwardable) {
    const observed = existing._remoteObservation;
    if (observed && (observed.version === null || observed.version <= incomingVersion)) {
      existing._remoteObservation = null;
    }
  } else if (existing._dirty && hasDirtyPhysicalField) {
    const heldObservationVersion = existing._remoteObservation?.version ?? null;
    if (heldObservationVersion !== null && !isCanonicalNoteRevision(heldObservationVersion)) {
      return;
    }
    const isNewerObservation =
      incomingVersion !== null &&
      (heldObservationVersion === null || incomingVersion > heldObservationVersion);
    if (
      isNewerObservation ||
      (incomingVersion !== null &&
        incomingVersion === heldObservationVersion &&
        fetchStatus === "full" &&
        existing._remoteObservation?.complete === false) ||
      (incomingVersion === null && isNewerTimestamp)
    ) {
      existing._remoteObservation = {
        version: incomingVersion,
        updatedAt: note.updated_at ?? null,
        complete: fetchStatus === "full",
        note: { ...note },
      };
    }
    return;
  }

  // Merge server fields (don't overwrite undoable fields if dirty).
  // `note` is `Partial<Note> & { id }`, so every key really is `keyof Note`
  // and every value really is `Note[typeof key]` — Object.entries just
  // can't express that correlation, hence the one key cast (not a value
  // cast) before handing both to the correlated writer above.
  for (const [key, value] of Object.entries(note)) {
    if (key.startsWith("_")) continue;
    const field = key as keyof Note;
    if (
      existing._dirty &&
      existing._dirtyFields.has(field as NoteUndoableField)
    ) {
      continue; // Preserve local edit
    }
    writeNoteField(existing, field, value as Note[typeof field]);
  }
  // Only a verified complete, clean full read advances the retained base.
  // A dirty/realtime path returned above and cannot rebase it.
  const acknowledged = acknowledgedSnapshotFromFullRead(note, fetchStatus);
  if (acknowledged) existing._acknowledgedPhysicalSnapshot = acknowledged;
}

