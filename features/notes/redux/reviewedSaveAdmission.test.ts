const schema = jest.fn();
const getSession = jest.fn();
const listForSources = jest.fn();
const setTargets = jest.fn();

jest.mock("@/utils/supabase/client", () => ({ supabase: { schema, auth: { getSession } } }));
jest.mock("@/features/scopes/service/associationsService", () => ({ associationsService: { listForSources, setTargets } }));

import { configureStore } from "@reduxjs/toolkit";
import { enableMapSet } from "immer";
import { createSlimRootReducer, type RootState } from "@/lib/redux/rootReducer";
import { setStoreSingleton } from "@/lib/redux/store-singleton";
import notesReducer, { captureNoteConflictLiveBuffer, setNoteField, upsertNoteFromServer } from "./slice";
import { captureReviewedNoteSave, saveReviewedNoteSnapshot, saveNote, resolveNoteConflict, initializeAutogeneratedNote } from "./thunks";
import type { NoteSaveObservation } from "./thunks";
import { captureNoteEditSourceFromRecord, noteEditableContentSource } from "../richDocumentSource";
import type { Note } from "../types";

enableMapSet();
const ORG = "11111111-1111-4111-8111-111111111111";
const USER = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
const ID = "22222222-2222-4222-8222-222222222222";
const note = (overrides: Partial<Note> = {}): Note => ({ id: ID, organization_id: ORG, content: "before", label: "note", folder_id: null, folder_name: null, tags: [], metadata: {}, position: 0, project_id: null, task_id: null, visibility: "personal", version: 7, updated_at: "2026-09-13T00:00:00.000Z", created_at: "2026-09-13T00:00:00.000Z", created_by: USER, updated_by: null, deleted_at: null, content_hash: null, file_path: null, last_device_id: null, sync_version: 0, ...overrides });

function query(result: unknown) {
  const value = { select: jest.fn(), eq: jest.fn(), is: jest.fn(), update: jest.fn(), insert: jest.fn(), single: jest.fn(), maybeSingle: jest.fn() };
  value.select.mockReturnValue(value); value.eq.mockReturnValue(value); value.is.mockReturnValue(value); value.update.mockReturnValue(value); value.insert.mockReturnValue(value); value.single.mockResolvedValue(result); value.maybeSingle.mockResolvedValue(result);
  return value;
}
function reducer(state: RootState | undefined, action: { type: string }): RootState {
  const next = createSlimRootReducer()(state, action);
  if (action.type === "test/seed-user") return { ...next, userAuth: { ...next.userAuth, id: USER } };
  if (action.type === "test/switch-user") return { ...next, userAuth: { ...next.userAuth, id: "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb" } };
  return next;
}
function storeWithNote() {
  const store = configureStore({ reducer, middleware: (gdm) => gdm({ serializableCheck: false }) });
  store.dispatch({ type: "test/seed-user" });
  store.dispatch(upsertNoteFromServer({ note: note(), fetchStatus: "full" }));
  return store;
}

function prepared(store: ReturnType<typeof storeWithNote>, snapshotId = "snapshot") {
  const record = store.getState().notes.notes[ID];
  return captureNoteEditSourceFromRecord({ record, displayedNote: record, actorId: USER, sourceId: "admission", snapshotId });
}
function captured(store: ReturnType<typeof storeWithNote>) {
  const source = prepared(store);
  const capture = store.dispatch(captureReviewedNoteSave(source));
  if (capture.status !== "captured") throw new Error(`capture refused: ${capture.reason}`);
  return { source, permit: capture.permit };
}

describe("reviewed Notes save admission", () => {
  beforeEach(() => {
    jest.clearAllMocks();
    getSession.mockResolvedValue({ data: { session: { user: { id: USER } } }, error: null });
    listForSources.mockResolvedValue({ ok: true, data: { edges: [] } });
    setTargets.mockResolvedValue({ ok: true, data: null });
  });

  it("settles a clean capture without database I/O or a manufactured receipt", async () => {
    const store = storeWithNote(); const { source, permit } = captured(store);
    const result = await store.dispatch(saveReviewedNoteSnapshot({ permit, currentSource: source })).result;
    expect(result).toMatchObject({ status: "no-write", reason: "clean", noteId: ID, actorId: USER, organizationId: ORG });
    expect(result).not.toHaveProperty("receipt"); expect(schema).not.toHaveBeenCalled();
  });

  it("refuses reviewed autogenerated insertion while preserving ordinary explicit-org materialization", async () => {
    const store = configureStore({ reducer, middleware: (gdm) => gdm({ serializableCheck: false }) });
    setStoreSingleton(store);
    store.dispatch({ type: "test/seed-user" });
    await store.dispatch(initializeAutogeneratedNote({ id: ID, userId: USER, organizationId: ORG, instanceId: "admission", destination: { kind: "unfiled", organizationId: ORG } })).unwrap();
    const source = noteEditableContentSource({ note: note({ version: 0 }), actorId: USER, sourceId: "draft", snapshotId: "draft" });
    expect(store.dispatch(captureReviewedNoteSave(source))).toMatchObject({ status: "refused", reason: "not-persisted" });
    expect(schema).not.toHaveBeenCalled();
    store.dispatch(setNoteField({ id: ID, field: "content", value: "typed" }));
    const inserted = query({ data: note({ content: "typed", version: 1 }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValue(inserted) });
    await store.dispatch(saveNote(ID)).unwrap();
    expect(inserted.insert).toHaveBeenCalledTimes(1);
    expect(inserted.insert).toHaveBeenCalledWith(expect.objectContaining({ id: ID, organization_id: ORG, content: "typed", folder_id: null }));
    expect(store.getState().notes.notes[ID]).toMatchObject({ _isAutogenerated: false, _dirty: false });
  });

  it("refuses forged and cross-store permits without I/O", async () => {
    const store = storeWithNote(); const other = storeWithNote();
    const { source, permit } = captured(store);
    for (const [target, supplied] of [[store, {}], [store, { ...permit }], [other, permit]] as const) {
      await expect(target.dispatch(saveReviewedNoteSnapshot({ permit: supplied, currentSource: source })).result).resolves.toMatchObject({ status: "refused", reason: "invalid-permit" });
    }
    expect(schema).not.toHaveBeenCalled();
  });

  it("refuses extra source and base keys and accessors before any I/O", () => {
    const store = storeWithNote(); const source = prepared(store);
    const extraSource = { ...source, unreviewed: true };
    const extraBase = { ...source, editBase: { ...source.editBase, unreviewed: true } };
    for (const malformed of [extraSource, extraBase]) expect(store.dispatch(captureReviewedNoteSave(malformed))).toMatchObject({ status: "refused" });
    const getter = jest.fn(() => source.noteId);
    const accessorSource = Object.defineProperty({ ...source }, "noteId", { enumerable: true, get: getter });
    expect(store.dispatch(captureReviewedNoteSave(accessorSource))).toMatchObject({ status: "refused", reason: "invalid-permit" });
    expect(getter).not.toHaveBeenCalled(); expect(schema).not.toHaveBeenCalled();
  });

  it("refuses wrong organization, base revision and undefined field values", () => {
    const store = storeWithNote(); const source = prepared(store);
    const otherOrg = "cccccccc-cccc-4ccc-8ccc-cccccccccccc";
    const badOrg = { ...source, editBase: { ...source.editBase, organizationId: otherOrg }, acknowledgedPhysicalSnapshot: { ...source.acknowledgedPhysicalSnapshot, organization_id: otherOrg }, displayedPhysicalSnapshot: { ...source.displayedPhysicalSnapshot, organization_id: otherOrg } };
    const badBase = { ...source, editBase: { ...source.editBase, version: 6 }, acknowledgedPhysicalSnapshot: { ...source.acknowledgedPhysicalSnapshot, version: 6 }, displayedPhysicalSnapshot: { ...source.displayedPhysicalSnapshot, version: 6 } };
    for (const bad of [badOrg, badBase]) expect(store.dispatch(captureReviewedNoteSave(bad))).toMatchObject({ status: "refused", reason: "source-changed" });
    const undefinedField = { ...source, displayedPhysicalSnapshot: { ...source.displayedPhysicalSnapshot, content: undefined } };
    // @ts-expect-error Runtime callers can omit required physical values.
    expect(store.dispatch(captureReviewedNoteSave(undefinedField))).toMatchObject({ status: "refused", reason: "invalid-permit" });
    expect(schema).not.toHaveBeenCalled();
  });

  it("does not reread caller-owned arrays after dispatch", async () => {
    const store = storeWithNote(); store.dispatch(setNoteField({ id: ID, field: "tags", value: ["reviewed"] }));
    const source = structuredClone(prepared(store));
    const capture = store.dispatch(captureReviewedNoteSave(source));
    if (capture.status !== "captured") throw new Error("Expected mutable caller source to capture");
    let resume: (() => void) | undefined;
    const auth = new Promise<void>((resolve) => { resume = resolve; });
    getSession.mockImplementationOnce(async () => { await auth; return { data: { session: { user: { id: USER } } }, error: null }; });
    const read = query({ data: note(), error: null }); const written = query({ data: note({ tags: ["reviewed"], version: 8 }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(read).mockReturnValueOnce(written) });
    const observation = store.dispatch(saveReviewedNoteSnapshot({ permit: capture.permit, currentSource: source }));
    source.displayedPhysicalSnapshot.tags?.push("unreviewed");
    if (!resume) throw new Error("Expected auth gate"); resume();
    await expect(observation.result).resolves.toMatchObject({ status: "physical-saved", attemptedFields: { physical: { tags: ["reviewed"] } }, receipt: { note: { tags: ["reviewed"] } } });
    expect(written.update.mock.calls[0][0]).toMatchObject({ tags: ["reviewed"] });
  });

  it("refuses extra dirt added after capture even when the caller retains the old source", async () => {
    const store = storeWithNote(); store.dispatch(setNoteField({ id: ID, field: "content", value: "reviewed" }));
    const { source, permit } = captured(store);
    store.dispatch(setNoteField({ id: ID, field: "label", value: "later label" }));
    await expect(store.dispatch(saveReviewedNoteSnapshot({ permit, currentSource: source })).result).resolves.toMatchObject({ status: "refused", reason: "source-changed", attemptedFields: { physical: { content: "reviewed" }, context: {} } });
    expect(schema).not.toHaveBeenCalled();
    expect(store.getState().notes.notes[ID]).toMatchObject({ content: "reviewed", label: "later label", _dirty: true });
  });

  it("retains exact captured fields and explicit null in a pre-attempt refusal", async () => {
    const store = storeWithNote();
    const project = "cccccccc-cccc-4ccc-8ccc-cccccccccccc";
    const folder = "dddddddd-dddd-4ddd-8ddd-dddddddddddd";
    store.dispatch(upsertNoteFromServer({ note: note({ project_id: project }), fetchStatus: "full" }));
    store.dispatch(setNoteField({ id: ID, field: "content", value: "reviewed" }));
    store.dispatch(setNoteField({ id: ID, field: "tags", value: ["reviewed"] }));
    store.dispatch(setNoteField({ id: ID, field: "project_id", value: null }));
    store.dispatch(setNoteField({ id: ID, field: "folder_id", value: folder }));
    store.dispatch(setNoteField({ id: ID, field: "folder_name", value: "Target" }));
    const { source, permit } = captured(store);
    store.dispatch(setNoteField({ id: ID, field: "label", value: "later" }));
    const result = await store.dispatch(saveReviewedNoteSnapshot({ permit, currentSource: source })).result;
    expect(result).toMatchObject({ status: "refused", reason: "source-changed", operationId: null });
    expect(result.attemptedFields).toEqual({ physical: { content: "reviewed", tags: ["reviewed"], folder_id: folder }, context: { project_id: null }, folderName: "Target" });
    expect(schema).not.toHaveBeenCalled();
  });

  it("refuses an ordinary in-flight attempt instead of borrowing its receipt", async () => {
    const store = storeWithNote(); store.dispatch(setNoteField({ id: ID, field: "content", value: "reviewed" }));
    const { source, permit } = captured(store);
    let finish: ((value: unknown) => void) | undefined;
    let entered: (() => void) | undefined;
    const entering = new Promise<void>((resolve) => { entered = resolve; });
    const existing = query({ data: note(), error: null }); const updated = query(undefined);
    updated.maybeSingle.mockImplementation(() => new Promise((resolve) => { finish = resolve; entered?.(); }));
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(updated) });
    const drain = store.dispatch(saveNote(ID)); await entering;
    await expect(store.dispatch(saveReviewedNoteSnapshot({ permit, currentSource: source })).result).resolves.toMatchObject({ status: "refused", reason: "queue-busy" });
    if (!finish) throw new Error("transport did not start"); finish({ data: note({ content: "reviewed", version: 8 }), error: null });
    await expect(drain.unwrap()).resolves.toBeUndefined(); expect(updated.update).toHaveBeenCalledTimes(1);
  });

  it("requires a fresh capture to retry an unacknowledged failed attempt", async () => {
    const store = storeWithNote(); store.dispatch(setNoteField({ id: ID, field: "content", value: "reviewed" }));
    const { source, permit } = captured(store);
    schema.mockReturnValue({ from: jest.fn().mockReturnValue(query({ data: null, error: { message: "transport refused" } })) });
    const first = await store.dispatch(saveReviewedNoteSnapshot({ permit, currentSource: source })).result;
    expect(first).toMatchObject({ status: "refused" }); expect(first).not.toHaveProperty("receipt");
    const calls = schema.mock.calls.length;
    expect(await store.dispatch(saveReviewedNoteSnapshot({ permit, currentSource: source })).result).toBe(first);
    expect(schema).toHaveBeenCalledTimes(calls);
    const retry = captured(store);
    const existing = query({ data: note(), error: null }); const updated = query({ data: note({ content: "reviewed", version: 8 }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(updated) });
    await expect(store.dispatch(saveReviewedNoteSnapshot({ permit: retry.permit, currentSource: retry.source })).result).resolves.toMatchObject({ status: "physical-saved", receipt: { note: { version: 8 } } });
    expect(updated.update).toHaveBeenCalledTimes(1);
  });

  it("captures before pending re-entry and binds each observer to its exact attempt", async () => {
    const store = storeWithNote(); store.dispatch(setNoteField({ id: ID, field: "content", value: "first" }));
    const first = captured(store); const unrelated = captured(store);
    const existing = query({ data: note(), error: null });
    const saved = query({ data: note({ content: "first", version: 8 }), error: null });
    const reread = query({ data: note({ content: "first", version: 8 }), error: null });
    const replay = query({ data: note({ content: "later", version: 9 }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(existing).mockReturnValueOnce(saved).mockReturnValueOnce(reread).mockReturnValueOnce(replay) });
    const reentries: NoteSaveObservation[] = [];
    const unsubscribe = store.subscribe(() => {
      unsubscribe();
      reentries.push(store.dispatch(saveReviewedNoteSnapshot({ permit: first.permit, currentSource: first.source })));
      reentries.push(store.dispatch(saveReviewedNoteSnapshot({ permit: unrelated.permit, currentSource: unrelated.source })));
      store.dispatch(setNoteField({ id: ID, field: "content", value: "later" }));
      reentries.push(store.dispatch(saveReviewedNoteSnapshot({ permit: first.permit, currentSource: prepared(store, "newer") })));
    });
    const observed = store.dispatch(saveReviewedNoteSnapshot({ permit: first.permit, currentSource: first.source }));
    const drain = store.dispatch(saveNote(ID));
    expect(reentries).toHaveLength(3);
    const result = await observed.result;
    expect(result).toMatchObject({ status: "physical-saved", attemptedFields: { physical: { content: "first" } }, receipt: { note: { content: "first", version: 8 } } });
    expect(await reentries[0].result).toBe(result);
    await expect(reentries[1].result).resolves.toMatchObject({ status: "refused", reason: "queue-busy" });
    await expect(reentries[2].result).resolves.toMatchObject({ status: "refused", reason: "source-changed" });
    await drain.unwrap();
    expect(saved.update.mock.calls[0][0]).toMatchObject({ content: "first" });
    expect(replay.update.mock.calls[0][0]).toMatchObject({ content: "later" });
    expect(store.getState().notes.notes[ID]).toMatchObject({ content: "later", version: 9, _dirty: false });
  });

  it("rebases a reviewed mine choice before capturing the next successful CAS", async () => {
    const store = storeWithNote(); store.dispatch(setNoteField({ id: ID, field: "content", value: "mine" }));
    const prior = query({ data: note(), error: null }); const missed = query({ data: null, error: null });
    const remote = note({ content: "theirs", version: 8 }); const winner = query({ data: remote, error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(prior).mockReturnValueOnce(missed).mockReturnValueOnce(winner) });
    const first = captured(store);
    await expect(store.dispatch(saveReviewedNoteSnapshot({ permit: first.permit, currentSource: first.source })).result).resolves.toMatchObject({ status: "refused", reason: "conflict" });
    store.dispatch(captureNoteConflictLiveBuffer({ id: ID, content: "mine" }));
    const decision = store.getState().notes.notes[ID]._conflictDecision;
    if (!decision) throw new Error("Expected actual CAS decision");
    await expect(store.dispatch(resolveNoteConflict({ noteId: ID, decisionId: decision.decisionId, reviewId: decision.reviewId, choice: "mine", proposedContent: "mine", getLiveBuffer: () => "mine" }))).resolves.toMatchObject({ status: "applied" });
    const next = captured(store);
    expect(next.source.editBase.version).toBe(8);
    expect(next.source.acknowledgedPhysicalSnapshot.content).toBe("theirs");
    const read = query({ data: remote, error: null }); const written = query({ data: note({ content: "mine", version: 9 }), error: null });
    schema.mockReturnValue({ from: jest.fn().mockReturnValueOnce(read).mockReturnValueOnce(written) });
    await expect(store.dispatch(saveReviewedNoteSnapshot({ permit: next.permit, currentSource: next.source })).result).resolves.toMatchObject({ status: "physical-saved", receipt: { note: { content: "mine", version: 9 } } });
    expect(written.update).toHaveBeenCalledTimes(1);
    expect(written.eq).toHaveBeenCalledWith("version", 8);
  });
});
