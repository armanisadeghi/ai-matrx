/**
 * Build the `matrx-user/notes` surface scope at trigger time.
 *
 * Returns a `() => SurfaceScopePayload` builder rather than a static object,
 * because the textarea's selection lives in the DOM (not React state) and the
 * caller wants the *current* selection at the moment the user clicks an
 * action — not a stale snapshot from the last render.
 *
 * Workspace-wide state (note metadata, folder tree, tab summaries, scope
 * assignments, find/replace) is read from the store at call time via
 * `store.getState()` — NOT via subscriptions — so the returned builder stays
 * referentially stable across unrelated store churn (the 2026-07 keystroke
 * freeze class: a builder that re-identifies per keystroke re-memoizes every
 * consumer downstream).
 *
 * Wire-up pattern (see `NoteContextMenuContent.executeAction`):
 *
 *   const buildSurfaceScope = useNotesSurfaceScope({ ... });
 *   ...
 *   await trigger(shortcutId, {
 *     scope: buildSurfaceScope(),
 *     sourceFeature: "notes",
 *     runtime: { surfaceName: "matrx-user/notes" },
 *   });
 */

import { useCallback } from "react";
import type { RefObject } from "react";

import { useAppSelector, useAppStore } from "@/lib/redux/hooks";
import type { SurfaceScopePayload } from "@/features/surfaces/types";
import {
  selectAllFolders,
  selectFindReplaceState,
  selectInstanceHistoryOpen,
  selectInstanceSplitNoteId,
  selectInstanceTabs,
  selectNoteById,
  selectNoteIsAutogenerated,
  selectNoteIsDirtyById,
  selectNoteScopeAssignments,
  selectNotesMap,
} from "@/features/notes/redux/selectors";
import type { EditorMode } from "@/features/notes/components/NoteEditorCore";
import {
  buildNotesEditorContextData,
  type NotesEditorFindReplace,
  type NotesEditorNotesMapEntry,
  type NotesEditorSharedAccess,
} from "@/features/notes/agent-context/buildNotesEditorContextData";

export interface UseNotesSurfaceScopeParams {
  /**
   * NotesView instance id (per-pane state, owns tabs + split note). Optional
   * for callsites outside the multi-tab Notes view (overlays, embedded
   * editors); when absent the scope reports an empty tab list and no split.
   */
  instanceId?: string;
  /** Id of the note the user has open in the active tab. */
  noteId: string;
  /** Live note body — usually the in-flight buffer (`localContent`). */
  content: string;
  /** Reference to the editor textarea — selection is read live from the DOM. */
  textareaRef: RefObject<HTMLTextAreaElement | null>;
  /** Active note's editor mode (plain / split / preview / wysiwyg / markdown-split). */
  editorMode: EditorMode;
}

/**
 * Returns a stable function that snapshots the Notes surface state and emits a
 * `SurfaceScopePayload` for `matrx-user/notes`. The function is stable across
 * renders for a given (instanceId, noteId) — the live values are pulled from
 * Redux + the textarea DOM at call time.
 */
export function useNotesSurfaceScope(
  params: UseNotesSurfaceScopeParams,
): () => SurfaceScopePayload {
  const { instanceId, noteId, content, textareaRef, editorMode } = params;

  // Empty-string sentinel for selectors when no instance is bound (overlay use).
  const instanceKey = instanceId ?? "";

  const store = useAppStore();
  const isDirty = useAppSelector(selectNoteIsDirtyById(noteId));
  const isAutogenerated = useAppSelector(selectNoteIsAutogenerated(noteId));
  const openTabs = useAppSelector(selectInstanceTabs(instanceKey));
  const splitNoteId = useAppSelector(selectInstanceSplitNoteId(instanceKey));

  return useCallback(() => {
    const ta = textareaRef.current;
    const text = ta?.value ?? content ?? "";
    const selectionStart = ta?.selectionStart ?? 0;
    const selectionEnd = ta?.selectionEnd ?? selectionStart;

    // Workspace-wide state, read at trigger time (not subscribed — see header).
    const state = store.getState();
    const record = noteId ? selectNoteById(noteId)(state) : undefined;
    const allFolders = selectAllFolders(state);
    // Project the store's NoteRecords down to the builder's lightweight map
    // entries (deleted_at → is_deleted so deleted notes never count as
    // folder peers).
    const notesMap: Record<string, NotesEditorNotesMapEntry> = {};
    for (const [id, rec] of Object.entries(selectNotesMap(state))) {
      notesMap[id] = {
        id,
        label: rec.label,
        folder_name: rec.folder_name,
        updated_at: rec.updated_at,
        is_deleted: rec.deleted_at != null,
      };
    }
    const scopeAssignments = selectNoteScopeAssignments(state)
      .filter((a) => a.entity_id === noteId)
      .map((a) => ({
        scope_id: a.scope_id,
        scope_name: a.scope_name,
        scope_type: a.scope_type,
      }));
    const historyOpen = selectInstanceHistoryOpen(instanceKey)(state);
    const fr = selectFindReplaceState(instanceKey)(state);
    const findReplace: NotesEditorFindReplace | null =
      fr && fr.isOpen
        ? {
            query: fr.query,
            scope: fr.scope,
            case_sensitive: fr.caseSensitive,
            use_regex: fr.useRegex,
            match_count: fr.matchCount,
          }
        : null;
    const sharedAccess: NotesEditorSharedAccess | null =
      record?._sharedWithMe && record._sharedMeta
        ? {
            permission_level: record._sharedMeta.permissionLevel,
            owner_email: record._sharedMeta.ownerEmail,
          }
        : null;

    return buildNotesEditorContextData({
      noteId,
      content: text,
      selectionStart,
      selectionEnd,
      editorMode,
      noteRecord: record
        ? {
            label: record.label,
            folder_name: record.folder_name,
            tags: record.tags,
            visibility: record.visibility,
            updated_at: record.updated_at,
          }
        : null,
      isDirty,
      isAutogenerated,
      openTabs: openTabs ?? [],
      splitNoteId,
      allFolders,
      notesMap,
      sharedAccess,
      scopeAssignments,
      historyOpen: historyOpen ?? false,
      findReplace,
    }) as SurfaceScopePayload;
  }, [
    store,
    textareaRef,
    content,
    noteId,
    instanceKey,
    editorMode,
    isDirty,
    isAutogenerated,
    openTabs,
    splitNoteId,
  ]);
}
