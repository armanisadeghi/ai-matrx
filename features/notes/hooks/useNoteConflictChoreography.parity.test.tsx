const ID = "33333333-3333-4333-8333-333333333333";
const ORG = "11111111-1111-4111-8111-111111111111";
const ACTOR = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";

const row = (overrides: Partial<Note> = {}): Note => ({
  id: ID, organization_id: ORG, version: 4, content: "base", label: "N",
  folder_name: null, folder_id: null, tags: [], metadata: {}, visibility: "personal",
  position: 0, project_id: null, task_id: null, created_at: "2026-09-15T00:00:00.000Z",
  created_by: ACTOR, updated_at: "2026-09-15T00:00:00.000Z", updated_by: ACTOR,
  deleted_at: null, content_hash: null, file_path: null, last_device_id: null,
  custom_fields: {},
  sync_version: 0, ...overrides,
});

const dispatched: string[] = [];

/** Plain actions only — thunks are consumed by the thunk middleware first. */
const recordActionTypes: Middleware = () => (next) => (action) => {
  if (isAction(action)) dispatched.push(action.type);
  return next(action);
};

function makeStore() {
  return configureStore({
    reducer: {
      notes: notesReducer,
      userAuth: (state = { id: ACTOR, authReady: true }) => state,
      // The real app-context reducer: the editors' ShareModal reads the personal org from it.
      appContext: appContextReducer,
    },
    middleware: (gdm) =>
      gdm({ serializableCheck: false, immutableCheck: false }).concat(recordActionTypes),
  });
}
type Store = ReturnType<typeof makeStore>;
type State = ReturnType<Store["getState"]>;

/** A note the user has edited, with a real CAS decision recorded against it. */
function seed(store: Store) {
  store.dispatch(upsertNoteFromServer({ note: row(), fetchStatus: "full" }));
  store.dispatch(setNoteField({ id: ID, field: "content", value: "mine" }));
  store.dispatch(
    recordNoteConflict({
      id: ID,
      expectedVersion: 4,
      currentVersion: 5,
      currentRow: row({ content: "theirs", version: 5, updated_at: "2026-09-15T00:01:00.000Z" }),
      sentSnapshot: { content: "mine" },
      actorId: ACTOR,
      organizationId: ORG,
      decisionId: "decision-1",
      reviewId: "review-1",
    }),
  );
}

function MobileHost() {
  const record = useSelector((state: State) => state.notes.notes[ID]);
  return <MobileNoteEditor note={record as unknown as Note} editorMode="plain" onBack={() => {}} />;
}

async function runKeepMine(editor: "desktop" | "mobile") {
  const store = makeStore();
  seed(store);
  const container = document.createElement("div");
  document.body.appendChild(container);
  const root = createRoot(container);
  await act(async () => {
    root.render(
      <Provider store={store}>
        {editor === "desktop" ? (
          <NotesInstanceProvider value="parity">
            <NoteContentEditor noteId={ID} />
          </NotesInstanceProvider>
        ) : (
          <MobileHost />
        )}
      </Provider>,
    );
  });
  await act(async () => {
    await Promise.resolve();
  });
  const keepMine = [...container.querySelectorAll("button"), ...document.querySelectorAll("button")].find(
    (button) => button.textContent === "Keep Mine",
  );
  if (!keepMine) throw new Error(`${editor}: the conflict window rendered no Keep Mine button`);
  expect(keepMine.disabled).toBe(false);

  dispatched.length = 0;
  await act(async () => {
    keepMine.click();
    await new Promise((resolve) => setTimeout(resolve, 10));
  });
  const sequence = [...dispatched];
  // The coordinator's ledger is keyed by the getState FUNCTION the mounted
  // hook received from the Provider — this exact reference. Only the static
  // type widens (this harness mounts two reducers, not the whole RootState).
  const getRootState = store.getState as unknown as () => RootState;
  const outcomes = readReviewCommandOutcomes(getRootState).map((outcome) => ({
    noteId: outcome.noteId, decisionId: outcome.decisionId, reviewId: outcome.reviewId,
  }));
  await act(async () => root.unmount());
  container.remove();
  return { sequence, outcomes, content: store.getState().notes.notes[ID].content };
}

beforeAll(() => {
  enableMapSet();
  (globalThis as typeof globalThis & { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
  Object.defineProperty(window, "matchMedia", {
    value: () => ({ matches: false, addEventListener: () => {}, removeEventListener: () => {} }),
    configurable: true,
  });
});

beforeEach(() => {
  dispatched.length = 0;
  getSession.mockResolvedValue({ data: { session: { user: { id: ACTOR } } }, error: null });
  getUserId.mockReturnValue(ACTOR);
  // The physical write is not what this test judges; it only has to be the
  // SAME boundary for both editors.
  persistNoteUpdate.mockRejectedValue(new Error("network unavailable"));
});

describe("both editors drive one conflict choreography", () => {
  it("Keep Mine on a phone produces the desktop dispatch sequence and goes through the reviewed-save coordinator", async () => {
    const desktop = await runKeepMine("desktop");
    const mobile = await runKeepMine("mobile");

    // The decision itself was applied, on both surfaces.
    expect(desktop.sequence).toContain("notes/beginRetainedNoteConflictCommand");
    expect(desktop.sequence).toContain("notes/applyNoteConflictResolution");
    expect(desktop.content).toBe("mine");
    expect(mobile.content).toBe("mine");

    // THE POINT: the same actions, in the same order — no mobile-only
    // resolve-then-`saveNote` tail.
    expect(mobile.sequence).toEqual(desktop.sequence);

    // …and the reviewed package reached the coordinator, which owns the
    // receipt for the physical write.
    expect(mobile.outcomes).toEqual([{ noteId: ID, decisionId: "decision-1", reviewId: "review-1" }]);
    expect(mobile.outcomes).toEqual(desktop.outcomes);
  });
});
