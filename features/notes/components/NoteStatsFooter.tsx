"use client";

// NoteStatsFooter — the ONLY place notes surfaces show save status + live
// content metrics. It renders INSIDE NoteMetadataBar (the note's one bottom
// row) — no host mounts it on its own.
//
// Quiet when all is well (Docs, Bear, iA Writer): "Saved" in muted ink with a
// check; color only when something needs the writer (unsaved, failed). The
// status never clips; counts step down with the row's width (words from 22rem,
// characters and read time from 36rem).

import { useAppSelector } from "@/lib/redux/hooks";
import {
  selectNoteById,
  selectNoteContent,
  selectNoteIsDirtyById,
  selectNoteIsSavingById,
} from "../redux/selectors";
import { noteWorkingCopy } from "../utils/noteLiveContent";
import { selectWorkingCopyValue } from "@/lib/working-copy/workingCopySlice";
import { useMemo } from "react";
import { measureText } from "@ai-matrx/rich-editor/core/text-metrics";
import { formatCount } from "@ai-matrx/kit/format";
import { useDebounce } from "@ai-matrx/kit/hooks";
import { cn } from "@/lib/utils";
import { ErrorAlchemyMenu } from "@/components/errors/ErrorAlchemyMenu";
import { Check } from "lucide-react";

export interface NoteStatsFooterProps {
  noteId: string;
  className?: string;
}

export function NoteStatsFooter({ noteId, className }: NoteStatsFooterProps) {
  const reduxContent = useAppSelector(selectNoteContent(noteId)) ?? "";
  const liveContent = useAppSelector((state) => selectWorkingCopyValue(state, noteWorkingCopy.key(noteId)));
  const content = liveContent ?? reduxContent;
  // What a writer counts (Docs, Bear, iA Writer): words · characters · read time, of the
  // prose a reader reads (markdown markers and protected blocks are not words). Measured
  // a beat behind typing — never a full tokenize per keystroke.
  const settled = useDebounce(content, 250);
  const metrics = useMemo(() => measureText(settled), [settled]);
  const words = `${formatCount(metrics.words)} ${metrics.words === 1 ? "word" : "words"}`;
  const chars = `${formatCount(metrics.characters)} chars`;
  const read = `${metrics.readingMinutes} min`;

  const isDirty = useAppSelector(selectNoteIsDirtyById(noteId));
  const isSaving = useAppSelector(selectNoteIsSavingById(noteId));
  const note = useAppSelector(selectNoteById(noteId));

  const saveError =
    note?._error && note._error !== "conflict" ? note._error : null;
  const saveStatus = saveError
    ? "Save failed"
    : isSaving
      ? "Saving…"
      : isDirty
        ? "Unsaved"
        : note?._isAutogenerated
          ? "Draft"
          : "Saved";
  const statusColor = saveError
    ? "text-destructive"
    : isSaving
      ? "text-muted-foreground"
      : isDirty
        ? "text-warning"
        : "text-muted-foreground";

  const saved = saveStatus === "Saved";

  return (
    <div className={cn("flex min-w-0 items-center gap-2", className)}>
      <span
        className={cn("flex shrink-0 items-center gap-0.5 text-xs", statusColor)}
        title={saveError ?? (note?._isAutogenerated ? "Start typing to save" : undefined)}
      >
        {saved && <Check className="h-3 w-3" aria-hidden />}
        {saveStatus}
        {/* Only a real save failure carries the error menu. */}
        {saveError && <ErrorAlchemyMenu error={saveError} />}
      </span>
      <span
        className="hidden truncate text-xs tabular-nums text-muted-foreground @[22rem]/notemeta:inline"
        data-note-metrics=""
        title={`${words} · ${chars} · ${metrics.readingMinutes} min read`}
      >
        {words}
        <span className="hidden @[36rem]/notemeta:inline">
          {" "}· {chars} · {read}
        </span>
      </span>
    </div>
  );
}
