"use client";

// Layer 4: NoteTabBar — VSCode-style compact tab row.
// Matches the SSR workspace tab bar design exactly.
// Props: instanceId only. Everything from Redux.

import React, { useRef, useEffect, useCallback, useState } from "react";
import { Plus } from "lucide-react";
import { useAppDispatch, useAppSelector } from "@/lib/redux/hooks";
import {
  addInstanceTab,
  setInstanceActiveTab,
  reorderInstanceTabs,
  createAutogeneratedNote,
  setSplitNote,
  markTabInteraction,
  moveActiveTabToFront,
} from "../redux/slice";
import { TAB_AUTO_MOVE_IDLE_MS } from "../redux/notes.types";
import { fetchNoteContent } from "../redux/thunks";
import {
  selectInstanceTabs,
  selectInstanceActiveTab,
  selectInstanceSplitNoteId,
  selectInstanceTabInteractionAt,
} from "../redux/selectors";
import { NoteTabItem } from "./NoteTabItem";
import { SplitNotePicker } from "./SplitNotePicker";
import { orderTabsActiveFirst } from "../utils/tabUrlOrder";
import { cn } from "@/lib/utils";

interface NoteTabBarProps {
  instanceId: string;
  /**
   * When true (default), hydrate from and write `?tabs=&active=&split=` URL
   * params. Floating Notes windows must pass false — otherwise every window
   * fights over the same global URL and steals each other's tabs.
   */
  syncUrl?: boolean;
}

export function NoteTabBar({ instanceId, syncUrl = true }: NoteTabBarProps) {
  const dispatch = useAppDispatch();

  const openTabs = useAppSelector(selectInstanceTabs(instanceId));
  const activeTabId = useAppSelector(selectInstanceActiveTab(instanceId));
  const splitNoteId = useAppSelector(selectInstanceSplitNoteId(instanceId));
  const tabInteractionAt = useAppSelector(
    selectInstanceTabInteractionAt(instanceId),
  );
  const userId = useAppSelector((s) => s.userAuth?.id);

  const scrollRef = useRef<HTMLDivElement>(null);
  const hydratedRef = useRef(false);
  const lastPushedUrlRef = useRef("");

  // ── DnD state (local only) ────────────────────────────────────────
  const [draggedTab, setDraggedTab] = useState<string | null>(null);
  const [dragOverTab, setDragOverTab] = useState<string | null>(null);

  // ── URL → Redux: hydrate ONCE on mount ────────────────────────────
  // Active-first order is the contract: `?active=` wins, and `?tabs=` is
  // rewritten with the focused note first so reloads never lose focus.
  useEffect(() => {
    if (!syncUrl) {
      hydratedRef.current = true;
      return;
    }
    if (hydratedRef.current) return;
    hydratedRef.current = true;

    const params = new URLSearchParams(window.location.search);
    const tabsParam = params.get("tabs");
    if (!tabsParam) return;

    const tabIds = tabsParam.split(",").filter(Boolean);
    if (tabIds.length === 0) return;

    const activeParam = params.get("active");
    const activeId =
      activeParam && tabIds.includes(activeParam) ? activeParam : tabIds[0];
    const ordered = orderTabsActiveFirst(tabIds, activeId);

    ordered.forEach((id) => {
      dispatch(addInstanceTab({ instanceId, noteId: id }));
      dispatch(fetchNoteContent(id));
    });
    dispatch(reorderInstanceTabs({ instanceId, tabs: ordered }));
    dispatch(setInstanceActiveTab({ instanceId, noteId: activeId }));

    const splitParam = params.get("split");
    if (splitParam) {
      dispatch(setSplitNote({ instanceId, noteId: splitParam }));
      dispatch(fetchNoteContent(splitParam));
    }
  }, [dispatch, instanceId, syncUrl]);

  // ── Redux → URL: push state (active first in ?tabs=) ──────────────
  useEffect(() => {
    if (!syncUrl) return;
    if (!hydratedRef.current) return;
    // Child effects run before parent effects: on a fresh mount this writer
    // fires BEFORE NotesView's registerInstance, sees `openTabs === undefined`
    // (instance not in the store yet), and would transiently wipe
    // `?tabs=&active=` from the URL — a reload in that window loses the whole
    // workspace. An empty ARRAY (all tabs closed) is a real state and must
    // still sync; only the not-yet-registered undefined is skipped.
    if (openTabs === undefined) return;

    const params = new URLSearchParams(window.location.search);
    const orderedTabs = orderTabsActiveFirst(openTabs ?? [], activeTabId);

    if (orderedTabs.length > 0) {
      params.set("tabs", orderedTabs.join(","));
    } else {
      params.delete("tabs");
    }

    if (activeTabId) {
      params.set("active", activeTabId);
    } else {
      params.delete("active");
    }

    if (splitNoteId) {
      params.set("split", splitNoteId);
    } else {
      params.delete("split");
    }

    const newUrl = `${window.location.pathname}?${params.toString()}`;
    if (newUrl !== lastPushedUrlRef.current) {
      lastPushedUrlRef.current = newUrl;
      window.history.replaceState(null, "", newUrl);
    }
  }, [openTabs, activeTabId, splitNoteId, syncUrl]);

  // ── New tab ────────────────────────────────────────────────────────
  // `createAutogeneratedNote` already inserts at position 0 and bumps
  // the interaction timestamp inside the reducer.
  const handleNewTab = useCallback(() => {
    if (!userId) return;
    const id = crypto.randomUUID();
    dispatch(
      createAutogeneratedNote({ id, userId, folder: "Draft", instanceId }),
    );
  }, [dispatch, userId, instanceId]);

  // ── DnD reorder ────────────────────────────────────────────────────
  const handleDrop = useCallback(
    (e: React.DragEvent) => {
      e.preventDefault();
      const fromId = e.dataTransfer.getData("text/plain");
      if (!fromId || !openTabs || !dragOverTab) return;
      if (fromId === dragOverTab) return;

      const filtered = openTabs.filter((t) => t !== fromId);
      const dropIdx = filtered.indexOf(dragOverTab);
      if (dropIdx === -1) return;
      filtered.splice(dropIdx, 0, fromId);
      dispatch(markTabInteraction({ instanceId }));
      dispatch(reorderInstanceTabs({ instanceId, tabs: filtered }));
      setDraggedTab(null);
      setDragOverTab(null);
    },
    [dispatch, instanceId, openTabs, dragOverTab],
  );

  // ── Auto-scroll active tab into view ──────────────────────────────
  // Title-anchored scroll: the title (left edge of the tab) is always the
  // priority. If the active tab is wider than the scroll area, we never
  // scroll past its left edge — so the title stays visible even when the
  // action buttons on the right overflow.
  useEffect(() => {
    if (!scrollRef.current || !activeTabId) return;
    const container = scrollRef.current;
    const el = container.querySelector<HTMLElement>(`[data-active="true"]`);
    if (!el) return;

    const containerRect = container.getBoundingClientRect();
    const elRect = el.getBoundingClientRect();
    const leftDelta = elRect.left - containerRect.left;
    const rightDelta = elRect.right - containerRect.right;

    let scrollBy = 0;
    if (leftDelta < 0) {
      // Title is hidden off the left — scroll left to bring it back into view.
      scrollBy = leftDelta;
    } else if (rightDelta > 0) {
      // Right edge is offscreen — scroll right, but never past the title.
      // Cap by leftDelta so the title is never pushed offscreen to the left.
      scrollBy = Math.min(rightDelta, leftDelta);
    }

    if (scrollBy !== 0) {
      container.scrollBy({ left: scrollBy, behavior: "smooth" });
    }
  }, [activeTabId]);

  // ── Idle auto-move: active tab → position 0 ───────────────────────
  // Once the user has been quiet about tabs for `TAB_AUTO_MOVE_IDLE_MS`,
  // pull the active tab to the front so the most-recently-used note
  // lives on the left edge. Any tab-direct action (click, rename,
  // drag, modal open, etc.) bumps `tabInteractionAt` and resets this
  // timer, so the move never happens mid-interaction or while the
  // user is just clicking around between tabs.
  //
  // `tabInteractionAt === null` means there's been no user interaction
  // yet (fresh mount, URL hydration) — in that case we leave the order
  // alone so the persisted layout is preserved.
  useEffect(() => {
    if (tabInteractionAt === null) return undefined;
    if (!activeTabId || !openTabs || openTabs.length < 2) return undefined;
    if (openTabs[0] === activeTabId) return undefined;

    const elapsed = Date.now() - tabInteractionAt;
    const remaining = Math.max(0, TAB_AUTO_MOVE_IDLE_MS - elapsed);

    const timer = setTimeout(() => {
      dispatch(moveActiveTabToFront({ instanceId }));
    }, remaining);

    return () => clearTimeout(timer);
  }, [activeTabId, openTabs, tabInteractionAt, instanceId, dispatch]);

  if (!openTabs || openTabs.length === 0) return null;

  // Per-tab wrapper (drag handlers + drop-target styling). Shared between the
  // pinned active tab and the scrolling tabs so behaviour stays identical.
  const renderTab = (tabId: string) => (
    <div
      key={tabId}
      onDragOver={(e) => {
        if (!draggedTab || draggedTab === tabId) return;
        e.preventDefault();
        setDragOverTab(tabId);
      }}
      onDragStart={() => {
        dispatch(markTabInteraction({ instanceId }));
        setDraggedTab(tabId);
      }}
      onDragEnd={() => {
        setDraggedTab(null);
        setDragOverTab(null);
      }}
      className={cn(
        "flex items-stretch",
        draggedTab === tabId && "opacity-40",
        dragOverTab === tabId && "border-l-2 border-primary",
      )}
    >
      <NoteTabItem noteId={tabId} instanceId={instanceId} />
    </div>
  );

  // The active tab lives in the pinned cluster (never scrolls); everything
  // else scrolls in the region to its right — so other tabs start where the
  // active tab ends instead of sliding behind it.
  const scrollingTabs = activeTabId
    ? openTabs.filter((t) => t !== activeTabId)
    : openTabs;

  return (
    <div
      className="notes-tab-bar-scroll flex items-stretch h-8 min-h-[2rem] overflow-hidden border-b border-border shrink-0"
      data-surface-value="open_note_ids"
      role="tablist"
      aria-label="Open notes"
      onDragOver={(e) => {
        e.preventDefault();
        e.dataTransfer.dropEffect = "move";
      }}
      onDrop={handleDrop}
    >
      {/* Pinned cluster: new-note button + active tab. Stays put while the
          rest of the strip scrolls underneath the scrolling region. */}
      <div className="flex items-stretch shrink-0 bg-background z-10">
        <button
          className="flex items-center justify-center w-8 h-8 shrink-0 self-stretch border-r border-border/60 cursor-pointer transition-colors text-muted-foreground hover:bg-accent hover:text-foreground [&_svg]:w-3.5 [&_svg]:h-3.5"
          onClick={handleNewTab}
          title="New Note"
        >
          <Plus />
        </button>
        {activeTabId && renderTab(activeTabId)}
      </div>

      {/* Scrolling region: the remaining (non-active) tabs. */}
      <div
        ref={scrollRef}
        className="flex items-stretch flex-1 min-w-0 overflow-x-auto overflow-y-hidden h-full"
      >
        {scrollingTabs.map(renderTab)}

        {/* Split view button */}
        {activeTabId && !splitNoteId && (
          <div className="shrink-0 self-center mx-0.5">
            <SplitNotePicker />
          </div>
        )}
      </div>
    </div>
  );
}
