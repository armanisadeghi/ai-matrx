/** "admin's Workspace" → "AW"; "Castellano & Reyes, LLP" → "CRL". */
function orgInitials(name: string): string {
  const letters = name
    .split(/[\s,&/-]+/)
    .map((word) => word.replace(/[^\p{L}\p{N}]/gu, ""))
    .filter(Boolean)
    .map((word) => word[0]!.toUpperCase());
  return letters.slice(0, 3).join("") || name.slice(0, 2);
}

