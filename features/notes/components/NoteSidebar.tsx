// Page size for the collapsible "Recent" section at the top of "default" mode.
// The section starts showing this many and grows by this step on "Show more".
const RECENT_PAGE_SIZE = 10;

interface NoteSidebarProps {
  instanceId: string;
}

export function NoteSidebar({ instanceId }: NoteSidebarProps) {
  const dispatch = useAppDispatch();
  const { id: userId } = useAppSelector(selectUser);
  const openKnowledge = useOpenNoteKnowledgePanel();

  // ── Redux state (memoized selectors — no new references) ──────────
  const allNotes = useAppSelector(selectAllNotesList);
  const activeTabId = useAppSelector(selectInstanceActiveTab(instanceId));
  const openTabIds = useAppSelector(selectInstanceTabs(instanceId));
  const listStatus = useAppSelector(selectNotesListStatus);
  const allFolders = useAppSelector(selectAllFolders);
  const scopeGrouped = useAppSelector(selectNotesGroupedByScope);
  const scopesLoaded = useAppSelector(selectNoteScopesLoaded);

  // ── Active context for filtering + grouping labels ──────────────────
  const activeOrgId = useAppSelector(selectOrganizationId);
  const personalOrgId = useAppSelector(selectPersonalOrganizationId);
  const activeProjectId = useAppSelector(selectProjectId);
  const activeTaskId = useAppSelector(selectTaskId);
  const scopeSelections = useAppSelector(selectScopeSelectionsContext);
  const orgName = useAppSelector(selectOrganizationName);
  const projName = useAppSelector(selectProjectName);
  const taskName = useAppSelector(selectTaskName);

  // ── Scope-filtered note IDs (fetched when scopes change) ──────────
  const activeScopeIds = useMemo(
    () => Object.values(scopeSelections).filter(Boolean) as string[],
    [scopeSelections],
  );
  const { entityIds: scopeFilteredNoteIds } = useEntitiesByScopes({
    scopeIds: activeScopeIds,
    entityType: "note",
    matchAll: false,
  });

  // ── Filter notes by active context (org + scopes + project + task) ─
  //
  // Org rule (see `noteMatchesActiveOrgContext`): active org OR personal org.
  // Historical notes were stamped onto the personal org at retrofit time, so
  // a strict active-org-only filter zeros every folder count whenever the
  // user is working in a company org. Other company orgs stay excluded.
  // Null-org ("homeless") notes are hidden by default with a banner + toggle.
  const [includeHomeless, setIncludeHomeless] = useState(false);
  const [claimingHomeless, setClaimingHomeless] = useState(false);
  const { contextFiltered, homelessCount } = useMemo(() => {
    let result = allNotes;
    let homeless: typeof allNotes = [];
    if (activeOrgId) {
      homeless = result.filter((n) => n.organization_id == null);
      result = result.filter((n) =>
        noteMatchesActiveOrgContext(n, activeOrgId, personalOrgId),
      );
    }
    if (scopeFilteredNoteIds)
      result = result.filter((n) => scopeFilteredNoteIds.has(n.id));
    if (activeProjectId) {
      result = result.filter((n) => n.project_id === activeProjectId);
      homeless = homeless.filter(
        (n) => n.project_id == null || n.project_id === activeProjectId,
      );
    }
    if (activeTaskId) {
      result = result.filter((n) => n.task_id === activeTaskId);
      homeless = homeless.filter(
        (n) => n.task_id == null || n.task_id === activeTaskId,
      );
    }
    return {
      contextFiltered: includeHomeless ? [...result, ...homeless] : result,
      homelessCount: homeless.length,
    };
  }, [
    allNotes,
    activeOrgId,
    personalOrgId,
    scopeFilteredNoteIds,
    activeProjectId,
    activeTaskId,
    includeHomeless,
  ]);

  // ── Local UI state ─────────────────────────────────────────────────
  const [searchQuery, setSearchQuery] = useState("");
  const [expandedFolders, setExpandedFolders] = useState<Set<string>>(() => {
    if (!activeTabId) return new Set<string>();
    const activeNote = allNotes.find((n) => n.id === activeTabId);
    if (activeNote?.folder_name) return new Set([activeNote.folder_name]);
    return new Set<string>();
  });
  const [sortField, setSortField] = useState<NoteSortField>("updated_at");
  const [sortOrder, setSortOrder] = useState<NoteSortOrder>("desc");
  const [groupBy, setGroupBy] = useState<NoteGroupBy | "recent" | "default">(
    "default",
  );
  const [trashOpen, setTrashOpen] = useState(false);
  const trashFetchedRef = useRef(false);
  const deletedNotes = useAppSelector(selectDeletedNotesList);
  const sharedNotes = useAppSelector(selectSharedWithMeNotes);
  const [sharedOpen, setSharedOpen] = useState(true);
  const [groupByDropdown, setGroupByDropdown] = useState(false);

  // Collapsible "Recent" section (default mode) — open by default, paginated.
  const [recentOpen, setRecentOpen] = useState(true);
  const [recentVisibleCount, setRecentVisibleCount] = useState(RECENT_PAGE_SIZE);

  // ── Fetch scope assignments when switching to scope mode ────────────
  useEffect(() => {
    if (groupBy === "scope" && !scopesLoaded) {
      dispatch(fetchAllNoteScopes());
    }
  }, [dispatch, groupBy, scopesLoaded]);

  // Bulk-selection mode — checkboxes replace the leading icon on every row
  // and a NoteSidebarBulkBar (move / knowledge / export / share / delete)
  // replaces the "New Note / New Folder" bar once something is selected.
  const [selectionMode, setSelectionMode] = useState(false);
  const [selectedIds, setSelectedIds] = useState<Set<string>>(new Set());

  // DnD state
  const [draggedNoteId, setDraggedNoteId] = useState<string | null>(null);
  const [dropTargetFolder, setDropTargetFolder] = useState<string | null>(null);

  // Dialog state
  const [createFolderOpen, setCreateFolderOpen] = useState(false);
  const [renameFolderTarget, setRenameFolderTarget] = useState<string | null>(
    null,
  );

  // Refs
  const folderTreeRef = useRef<HTMLDivElement>(null);
  const searchInputRef = useRef<HTMLInputElement>(null);
  const searchFocusedRef = useRef(false);

  // ── Reveal + center the active note ────────────────────────────────
  // ONE effect keyed on the active tab (and the grouping mode, which changes
  // where the row lives): expand the folder that holds it, open the "Shared
  // with me" section if it lives there, then smooth-scroll it to the vertical
  // center of the list. Deliberately does NOT depend on `allNotes` — note-list
  // churn (autosave, realtime) must never re-scroll the sidebar; only a real
  // active-tab change does. `allNotes`/`sharedNotes` are read through refs so
  // the lookup stays current without widening the dependency set.
  const allNotesRef = useRef(allNotes);
  allNotesRef.current = allNotes;
  const sharedNotesRef = useRef(sharedNotes);
  sharedNotesRef.current = sharedNotes;

  useEffect(() => {
    if (!activeTabId) return undefined;

    const isShared = sharedNotesRef.current.some((n) => n.id === activeTabId);
    if (isShared) {
      // Ensure the shared section is open so the active row can be seen.
      setSharedOpen(true);
    } else if (groupBy === "folder" || groupBy === "default") {
      const note = allNotesRef.current.find((n) => n.id === activeTabId);
      const folderName = note?.folder_name || "Uncategorized";
      setExpandedFolders((prev) => {
        if (prev.has(folderName)) return prev;
        const next = new Set(prev);
        next.add(folderName);
        return next;
      });
    }

    // Scroll after the DOM settles. A just-triggered folder expansion paints
    // on a later frame, so poll a few frames until the row exists, then center
    // it within the list container only (never scrolls ancestors/the page).
    let raf = 0;
    let tries = 0;
    const tryScroll = () => {
      const container = folderTreeRef.current;
      if (!container) return;
      const el = container.querySelector<HTMLElement>(
        `[data-note-id="${activeTabId}"]`,
      );
      if (el) {
        const cRect = container.getBoundingClientRect();
        const eRect = el.getBoundingClientRect();
        const rowCenter =
          eRect.top - cRect.top + container.scrollTop + eRect.height / 2;
        // Clamp to [0, max]: a row too near the top can't be centered and so
        // stays ABOVE center (never below it), exactly as required.
        const target = Math.max(
          0,
          Math.min(
            rowCenter - container.clientHeight / 2,
            container.scrollHeight - container.clientHeight,
          ),
        );
        container.scrollTo({ top: target, behavior: "smooth" });
      } else if (tries++ < 12) {
        raf = requestAnimationFrame(tryScroll);
      }
    };
    raf = requestAnimationFrame(tryScroll);
    return () => cancelAnimationFrame(raf);
  }, [activeTabId, groupBy]);

  // ── Auto-scroll first search result into view ─────────────────────
  useEffect(() => {
    if (!searchQuery || !folderTreeRef.current) return undefined;
    // Small delay to let the filtered list render
    const timer = setTimeout(() => {
      const firstNote = folderTreeRef.current?.querySelector("[data-note-id]");
      if (firstNote) {
        firstNote.scrollIntoView({ behavior: "smooth", block: "nearest" });
      }
    }, 50);
    return () => clearTimeout(timer);
  }, [searchQuery]);

  // ── Derived data ───────────────────────────────────────────────────
  // Folder list MUST come from the same note set as the counts
  // (`contextFiltered`). Building it from `allNotes` left empty folders
  // (count 0) for notes that the org filter had already excluded.
  const folders = useMemo(() => {
    const result = folderNamesForNotes(contextFiltered);
    const hasOrphans = contextFiltered.some((n) => !n.folder_name);
    if (hasOrphans && !result.includes("Uncategorized")) {
      result.push("Uncategorized");
    }
    return result;
  }, [contextFiltered]);

  // Filter notes by search (operates on context-filtered set)
  const filteredNotes = useMemo(() => {
    if (!searchQuery) return contextFiltered;
    const q = searchQuery.toLowerCase();
    return contextFiltered.filter(
      (n) =>
        n.label.toLowerCase().includes(q) ||
        n.content?.toLowerCase().includes(q) ||
        n.tags?.some((t) => t.toLowerCase().includes(q)) ||
        idMatchesQuery(n, q),
    );
  }, [contextFiltered, searchQuery]);

  // Sort function
  const sortNotes = useCallback(
    (notes: NoteRecord[]) => {
      return [...notes].sort((a, b) => {
        let cmp = 0;
        if (sortField === "label") {
          cmp = a.label.localeCompare(b.label);
        } else if (sortField === "created_at") {
          cmp = (a.created_at ?? "").localeCompare(b.created_at ?? "");
        } else {
          cmp = (a.updated_at ?? "").localeCompare(b.updated_at ?? "");
        }
        return sortOrder === "desc" ? -cmp : cmp;
      });
    },
    [sortField, sortOrder],
  );

  // Group notes by selected mode
  const groupedNotes = useMemo(() => {
    const map = new Map<string, NoteRecord[]>();

    if (groupBy === "recent") {
      map.set("__all__", sortNotes(filteredNotes));
      return map;
    }

    // Scope grouping uses the pre-computed selector (many-to-many)
    if (groupBy === "scope") {
      // Apply search filter to the scope-grouped results
      const searchIds = searchQuery
        ? new Set(filteredNotes.map((n) => n.id))
        : null;
      for (const [key, notes] of scopeGrouped) {
        const filtered = searchIds
          ? notes.filter((n) => searchIds.has(n.id))
          : notes;
        if (filtered.length > 0) {
          map.set(key, sortNotes(filtered));
        }
      }
      return map;
    }

    for (const n of filteredNotes) {
      let key: string;
      switch (groupBy) {
        case "organization":
          key = n.organization_id || "__none__";
          break;
        case "project":
          key = n.project_id || "__none__";
          break;
        case "task":
          key = n.task_id || "__none__";
          break;
        case "default":
        default: // "folder"
          key = n.folder_name || "Uncategorized";
          break;
      }
      let bucket = map.get(key);
      if (!bucket) {
        bucket = [];
        map.set(key, bucket);
      }
      bucket.push(n);
    }

    // Sort each group
    for (const [key, notes] of map) {
      map.set(key, sortNotes(notes));
    }

    return map;
  }, [filteredNotes, groupBy, sortNotes]);

  // Recent notes for "default" mode, always by updated_at desc (independent of
  // the user's sort field/order, which applies to folder groups). Fully sorted
  // here; the render slices to `recentVisibleCount` for pagination.
  const recentSorted = useMemo(() => {
    if (groupBy !== "default") return [] as NoteRecord[];
    return [...filteredNotes].sort((a, b) =>
      (b.updated_at ?? "").localeCompare(a.updated_at ?? ""),
    );
  }, [groupBy, filteredNotes]);

  // Get group labels for display
  const getGroupLabel = useCallback(
    (key: string): string => {
      if (key === "__all__") return "All Notes";
      if (key === "__none__" || key === "Unassigned") return "Unassigned";
      if (groupBy === "folder" || groupBy === "default") return key;
      // Scope keys are already human-readable: "Department: SEO"
      if (groupBy === "scope") return key;
      // For org/project/task, the key is a UUID — show context name if matching
      if (groupBy === "organization" && orgName) return orgName;
      if (groupBy === "project" && projName) return projName;
      if (groupBy === "task" && taskName) return taskName;
      return key.slice(0, 8) + "...";
    },
    [groupBy, orgName, projName, taskName],
  );

  // Ordered group keys
  const groupKeys = useMemo(() => {
    if (groupBy === "folder" || groupBy === "default") return folders;
    if (groupBy === "recent") return ["__all__"];
    if (groupBy === "scope") {
      // Sort scope groups alphabetically, "Unassigned" last
      const keys = Array.from(groupedNotes.keys());
      return keys.sort((a, b) => {
        if (a === "Unassigned") return 1;
        if (b === "Unassigned") return -1;
        return a.localeCompare(b);
      });
    }
    // For hierarchy modes, show assigned first, then unassigned
    const keys = Array.from(groupedNotes.keys());
    return keys.sort((a, b) => {
      if (a === "__none__") return 1;
      if (b === "__none__") return -1;
      return 0;
    });
  }, [groupBy, folders, groupedNotes]);

  // ── Bulk-selection handlers ─────────────────────────────────────────
  const selectedNoteRecords = useMemo(
    () => allNotes.filter((n) => selectedIds.has(n.id)),
    [allNotes, selectedIds],
  );

  const toggleSelect = useCallback((noteId: string) => {
    setSelectedIds((prev) => {
      const next = new Set(prev);
      if (next.has(noteId)) next.delete(noteId);
      else next.add(noteId);
      return next;
    });
  }, []);

  const exitSelectionMode = useCallback(() => {
    setSelectionMode(false);
    setSelectedIds(new Set());
  }, []);

  const toggleSelectionMode = useCallback(() => {
    setSelectionMode((prev) => {
      if (prev) setSelectedIds(new Set());
      return !prev;
    });
  }, []);

  // ── Handlers ───────────────────────────────────────────────────────
  const toggleFolder = useCallback((folder: string) => {
    setExpandedFolders((prev) => {
      const next = new Set(prev);
      if (next.has(folder)) next.delete(folder);
      else next.add(folder);
      return next;
    });
  }, []);

  // ── DnD handlers ──────────────────────────────────────────────────
  const handleNoteDragStart = useCallback(
    (e: React.DragEvent, noteId: string) => {
      e.dataTransfer.effectAllowed = "move";
      e.dataTransfer.setData("text/plain", noteId);
      setDraggedNoteId(noteId);
    },
    [],
  );

  const handleNoteDragEnd = useCallback(() => {
    setDraggedNoteId(null);
    setDropTargetFolder(null);
  }, []);

  const handleFolderDragOver = useCallback(
    (e: React.DragEvent, folder: string) => {
      if (!draggedNoteId) return;
      e.preventDefault();
      e.dataTransfer.dropEffect = "move";
      setDropTargetFolder(folder);
    },
    [draggedNoteId],
  );

  const handleFolderDragLeave = useCallback(() => {
    setDropTargetFolder(null);
  }, []);

  // Auto-scroll the note list while dragging a note near its top/bottom edge,
  // so you can drop into a folder that's scrolled out of view. Fires on the
  // bubbled dragover (folder rows don't stopPropagation); speed scales with
  // proximity to the edge.
  const handleListAutoScroll = useCallback(
    (e: React.DragEvent) => {
      if (!draggedNoteId) return;
      const viewport = folderTreeRef.current;
      if (!viewport) return;
      const rect = viewport.getBoundingClientRect();
      const EDGE = 60; // px from edge where scrolling begins
      const MAX_SPEED = 8; // px/frame at the very edge
      if (e.clientY >= rect.top && e.clientY < rect.top + EDGE) {
        const proximity = 1 - (e.clientY - rect.top) / EDGE;
        viewport.scrollTop -= MAX_SPEED * Math.max(0, proximity);
      } else if (e.clientY <= rect.bottom && e.clientY > rect.bottom - EDGE) {
        const proximity = 1 - (rect.bottom - e.clientY) / EDGE;
        viewport.scrollTop += MAX_SPEED * Math.max(0, proximity);
      }
    },
    [draggedNoteId],
  );

  const handleFolderDrop = useCallback(
    (e: React.DragEvent, targetFolder: string) => {
      e.preventDefault();
      const noteId = e.dataTransfer.getData("text/plain");
      if (!noteId) return;
      // Find the note's current folder to avoid no-op moves
      const note = allNotes.find((n) => n.id === noteId);
      if (note && note.folder_name !== targetFolder) {
        dispatch(moveNoteToFolder({ noteId, folder: targetFolder }));
      }
      setDraggedNoteId(null);
      setDropTargetFolder(null);
    },
    [dispatch, allNotes],
  );

  const handleClaimHomeless = useCallback(async () => {
    if (claimingHomeless || homelessCount === 0) return;
    const ok = await confirm({
      title: `Add ${homelessCount} note${homelessCount === 1 ? "" : "s"} to your organization?`,
      description:
        "Notes without an organization will be assigned to your personal organization so they appear in your workspace.",
      confirmLabel: "Add to my organization",
    });
    if (!ok) return;
    setClaimingHomeless(true);
    try {
      const { noteIds } = await assignHomelessNotesToPersonalOrg();
      await dispatch(fetchNotesList());
      setIncludeHomeless(false);
      toast.success(
        `Added ${noteIds.length} note${noteIds.length === 1 ? "" : "s"} to your organization`,
      );
    } catch (err) {
      console.error("Failed to assign personal organization to notes:", err);
      toast.error("Couldn't add notes to your organization");
    } finally {
      setClaimingHomeless(false);
    }
  }, [claimingHomeless, homelessCount, dispatch]);

  const toggleAllFolders = useCallback(() => {
    setExpandedFolders((prev) => {
      const allExpanded = folders.every((f) => prev.has(f));
      return allExpanded ? new Set<string>() : new Set(folders);
    });
  }, [folders]);

  const cycleSortField = useCallback(() => {
    setSortField((prev) => {
      const idx = SORT_FIELDS.findIndex((s) => s.field === prev);
      return SORT_FIELDS[(idx + 1) % SORT_FIELDS.length].field;
    });
  }, []);

  const toggleSortOrder = useCallback(() => {
    setSortOrder((prev) => (prev === "desc" ? "asc" : "desc"));
  }, []);

  const selectNote = useCallback(
    (noteId: string) => {
      // Sidebar click is a user-direct tab action — bump the
      // interaction timestamp so the auto-move doesn't fire while
      // the user is clicking through notes.
      dispatch(markTabInteraction({ instanceId }));
      dispatch(addInstanceTab({ instanceId, noteId }));
      dispatch(setInstanceActiveTab({ instanceId, noteId }));
      dispatch(fetchNoteContent(noteId));
    },
    [dispatch, instanceId],
  );

  const handleNewNote = useCallback(
    (folder: string) => {
      if (!userId) return;
      const existing = allNotes.find(
        (n) =>
          n._isAutogenerated && !n.content?.trim() && n.folder_name === folder,
      );
      if (existing) {
        selectNote(existing.id);
        return;
      }
      const id = crypto.randomUUID();
      dispatch(createAutogeneratedNote({ id, userId, folder, instanceId }));
    },
    [dispatch, instanceId, userId, allNotes, selectNote],
  );

  // ── Folder context menu actions ────────────────────────────────────
  const handleFolderRename = useCallback((folder: string) => {
    setRenameFolderTarget(folder);
  }, []);

  const handleFolderDeleteAll = useCallback(
    async (folder: string) => {
      const count = (groupedNotes.get(folder) ?? []).length;
      if (count === 0) return;
      const ok = await confirm({
        title: "Delete all notes in folder?",
        description: `${count} note${count === 1 ? "" : "s"} in "${folder}" will be moved to trash. You can restore them later.`,
        confirmLabel: "Delete all",
        variant: "destructive",
      });
      if (!ok) return;
      try {
        await deleteFolderNotes(folder);
        // Re-fetch notes list to reflect deletions
        dispatch(fetchNotesList());
      } catch {
        // Error handled in service
      }
    },
    [dispatch, groupedNotes],
  );

  // Surface sections for the v3 right-click menu on a folder header.
  const buildFolderSections = useCallback(
    (folder: string): ContextMenuExtraSection[] => {
      const items: ContextMenuExtraItem[] = [
        {
          kind: "item",
          id: "new-note",
          label: `New Note in ${folder}`,
          icon: Plus,
          onSelect: () => handleNewNote(folder),
        },
      ];
      if (!isDefaultFolder(folder)) {
        items.push(
          { kind: "separator", id: "folder-sep" },
          {
            kind: "item",
            id: "rename-folder",
            label: "Rename Folder",
            icon: Pencil,
            onSelect: () => handleFolderRename(folder),
          },
          {
            kind: "item",
            id: "delete-all",
            label: "Delete All Notes",
            icon: Trash2,
            destructive: true,
            onSelect: () => void handleFolderDeleteAll(folder),
          },
        );
      }
      return [{ id: "folder-actions", label: folder, items }];
    },
    [handleNewNote, handleFolderRename, handleFolderDeleteAll],
  );

  const handleRenameConfirm = useCallback(
    async (newName: string) => {
      if (!renameFolderTarget) return;
      try {
        await renameFolder(renameFolderTarget, newName);
        // Re-fetch notes list to reflect renamed folder_name
        dispatch(fetchNotesList());
      } catch {
        // Error handled in service
      }
    },
    [dispatch, renameFolderTarget],
  );

  // ── Create folder handler ──────────────────────────────────────────
  const handleCreateFolder = useCallback(
    async (folderName: string) => {
      try {
        // Create the note_folders record first
        await createFolder(folderName);
        // Then create a new note in that folder (which will resolve folder_id)
        handleNewNote(folderName);
      } catch {
        // Fall back to just creating the note
        handleNewNote(folderName);
      }
    },
    [handleNewNote],
  );

  // ── Format time ────────────────────────────────────────────────────
  const formatTime = (dateStr: string | null | undefined) => {
    if (!dateStr) return "";
    const d = new Date(dateStr);
    const mins = Math.floor((Date.now() - d.getTime()) / 60000);
    if (mins < 1) return "now";
    if (mins < 60) return `${mins}m`;
    const hrs = Math.floor(mins / 60);
    if (hrs < 24) return `${hrs}h`;
    const days = Math.floor(hrs / 24);
    if (days < 7) return `${days}d`;
    return d.toLocaleDateString(undefined, { month: "short", day: "numeric" });
  };

  const sortLabel =
    SORT_FIELDS.find((s) => s.field === sortField)?.label ?? "Modified";

  // ── Render ─────────────────────────────────────────────────────────
  return (
    <div className="flex flex-col h-full min-h-0">
      {/* Search */}
      <div className="shrink-0 px-2 py-1.5 border-b border-border/30">
        <div className="flex items-center gap-1.5 px-2 py-1 bg-muted/50 rounded-md">
          <Search className="w-3 h-3 text-muted-foreground shrink-0" />
          <input
            ref={searchInputRef}
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            onFocus={() => {
              searchFocusedRef.current = true;
            }}
            onBlur={() => {
              // Defer the blur check — if focus was stolen by a re-render,
              // restore it on the next frame
              const wasFocused = searchFocusedRef.current;
              searchFocusedRef.current = false;
              if (wasFocused && searchQuery) {
                requestAnimationFrame(() => {
                  if (
                    document.activeElement?.tagName === "TEXTAREA" ||
                    document.activeElement?.tagName === "BODY"
                  ) {
                    searchInputRef.current?.focus();
                  }
                });
              }
            }}
            placeholder="Search notes..."
            className="flex-1 min-w-0 bg-transparent text-base md:text-xs outline-none placeholder:text-muted-foreground/50"
          />
          {searchQuery && (
            <button
              onClick={() => setSearchQuery("")}
              className="text-muted-foreground hover:text-foreground cursor-pointer [&_svg]:w-3 [&_svg]:h-3"
            >
              <X />
            </button>
          )}
        </div>
      </div>

      {activeOrgId && homelessCount > 0 && (
        <div className="shrink-0 flex items-center gap-1.5 border-b border-border/20 px-2.5 py-1">
          <span className="flex min-w-0 items-center gap-1.5 text-[10px] text-amber-600/80 dark:text-amber-400/80">
            <TriangleAlert className="h-2.5 w-2.5 shrink-0" />
            <span className="truncate">
              {homelessCount} note{homelessCount === 1 ? "" : "s"} without an
              organization
            </span>
          </span>
          <button
            type="button"
            onClick={handleClaimHomeless}
            disabled={claimingHomeless}
            className="ml-auto shrink-0 rounded px-1.5 py-0.5 text-[10px] font-medium text-amber-600 hover:bg-amber-500/10 disabled:opacity-50 dark:text-amber-400 transition-colors"
            title="Assign your personal organization to these notes so they appear in your workspace."
          >
            {claimingHomeless ? "Adding…" : "Add to my organization"}
          </button>
          <button
            type="button"
            onClick={() => setIncludeHomeless((v) => !v)}
            className="shrink-0 rounded px-1.5 py-0.5 text-[10px] text-muted-foreground hover:text-foreground transition-colors"
            title={
              includeHomeless
                ? "Hide these notes"
                : "Show these notes in the list"
            }
          >
            {includeHomeless ? "Hide" : "Show"}
          </button>
        </div>
      )}

      {/* Toolbar. Two kinds of control, made visually distinct so their
          purpose reads at a glance:
          • Selectors (Group, Sort) — filled chips showing the CURRENT value.
          • Actions (order, Select, Expand) — plain icon buttons.
          Every control carries a proper tooltip. */}
      <div className="shrink-0 flex items-center gap-1 px-2 py-1 border-b border-border/20">
        {/* Group-by selector */}
        <div className="relative">
          <SimpleTooltip text="Group notes by">
            <button
              onClick={() => setGroupByDropdown((v) => !v)}
              className="flex items-center gap-1 h-6 px-1.5 rounded-md text-[0.625rem] font-medium text-muted-foreground bg-muted/40 hover:bg-muted hover:text-foreground cursor-pointer transition-colors [&_svg]:w-3 [&_svg]:h-3"
            >
              <Layers />
              <span>
                {GROUP_MODES.find((m) => m.mode === groupBy)?.label ?? "Folder"}
              </span>
              <ChevronDown className="w-2! h-2! opacity-50" />
            </button>
          </SimpleTooltip>
          {groupByDropdown && (
            <>
              <div
                className="fixed inset-0 z-[100]"
                onClick={() => setGroupByDropdown(false)}
              />
              <div className="absolute left-0 top-full mt-1 z-[110] min-w-[130px] py-1 bg-card/95 backdrop-blur-2xl border border-border rounded-lg shadow-lg">
                {GROUP_MODES.map((m) => {
                  const Icon = m.icon;
                  return (
                    <button
                      key={m.mode}
                      className={cn(
                        "flex items-center gap-2 w-full px-3 py-1.5 text-[0.625rem] cursor-pointer transition-colors",
                        groupBy === m.mode
                          ? "bg-primary/10 text-primary font-medium"
                          : "text-foreground hover:bg-accent",
                      )}
                      onClick={() => {
                        setGroupBy(m.mode);
                        setGroupByDropdown(false);
                      }}
                    >
                      <Icon className="w-3 h-3" /> {m.label}
                    </button>
                  );
                })}
              </div>
            </>
          )}
        </div>

        {/* Sort-field selector */}
        <SimpleTooltip text={`Sorted by ${sortLabel} \u2014 click to change`}>
          <button
            onClick={cycleSortField}
            className="flex items-center gap-1 h-6 px-1.5 rounded-md text-[0.625rem] font-medium text-muted-foreground bg-muted/40 hover:bg-muted hover:text-foreground cursor-pointer transition-colors [&_svg]:w-3 [&_svg]:h-3"
          >
            <ArrowUpDown />
            <span>{sortLabel}</span>
          </button>
        </SimpleTooltip>

        {/* Sort-order action */}
        <SimpleTooltip
          text={sortOrder === "desc" ? "Newest first" : "Oldest first"}
        >
          <button
            onClick={toggleSortOrder}
            className="flex items-center justify-center h-6 w-6 rounded-md text-muted-foreground hover:bg-muted hover:text-foreground cursor-pointer transition-colors [&_svg]:w-3.5 [&_svg]:h-3.5"
          >
            {sortOrder === "desc" ? (
              <ArrowDownWideNarrow />
            ) : (
              <ArrowUpWideNarrow />
            )}
          </button>
        </SimpleTooltip>

        <div className="flex-1" />

        {/* Select-notes action (bulk mode) */}
        <SimpleTooltip
          text={selectionMode ? "Exit selection mode" : "Select notes"}
        >
          <button
            onClick={toggleSelectionMode}
            className={cn(
              "flex items-center justify-center h-6 w-6 rounded-md cursor-pointer transition-colors [&_svg]:w-3.5 [&_svg]:h-3.5",
              selectionMode
                ? "text-primary bg-primary/10"
                : "text-muted-foreground hover:bg-muted hover:text-foreground",
            )}
          >
            <ListChecks />
          </button>
        </SimpleTooltip>

        {/* Expand/collapse-all action */}
        {groupBy !== "recent" && (
          <SimpleTooltip text="Expand or collapse all folders">
            <button
              onClick={toggleAllFolders}
              className="flex items-center justify-center h-6 w-6 rounded-md text-muted-foreground hover:bg-muted hover:text-foreground cursor-pointer transition-colors [&_svg]:w-3.5 [&_svg]:h-3.5"
            >
              <ChevronsUpDown />
            </button>
          </SimpleTooltip>
        )}
      </div>

      {/* Note list — grouped or flat */}
      <div
        className="flex-1 overflow-y-auto"
        ref={folderTreeRef}
        onDragOver={handleListAutoScroll}
      >
        {/* Recent — collapsible, paginated. Sits ABOVE "Shared with me".
            Default mode only (other modes surface recency differently). */}
        {groupBy === "default" && recentSorted.length > 0 && (
          <div className="mb-1 border-b border-border/30">
            <button
              type="button"
              onClick={() => setRecentOpen((v) => !v)}
              className="group flex items-center gap-1 w-full px-2 py-1 text-[0.6875rem] font-semibold uppercase tracking-wider text-muted-foreground cursor-pointer transition-colors hover:text-foreground hover:bg-accent/50 [&_svg]:w-3 [&_svg]:h-3"
            >
              {recentOpen ? (
                <ChevronDown className="opacity-60" />
              ) : (
                <ChevronRight className="opacity-60" />
              )}
              <Clock className="text-amber-500 dark:text-amber-400" />
              <span className="flex-1 text-left truncate">Recent</span>
              <span className="text-[0.625rem] font-normal opacity-50 tabular-nums">
                {recentSorted.length}
              </span>
            </button>
            {recentOpen && (
              <div className="ml-1 pb-1">
                {recentSorted.slice(0, recentVisibleCount).map((note) => {
                  const isActive = activeTabId === note.id;
                  const isOpenTab = openTabIds?.includes(note.id) ?? false;
                  return (
                    <NoteSidebarRow
                      key={note.id}
                      note={note}
                      instanceId={instanceId}
                      isActive={isActive}
                      isOpenTab={isOpenTab}
                      allFolders={allFolders}
                      openKnowledge={openKnowledge}
                      formatTime={formatTime}
                      showFolderTag
                      onSelectNote={selectNote}
                      selectionMode={selectionMode}
                      isSelected={selectedIds.has(note.id)}
                      onToggleSelect={toggleSelect}
                    />
                  );
                })}
                {(recentSorted.length > recentVisibleCount ||
                  recentVisibleCount > RECENT_PAGE_SIZE) && (
                  <div className="flex items-center gap-2 px-2 pt-0.5">
                    {recentSorted.length > recentVisibleCount && (
                      <button
                        type="button"
                        onClick={() =>
                          setRecentVisibleCount((c) => c + RECENT_PAGE_SIZE)
                        }
                        className="text-[0.625rem] font-medium text-primary/80 hover:text-primary cursor-pointer transition-colors"
                      >
                        Show{" "}
                        {Math.min(
                          RECENT_PAGE_SIZE,
                          recentSorted.length - recentVisibleCount,
                        )}{" "}
                        more
                      </button>
                    )}
                    {recentVisibleCount > RECENT_PAGE_SIZE && (
                      <button
                        type="button"
                        onClick={() => setRecentVisibleCount(RECENT_PAGE_SIZE)}
                        className="text-[0.625rem] text-muted-foreground hover:text-foreground cursor-pointer transition-colors"
                      >
                        Show less
                      </button>
                    )}
                  </div>
                )}
              </div>
            )}
          </div>
        )}

        {/* Shared with me — collapsible section, below Recent */}
        {sharedNotes.length > 0 && (
          <div className="mb-1">
            <button
              type="button"
              onClick={() => setSharedOpen((v) => !v)}
              className="group flex items-center gap-1 w-full px-2 py-1 text-[0.6875rem] font-semibold uppercase tracking-wider text-muted-foreground cursor-pointer transition-colors hover:text-foreground hover:bg-accent/50 [&_svg]:w-3 [&_svg]:h-3"
            >
              {sharedOpen ? (
                <ChevronDown className="opacity-60" />
              ) : (
                <ChevronRight className="opacity-60" />
              )}
              <Users className="text-indigo-500 dark:text-indigo-400" />
              <span className="flex-1 text-left truncate">Shared with me</span>
              <span className="text-[0.625rem] font-normal opacity-50 tabular-nums">
                {sharedNotes.length}
              </span>
            </button>
            {sharedOpen && (
              <div className="ml-2">
                {sharedNotes.map((note) => {
                  const level = note._sharedMeta?.permissionLevel ?? "viewer";
                  const canEdit = level === "editor" || level === "admin";
                  const isActive = activeTabId === note.id;
                  const isOpenTab = openTabIds?.includes(note.id) ?? false;
                  return (
                    <button
                      key={note.id}
                      type="button"
                      data-note-id={note.id}
                      onClick={() => selectNote(note.id)}
                      title={
                        `${note._sharedMeta?.ownerEmail ?? "Someone"} shared this with you — ` +
                        (canEdit ? "you can edit" : "view only")
                      }
                      className={cn(
                        "flex items-center gap-1.5 w-full text-left px-2 py-[3px] rounded-sm cursor-pointer transition-colors",
                        isActive
                          ? "bg-accent text-foreground"
                          : isOpenTab
                            ? "bg-accent/30 text-foreground/80"
                            : "text-muted-foreground hover:bg-accent/50 hover:text-foreground",
                      )}
                    >
                      <FileText className="w-3.5 h-3.5 shrink-0 text-indigo-500/70 dark:text-indigo-400/70" />
                      <span className="flex-1 text-xs truncate leading-tight">
                        {note.label}
                      </span>
                      <span className="text-[0.5625rem] opacity-40 shrink-0 truncate max-w-[80px]">
                        {note._sharedMeta?.ownerEmail?.split("@")[0] ?? ""}
                      </span>
                      {canEdit ? (
                        <Pencil className="w-3 h-3 shrink-0 text-emerald-500/70" />
                      ) : (
                        <Eye className="w-3 h-3 shrink-0 text-sky-500/70" />
                      )}
                    </button>
                  );
                })}
              </div>
            )}
          </div>
        )}

        {listStatus === "loaded" &&
        allNotes.length === 0 &&
        sharedNotes.length === 0 ? (
          <div className="flex flex-col items-center justify-center h-full text-muted-foreground/60 px-6 py-8">
            <StickyNote className="w-10 h-10 mb-3 opacity-40" />
            <p className="text-xs font-medium">No notes yet</p>
            <p className="text-[0.625rem] mt-1 text-center">
              Click "New Note" below to get started
            </p>
          </div>
        ) : groupBy === "recent" ? (
          /* ── Recent mode: flat sorted list ──────────────────────── */
          <div className="ml-1">
            {(groupedNotes.get("__all__") ?? []).map((note) => {
              const isActive = activeTabId === note.id;
              const isOpenTab = openTabIds?.includes(note.id) ?? false;
              return (
                <NoteSidebarRow
                  key={note.id}
                  note={note}
                  instanceId={instanceId}
                  isActive={isActive}
                  isOpenTab={isOpenTab}
                  allFolders={allFolders}
                  openKnowledge={openKnowledge}
                  formatTime={formatTime}
                  showFolderTag
                  onSelectNote={selectNote}
                  selectionMode={selectionMode}
                  isSelected={selectedIds.has(note.id)}
                  onToggleSelect={toggleSelect}
                />
              );
            })}
          </div>
        ) : (
          /* ── Grouped mode: collapsible sections (folder + default + hierarchy).
             Default mode's recents now live in the "Recent" section above. ── */
          <>
            {groupKeys.map((groupKey) => {
              const groupNotes = groupedNotes.get(groupKey) ?? [];
              const isExpanded = expandedFolders.has(groupKey);
              const label = getGroupLabel(groupKey);
              const count = groupNotes.length;

              // Folder + Default modes both render folder icons/colors and DnD
              const isFolderMode =
                groupBy === "folder" || groupBy === "default";
              const { icon: FolderIcon, color: iconColor } = isFolderMode
                ? getFolderIconAndColor(groupKey)
                : {
                    icon:
                      GROUP_MODES.find((m) => m.mode === groupBy)?.icon ??
                      Folder,
                    color: undefined,
                  };

              if (searchQuery && count === 0) return null;

              const folderHeaderButton = (
                <button
                  className={cn(
                    "group flex items-center gap-1 w-full px-2 py-1 text-[0.6875rem] font-semibold uppercase tracking-wider text-muted-foreground cursor-pointer transition-colors hover:text-foreground hover:bg-accent/50 [&_svg]:w-3 [&_svg]:h-3",
                    isFolderMode &&
                      dropTargetFolder === groupKey &&
                      "bg-primary/10 border-l-2 border-primary",
                  )}
                  onClick={() => toggleFolder(groupKey)}
                >
                  {isExpanded ? (
                    <ChevronDown className="opacity-60" />
                  ) : (
                    <ChevronRight className="opacity-60" />
                  )}
                  {isExpanded ? (
                    <FolderOpen className={cn("opacity-70", iconColor)} />
                  ) : (
                    <FolderIcon className={cn("opacity-70", iconColor)} />
                  )}
                  <span className="flex-1 text-left truncate">{label}</span>
                  <span className="text-[0.625rem] font-normal opacity-50 tabular-nums">
                    {count}
                  </span>
                  {isFolderMode && (
                    <Plus
                      className="w-3 h-3 opacity-0 group-hover:opacity-60 hover:!opacity-100 transition-opacity"
                      onClick={(e) => {
                        e.stopPropagation();
                        handleNewNote(groupKey);
                      }}
                    />
                  )}
                </button>
              );

              return (
                <div
                  key={groupKey}
                  onDragOver={
                    isFolderMode
                      ? (e) => handleFolderDragOver(e, groupKey)
                      : undefined
                  }
                  onDragLeave={isFolderMode ? handleFolderDragLeave : undefined}
                  onDrop={
                    isFolderMode
                      ? (e) => handleFolderDrop(e, groupKey)
                      : undefined
                  }
                >
                  {/* Folder actions ride the universal v3 menu (folder mode only) */}
                  {isFolderMode ? (
                    <NonEditableContextMenu
                      sourceFeature="notes"
                      contextData={{ content: groupKey }}
                      extraSections={buildFolderSections(groupKey)}
                    >
                      {folderHeaderButton}
                    </NonEditableContextMenu>
                  ) : (
                    folderHeaderButton
                  )}

                  {isExpanded && (
                    <div className="ml-2">
                      {groupNotes.length === 0 ? (
                        <div className="px-5 py-2 text-[0.625rem] text-muted-foreground/50 italic">
                          Empty
                        </div>
                      ) : (
                        groupNotes.map((note) => {
                          const isActive = activeTabId === note.id;
                          const isOpenTab =
                            openTabIds?.includes(note.id) ?? false;
                          const isDragging = draggedNoteId === note.id;
                          return (
                            <NoteSidebarRow
                              key={note.id}
                              note={note}
                              instanceId={instanceId}
                              isActive={isActive}
                              isOpenTab={isOpenTab}
                              allFolders={allFolders}
                              openKnowledge={openKnowledge}
                              formatTime={formatTime}
                              draggable={isFolderMode}
                              isDragging={isDragging}
                              onDragStart={(e) =>
                                handleNoteDragStart(e, note.id)
                              }
                              onDragEnd={handleNoteDragEnd}
                              onSelectNote={selectNote}
                              selectionMode={selectionMode}
                              isSelected={selectedIds.has(note.id)}
                              onToggleSelect={toggleSelect}
                            />
                          );
                        })
                      )}
                    </div>
                  )}
                </div>
              );
            })}
          </>
        )}

        {/* Trash — soft-deleted recovery, bottom of the scrollable list */}
        <div className="mt-1 border-t border-border/20">
          <button
            type="button"
            onClick={() => {
              setTrashOpen((v) => !v);
              if (!trashFetchedRef.current) {
                trashFetchedRef.current = true;
                dispatch(fetchDeletedNotes());
              }
            }}
            className="group flex items-center gap-1 w-full px-2 py-1 text-[0.6875rem] font-semibold uppercase tracking-wider text-muted-foreground cursor-pointer transition-colors hover:text-foreground hover:bg-accent/50 [&_svg]:w-3 [&_svg]:h-3"
          >
            {trashOpen ? (
              <ChevronDown className="opacity-60" />
            ) : (
              <ChevronRight className="opacity-60" />
            )}
            <Trash2 className="text-rose-500 dark:text-rose-400" />
            <span className="flex-1 text-left truncate">Trash</span>
            {deletedNotes.length > 0 && (
              <span className="text-[0.625rem] font-normal opacity-50 tabular-nums">
                {deletedNotes.length}
              </span>
            )}
          </button>
          {trashOpen && (
            <div className="ml-2 max-h-48 overflow-y-auto pb-1">
              {deletedNotes.length === 0 ? (
                <p className="px-3 py-2 text-[0.5625rem] text-muted-foreground/50">
                  Trash is empty
                </p>
              ) : (
                <>
                  <div className="mb-0.5 flex items-center justify-end px-2">
                    <button
                      type="button"
                      className="cursor-pointer text-[0.5625rem] text-destructive/80 transition-colors hover:text-destructive"
                      onClick={async () => {
                        const ok = await confirm({
                          title: "Empty trash",
                          description: `Permanently delete ${deletedNotes.length} note${deletedNotes.length === 1 ? "" : "s"}? This cannot be undone.`,
                          confirmLabel: "Empty trash",
                          variant: "destructive",
                        });
                        if (!ok) return;
                        try {
                          const count =
                            await dispatch(emptyTrashThunk()).unwrap();
                          toast.success(
                            count
                              ? `Emptied trash (${count})`
                              : "Nothing to delete",
                          );
                        } catch (err) {
                          console.error(err);
                          toast.error("Failed to empty trash");
                        }
                      }}
                    >
                      Empty trash
                    </button>
                  </div>
                  {deletedNotes.map((note) => {
                    const deletedLabel = note.deleted_at
                      ? new Date(note.deleted_at).toLocaleDateString(
                          undefined,
                          { month: "short", day: "numeric" },
                        )
                      : null;
                    return (
                      <div
                        key={note.id}
                        className="group/trash flex items-center gap-1.5 rounded-sm px-2 py-1"
                      >
                        <FileText className="h-3 w-3 shrink-0 text-muted-foreground/40" />
                        <div className="min-w-0 flex-1">
                          <span className="block truncate text-[0.625rem] text-muted-foreground">
                            {note.label || "Untitled"}
                          </span>
                          {deletedLabel && (
                            <span className="block text-[0.5rem] text-muted-foreground/50">
                              Deleted {deletedLabel}
                            </span>
                          )}
                        </div>
                        <button
                          type="button"
                          onClick={() => dispatch(restoreNote(note.id))}
                          className="cursor-pointer text-muted-foreground opacity-0 transition-opacity hover:text-foreground group-hover/trash:opacity-100 [&_svg]:h-3 [&_svg]:w-3"
                          title="Restore"
                        >
                          <RotateCcw />
                        </button>
                        <button
                          type="button"
                          onClick={async () => {
                            const ok = await confirm({
                              title: "Permanently delete",
                              description: `Permanently delete "${note.label || "Untitled"}"? This cannot be undone.`,
                              confirmLabel: "Delete forever",
                              variant: "destructive",
                            });
                            if (!ok) return;
                            try {
                              await dispatch(
                                permanentlyDeleteNoteThunk(note.id),
                              ).unwrap();
                              toast.success("Note permanently deleted");
                            } catch (err) {
                              console.error(err);
                              toast.error("Failed to permanently delete");
                            }
                          }}
                          className="cursor-pointer text-destructive/70 opacity-0 transition-opacity hover:text-destructive group-hover/trash:opacity-100 [&_svg]:h-3 [&_svg]:w-3"
                          title="Delete forever"
                        >
                          <Trash2 />
                        </button>
                      </div>
                    );
                  })}
                </>
              )}
            </div>
          )}
        </div>
      </div>

      {/* Bottom: bulk actions (selection mode) or New Note + New Folder */}
      {selectionMode && selectedIds.size > 0 ? (
        <NoteSidebarBulkBar
          instanceId={instanceId}
          selectedNotes={selectedNoteRecords}
          allFolders={allFolders}
          openTabIds={openTabIds}
          onClear={exitSelectionMode}
        />
      ) : (
        <div className="shrink-0 px-2 py-1.5 border-t border-border/30 flex items-center gap-1">
          <button
            className="flex items-center gap-1.5 flex-1 px-2 py-1 text-[0.6875rem] text-muted-foreground cursor-pointer transition-colors hover:text-foreground hover:bg-accent/50 rounded-md [&_svg]:w-3 [&_svg]:h-3"
            onClick={() => handleNewNote("Draft")}
          >
            <Plus /> New Note
          </button>
          <button
            className="flex items-center justify-center w-7 h-7 text-muted-foreground cursor-pointer transition-colors hover:text-foreground hover:bg-accent/50 rounded-md [&_svg]:w-3.5 [&_svg]:h-3.5"
            onClick={() => setCreateFolderOpen(true)}
            title="New Folder"
          >
            <FolderPlus />
          </button>
        </div>
      )}

      {/* ── Dialogs ────────────────────────────────────────────────────── */}
      <CreateFolderDialog
        open={createFolderOpen}
        onOpenChange={setCreateFolderOpen}
        onConfirm={handleCreateFolder}
        existingFolders={allFolders}
      />

      {renameFolderTarget && (
        <RenameFolderDialog
          open={!!renameFolderTarget}
          onOpenChange={(open) => {
            if (!open) setRenameFolderTarget(null);
          }}
          onConfirm={handleRenameConfirm}
          currentName={renameFolderTarget}
          existingFolders={allFolders}
        />
      )}
    </div>
  );
}
