/**
 * Canonical notes tab URL order: active first, then every other open tab.
 * Keeps `?tabs=` and the strip's mental model aligned — reload never loses
 * which note was focused just because it wasn't first in the list.
 */
export function orderTabsActiveFirst(
  tabs: readonly string[],
  activeId: string | null | undefined,
): string[] {
  if (!activeId) return [...tabs];
  if (!tabs.includes(activeId)) return [activeId, ...tabs];
  return [activeId, ...tabs.filter((id) => id !== activeId)];
}

/** The per-note facts the URL writer needs — only whether a row exists yet. */
export type NoteTabUrlRecord = { _isAutogenerated?: boolean } | undefined;

/**
 * The `?tabs=&active=&split=` params the Notes workspace writes for its open
 * tabs. `null` drops the key.
 *
 * THE URL NAMES ONLY NOTES THAT EXIST. A new note ("+", "New Note") is a
 * client-only draft (`_isAutogenerated`) with no database row until its first
 * edit is saved. Writing its id here made every reload restore the id and ask
 * `workbench.notes` for a row that was never written — the tab answered "We
 * couldn't find this note" (verifier, 2026-09-26). An empty draft ends with
 * the page, exactly as it would in any editor; typed-but-unsaved text is
 * captured by the local draft store, and because the id is no longer an open
 * tab after a reload, `NotesDraftRecoveryList` offers it ("never saved to the
 * server" · Recover as new note). The id enters the URL the moment the first
 * save lands (`materializeNote` clears the flag after the INSERT returns), so
 * the URL can never name a row before it exists.
 */
export function noteTabsUrlParams(input: {
  openTabs: readonly string[];
  activeTabId: string | null | undefined;
  splitNoteId: string | null | undefined;
  notes: Readonly<Record<string, NoteTabUrlRecord>>;
}): { tabs: string | null; active: string | null; split: string | null } {
  const persisted = (id: string | null | undefined): id is string =>
    Boolean(id) && input.notes[id as string]?._isAutogenerated !== true;
  const active = persisted(input.activeTabId) ? input.activeTabId : null;
  const orderedTabs = orderTabsActiveFirst(
    input.openTabs.filter(persisted),
    active,
  );
  return {
    tabs: orderedTabs.length > 0 ? orderedTabs.join(",") : null,
    active,
    split: persisted(input.splitNoteId) ? input.splitNoteId : null,
  };
}
