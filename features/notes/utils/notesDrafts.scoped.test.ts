/**
 * A capture made for ONE note (a delete) must not re-stamp every other note's
 * browser draft with that note's reason — the recovery banner on an unrelated
 * note would then claim "the note was deleted" (reviewer finding, 2026-09-15).
 */
const collectors = new Map<string, () => Array<Record<string, unknown>>>();
jest.mock("@ai-matrx/kit/drafts", () => ({
  registerDraftSource: (id: string, collect: () => Array<Record<string, unknown>>) => {
    collectors.set(id, collect);
    return () => collectors.delete(id);
  },
  captureDrafts: (reason: string) =>
    [...collectors.values()].flatMap((collect) => collect().map((d) => ({ ...d, reason }))),
  discardDraft: jest.fn(),
  getDraft: jest.fn(),
  listDrafts: jest.fn(),
}));

import {
  captureNoteDraftFor,
  captureNoteDrafts,
  registerNotesDraftSource,
} from "./notesDrafts";

const dirty = (id: string) => ({
  id,
  label: id,
  content: `unsaved text in ${id}`,
  _dirty: true,
  _isAutogenerated: false,
  created_by: "user-1",
});

describe("scoped draft capture", () => {
  it("captures only the named note, then a normal capture covers every note again", () => {
    const state = {
      userAuth: { id: "user-1" },
      notes: { notes: { a: dirty("a"), b: dirty("b") } },
    };
    const stop = registerNotesDraftSource(() => state as never);
    try {
      const scoped = captureNoteDraftFor("a", "note-deleted");
      expect(scoped.map((d) => d.entityId)).toEqual(["a"]);
      expect(scoped[0].reason).toBe("note-deleted");

      const all = captureNoteDrafts("unload");
      expect(all.map((d) => d.entityId).sort()).toEqual(["a", "b"]);
    } finally {
      stop();
    }
  });

  it("clears the scope even when the capture throws", () => {
    const state = { userAuth: { id: "user-1" }, notes: { notes: { a: dirty("a"), b: dirty("b") } } };
    const stop = registerNotesDraftSource(() => state as never);
    const boom = registerNotesDraftSource(() => {
      throw new Error("storage full");
    });
    try {
      expect(() => captureNoteDraftFor("a", "note-deleted")).toThrow("storage full");
    } finally {
      boom();
    }
    const again = registerNotesDraftSource(() => state as never);
    try {
      expect(captureNoteDrafts("unload").map((d) => d.entityId).sort()).toEqual(["a", "b"]);
    } finally {
      again();
      stop();
    }
  });
});
