// features/notes/utils/notesDrafts.ts
//
// Notes' half of the local unsaved-work draft store (`lib/local-drafts/`).
//
// The generic primitive owns storage, expiry, ownership and capture triggers.
// This file owns ONE thing: what "unsaved" means for a note — a record that is
// `_dirty` (edits Redux holds but the DB does not). It is deliberately thin;
// never fork a notes-only draft store here.

import {
  captureDrafts,
  discardDraft,
  getDraft,
  listDrafts,
  registerDraftSource,
} from "@/lib/local-drafts/localDrafts";
import type { LocalDraft, LocalDraftInput } from "@/lib/local-drafts/types";
import type { NoteRecord, NotesSliceState } from "../redux/notes.types";

export const NOTES_DRAFT_NAMESPACE = "note";

type StateWithNotes = {
  notes?: NotesSliceState;
  userAuth?: { id?: string | null };
};

/** Every dirty note in the store, as draft inputs. */
export function collectNoteDrafts(state: StateWithNotes): LocalDraftInput[] {
  const records = state.notes?.notes;
  if (!records) return [];
  const ownerId = state.userAuth?.id ?? null;

  const drafts: LocalDraftInput[] = [];
  for (const record of Object.values(records) as NoteRecord[]) {
    if (!record?._dirty) continue;
    const content = record.content ?? "";
    if (content.trim() === "") continue;
    drafts.push({
      namespace: NOTES_DRAFT_NAMESPACE,
      entityId: record.id,
      // The account the edits were made AS — the identity-drift case is
      // exactly why this is the record's own `created_by` when we have it.
      ownerId: record.created_by ?? ownerId,
      label: record.label ?? null,
      content,
      isNew: record._isAutogenerated === true,
    });
  }
  return drafts;
}

/**
 * Register the notes draft source. Idempotent — mounting several editors just
 * replaces the collector. Returns the unregister function.
 */
export function registerNotesDraftSource(
  getState: () => StateWithNotes,
): () => void {
  return registerDraftSource(NOTES_DRAFT_NAMESPACE, () =>
    collectNoteDrafts(getState()),
  );
}

/** Snapshot now — call before anything that discards the editor's buffer. */
export function captureNoteDrafts(reason: string): LocalDraft[] {
  return captureDrafts(reason);
}

export function getNoteDraft(
  noteId: string,
  ownerId: string | null,
): LocalDraft | null {
  return getDraft(NOTES_DRAFT_NAMESPACE, noteId, ownerId);
}

export function listNoteDrafts(ownerId: string | null): LocalDraft[] {
  return listDrafts(NOTES_DRAFT_NAMESPACE, ownerId);
}

export function discardNoteDraft(noteId: string): void {
  discardDraft(NOTES_DRAFT_NAMESPACE, noteId);
}
