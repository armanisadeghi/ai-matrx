import { start, S, dump } from "./_h.tmp.mjs";
const { browser, page } = await start();
await page.setViewportSize({width:1440,height:1500});
await page.waitForTimeout(3000);
const g = await page.evaluate(()=>{
  const hs=[...document.querySelectorAll('.bn-editor [data-content-type="heading"]')].filter(e=>e.innerText.includes("CLIENTSFULFILLMENT"));
  const h=hs[0].getBoundingClientRect();
  const ps=[...document.querySelectorAll('.bn-editor [data-content-type="paragraph"]')].filter(e=>e.getBoundingClientRect().x<840);
  const l=ps.at(-1).getBoundingClientRect();
  return {hx:h.x+h.width-5,hy:h.y+h.height/2,lx:l.x+60,ly:l.y+l.height/2};
});
console.log(g);
await page.mouse.click(g.hx,g.hy); await page.keyboard.press("End");
await page.keyboard.down("Shift"); await page.mouse.click(g.lx,g.ly); await page.keyboard.up("Shift");
await page.waitForTimeout(400);
await page.keyboard.press("Backspace"); await page.waitForTimeout(800);
console.log(await dump(page));
await page.waitForTimeout(6000);
await page.screenshot({ path: `${S}/shots/14.png` });
await browser.close();
