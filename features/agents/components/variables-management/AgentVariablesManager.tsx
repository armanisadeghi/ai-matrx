"use client";

/**
 * AgentVariablesManager
 *
 * Compact chip row used inside the agent builder sidebar. All edits flow
 * through Redux directly via the agentVariableEditorWindow overlay. "Add" uses the
 * instant-create pattern: dispatch a placeholder entity, then open the
 * modal in edit mode on the new variable.
 */

import React, { useEffect, useState } from "react";
import { Plus, X, AlertCircle, Layers, SlidersHorizontal } from "lucide-react";
import { Label } from "@/components/ui/label";
import { ScrollFade } from "@/components/ui/scroll-fade";
import { useAppSelector, useAppDispatch } from "@/lib/redux/hooks";
import { useOpenScopeBatchImportWindow } from "@/features/overlays/openers/scopeBatchImportWindow";
import {
  selectAgentVariableDefinitions,
  selectAgentMessages,
  selectAgentSettings,
} from "@/features/agents/redux/agent-definition/selectors";
import {
  setAgentControlBinding,
  setAgentVariableDefinitions,
} from "@/features/agents/redux/agent-definition/slice";
import {
  isControlVariable,
  unbindControlVariable,
} from "@/features/agents/utils/control-variables";
import type { VariableDefinition } from "@/features/agents/types/agent-definition.types";
import { useOpenAgentVariableEditorWindow } from "@/features/overlays/openers/agentVariableEditorWindow";
import {
  extractVariableReferences,
  generateNextVariableName,
  isAutoGeneratedVariableName,
  isDeclarableVariableName,
  sanitizeVariableName,
} from "@/features/agents/utils/variable-utils";
import { isCustomDataBinding } from "@/features/agents/utils/variable-binding";
import { CustomDataBindingSummary } from "./custom-data/CustomDataBindingSummary";

interface AgentVariablesManagerProps {
  agentId: string;
}

function isVariableUsedInText(name: string, text: string): boolean {
  return new RegExp(`\\{\\{\\s*${name}\\s*\\}\\}`).test(text);
}

/** Still eligible for the "Discard" affordance (auto-name + no config). */
function isStillFresh(v: VariableDefinition): boolean {
  if (!isAutoGeneratedVariableName(v.name)) return false;
  if (v.customComponent) return false;
  if (v.helpText) return false;
  if (v.required) return false;
  if (v.defaultValue != null && String(v.defaultValue).length > 0) return false;
  return true;
}

export function AgentVariablesManager({ agentId }: AgentVariablesManagerProps) {
  const dispatch = useAppDispatch();
  const openBatchImport = useOpenScopeBatchImportWindow();
  const settings = useAppSelector((state) => selectAgentSettings(state, agentId));
  const rawVariables = useAppSelector((state) =>
    selectAgentVariableDefinitions(state, agentId),
  );
  const messages = useAppSelector((state) =>
    selectAgentMessages(state, agentId),
  );

  const variables: VariableDefinition[] = rawVariables ?? [];

  const allText = (messages ?? [])
    .flatMap((m) =>
      (m.content ?? []).flatMap((b) => {
        if (b.type === "text") return [b.text];
        return Object.values(b).filter(
          (v): v is string => typeof v === "string" && v !== b.type,
        );
      }),
    )
    .join(" ");

  const definedNamesSet = new Set(variables.map((v) => v.name));
  const undeclaredNames = extractVariableReferences(allText).filter(
    (n) => !definedNamesSet.has(n) && isDeclarableVariableName(n),
  );

  // The editor is a registered overlay window: its open state lives in the
  // overlay slice, above the builder's desktop↔mobile tree swap (C1).
  const openVariableEditor = useOpenAgentVariableEditorWindow();

  // ── Fresh-name tracking ───────────────────────────────────────────────────
  const [freshNames, setFreshNames] = useState<Set<string>>(new Set());

  useEffect(() => {
    if (freshNames.size === 0) return;
    let changed = false;
    const next = new Set(freshNames);
    for (const name of freshNames) {
      const v = variables.find((x) => x.name === name);
      if (!v || !isStillFresh(v)) {
        next.delete(name);
        changed = true;
      }
    }
    if (changed) setFreshNames(next);
  }, [variables, freshNames]);

  // ── Handlers ──────────────────────────────────────────────────────────────
  const handleAddClick = (prefill?: string) => {
    const sanitized = prefill ? sanitizeVariableName(prefill) : "";
    const collides = !!sanitized && definedNamesSet.has(sanitized);
    const name =
      sanitized && !collides
        ? sanitized
        : generateNextVariableName(variables.map((v) => v.name));

    const newVar: VariableDefinition = { name, defaultValue: "" };
    dispatch(
      setAgentVariableDefinitions({
        id: agentId,
        variableDefinitions: [...variables, newVar],
      }),
    );

    if (isAutoGeneratedVariableName(name)) {
      setFreshNames((prev) => {
        const next = new Set(prev);
        next.add(name);
        return next;
      });
    }
    openVariableEditor({
      agentId,
      variableName: name,
      justCreated: isAutoGeneratedVariableName(name),
    });
  };

  const handleEditClick = (name: string) => {
    const v = variables.find((x) => x.name === name);
    openVariableEditor({
      agentId,
      variableName: name,
      justCreated: !!v && freshNames.has(name) && isStillFresh(v),
    });
  };

  const handleRemove = (name: string) => {
    // Removing a bound model control's variable UNBINDS it: its default goes
    // back into settings as the literal, never silently dropped.
    const removed = variables.find((v) => v.name === name);
    const controlKey = removed?.control?.key;
    if (controlKey) {
      const next = unbindControlVariable({
        key: controlKey,
        control: null,
        settings: (settings ?? {}) as Record<string, unknown>,
        variableDefinitions: variables,
      });
      dispatch(
        setAgentControlBinding({
          id: agentId,
          settings: next.settings as NonNullable<typeof settings>,
          variableDefinitions: next.variableDefinitions,
        }),
      );
      return;
    }
    dispatch(
      setAgentVariableDefinitions({
        id: agentId,
        variableDefinitions: variables.filter((v) => v.name !== name),
      }),
    );
  };

  return (
    <>
      <div className="flex items-center gap-2 min-w-0">
        <Label className="text-xs text-muted-foreground shrink-0">
          Variables
        </Label>

        <ScrollFade
          orientation="horizontal"
          className="flex items-center gap-1.5 flex-nowrap min-w-0 flex-1 py-0.5"
        >
          {variables.map((variable) => {
            // A bound model control is used by the model setting, not the text.
            const isControl = isControlVariable(variable);
            const isUsed =
              isControl || isVariableUsedInText(variable.name, allText);
            return (
              <div
                key={variable.name}
                className={`inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-md text-xs font-medium group shrink-0 ${
                  isUsed
                    ? "bg-muted text-foreground border border-border"
                    : "bg-amber-50 dark:bg-amber-900/20 text-amber-700 dark:text-amber-300 border border-amber-200 dark:border-amber-800"
                }`}
              >
                {!isUsed && <AlertCircle className="w-3 h-3 shrink-0" />}
                {isControl && (
                  <SlidersHorizontal
                    className="w-3 h-3 shrink-0 text-muted-foreground"
                    aria-label="Model setting input"
                  />
                )}
                {/* A real button: the chip is the door to the variable editor,
                    so it must be reachable and openable from the keyboard and
                    announced as a control (PNI-000 F2). */}
                <button
                  type="button"
                  className={`cursor-pointer rounded-sm transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring ${
                    isUsed
                      ? "hover:text-primary"
                      : "hover:text-amber-900 dark:hover:text-amber-100"
                  }`}
                  onClick={() => handleEditClick(variable.name)}
                  title={
                    isUsed
                      ? "Click to edit"
                      : "Not used in messages — click to edit"
                  }
                  aria-label={
                    isUsed
                      ? `Edit variable ${variable.name}`
                      : `Edit variable ${variable.name} — not used in messages`
                  }
                >
                  {variable.name}
                </button>
                {isCustomDataBinding(variable.binding) && (
                  <CustomDataBindingSummary
                    binding={variable.binding}
                    className="max-w-[16rem]"
                  />
                )}
                <button
                  type="button"
                  onClick={() => handleRemove(variable.name)}
                  title="Remove variable"
                  aria-label={`Remove variable ${variable.name}`}
                  className="rounded-sm hover:text-destructive transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
                >
                  <X className="w-3 h-3" />
                </button>
              </div>
            );
          })}
        </ScrollFade>

        <div className="flex items-center gap-1 shrink-0">
          <button
            type="button"
            className="inline-flex items-center gap-1 px-2.5 py-1 text-xs text-muted-foreground hover:text-foreground hover:bg-muted rounded-md transition-colors"
            onClick={() => handleAddClick()}
          >
            <Plus className="w-3.5 h-3.5" />
            Add
          </button>

          <button
            type="button"
            className="inline-flex items-center gap-1 px-2.5 py-1 text-xs text-muted-foreground hover:text-foreground hover:bg-muted rounded-md transition-colors"
            onClick={() => openBatchImport({ agentId })}
            title="Batch add variables and context policies from a scope type"
          >
            <Layers className="w-3.5 h-3.5" />
            Batch add
          </button>
        </div>
      </div>

      {undeclaredNames.length > 0 && (
        <div className="mt-3 flex items-center gap-2 min-w-0">
          <Label className="text-xs text-muted-foreground shrink-0">
            Undeclared
            <span className="ml-1 text-foreground/60">
              ({undeclaredNames.length})
            </span>
          </Label>
          <ScrollFade
            orientation="horizontal"
            className="flex items-center gap-1.5 flex-nowrap min-w-0 flex-1 py-0.5"
          >
            {undeclaredNames.map((name) => (
              <button
                type="button"
                key={name}
                onClick={() => handleAddClick(name)}
                className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-md text-xs font-medium bg-red-50 dark:bg-red-900/20 text-red-700 dark:text-red-300 border border-red-200 dark:border-red-800 hover:bg-red-100 dark:hover:bg-red-900/30 transition-colors shrink-0"
                title={`Found in messages — click to define ${name}`}
              >
                <AlertCircle className="w-3 h-3 shrink-0" />
                <span>{name}</span>
                <Plus className="w-3 h-3 shrink-0 opacity-70" />
              </button>
            ))}
          </ScrollFade>
        </div>
      )}

    </>
  );
}
