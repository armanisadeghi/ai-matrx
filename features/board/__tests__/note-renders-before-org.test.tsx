/**
 * A NEW note tile shows its editor at once: it never waits for the organization lookup or for the
 * Draft folder. The draft is in the store on the tile's first render; the organization (the
 * resolver's answer — never one picked for the person) and the folder are settled behind it.
 * Red before: the tile showed a skeleton until `resolveOrganization()` returned.
 */
import { act, useState, useSyncExternalStore } from "react";
import { createRoot } from "react-dom/client";
import { configureStore } from "@reduxjs/toolkit";

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

let resolveOrg: (id: string) => void = () => {};
const resolveOrganization = jest.fn(() => new Promise<string>((r) => (resolveOrg = r)));
const placed: unknown[] = [];

jest.mock("@/lib/redux/hooks", () => {
  const { store } = jest.requireActual("./note-renders-before-org.store") as { store: import("@reduxjs/toolkit").EnhancedStore };
  return {
    useAppDispatch: () => (a: unknown) => {
      if (typeof a === "object" && a && "type" in a) store.dispatch(a as never);
      return { unwrap: async () => undefined };
    },
    useAppStore: () => store,
    useAppSelector: <T,>(sel: (s: unknown) => T) =>
      useSyncExternalStore(store.subscribe, () => sel(store.getState()), () => sel(store.getState())),
  };
});
jest.mock("@/features/notes/hooks/useNewNoteOrganization", () => ({ useNewNoteOrganization: () => resolveOrganization }));
jest.mock("@/features/notes/redux/thunks", () => ({
  initializeAutogeneratedNote: jest.fn(),
  placeAutogeneratedNote: (arg: unknown) => {
    placed.push(arg);
    return { type: "test/placed" };
  },
}));
jest.mock("@/features/notes/service/notesApi", () => ({ NotesAPI: { getById: jest.fn(), create: jest.fn() } }));
jest.mock("@/features/notes/components/NoteWorkspace", () => ({
  NoteWorkspace: ({ noteId }: { noteId: string }) => <div data-testid="editor">{noteId}</div>,
}));
jest.mock("@ai-matrx/design-system", () => ({ ErrorNotice: () => null }));

import { NoteItemBody } from "../items/NoteItemBody";
import type { NodeSource } from "../board/document";

void configureStore;

/** The board keeps what `onSource` says; so does this. */
function Tile({ onSource }: { onSource: (s: NodeSource) => void }) {
  const [source, setSource] = useState<NodeSource>({ kind: "entity", entity: "note", id: null } as NodeSource);
  return (
    <NoteItemBody
      tileId="t1"
      source={source}
      title="Note"
      tier={"full" as never}
      interacting={false}
      onSource={(next) => {
        onSource(next);
        setSource(next);
      }}
    />
  );
}

it("renders the editor before the organization resolves, then settles the placement", async () => {
  const host = document.createElement("div");
  document.body.appendChild(host);
  const root = createRoot(host);
  const onSource = jest.fn();
  await act(async () => {
    root.render(<Tile onSource={onSource} />);
  });
  // The resolver has NOT answered, and the editor is already there, on a draft the tile remembers.
  expect(resolveOrganization).toHaveBeenCalledTimes(1);
  expect(host.querySelector('[data-testid="editor"]')).not.toBeNull();
  expect(onSource.mock.calls[0][0]).toMatchObject({ meta: { draft: "1" } });
  expect(placed).toHaveLength(0);

  await act(async () => {
    resolveOrg("org-named-by-the-gate");
  });
  expect(placed).toHaveLength(1);
  expect(placed[0]).toMatchObject({ organizationId: "org-named-by-the-gate", folderName: "Draft" });
  await act(async () => root.unmount());
});
