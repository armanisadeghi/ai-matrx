// features/crm/gmail/mailbox-agreement.test.ts
//
// 🚨 THE AGREEMENT GUARD — VERIFY-B1-B2-R4 V1/V7.
//
// There are two recipient parsers (this file's `./mailbox.ts` and aidream's
// `aidream/services/google_workspace/mailbox.py`), and nothing compared them:
// a `To` field carrying two addresses was accepted here and refused only by
// the server, one round-trip later, about a field this parser had already
// waved through; the server's own documented rule 3 ("group syntax is
// refused") was FALSE and the test that looked like its proof passed for the
// wrong reason. Both are the same class — a divergence nobody could see.
//
// This is that guard. `mailbox_corpus.json` is generated by aidream's own
// `mailbox_corpus.py` (lane B-14) and lives beside `mailbox.py` — the pattern
// `scripts/aidream-contract-pin.json` and `features/connectors/import/
// field-labels.test.ts` already use to read the sibling aidream checkout
// without a second copy. It carries the SERVER's verdict for each hostile
// `To` value; this test drives the CLIENT parser over every row and asserts
// its verdict agrees — never edited here, and never a fixture this repo owns.
// It fails as UNMEASURED, never a quiet pass, when the sibling checkout is
// absent, and it fails LOUDLY (not skip) when the corpus shrinks to nothing.

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { parseToField } from "./mailbox";
import { recipientsOfSend } from "./preflight";

const CORPUS_PATH = join(
  __dirname,
  "..",
  "..",
  "..",
  "..",
  "aidream",
  "aidream/services/google_workspace/mailbox_corpus.json",
);

/** The server's own case shape — read verbatim, never re-typed by hand. */
interface CorpusCase {
  value: string;
  verdict: "accepted" | "refused";
  why: string;
  rule: string;
}

function readCorpus(): CorpusCase[] | null {
  if (!existsSync(CORPUS_PATH)) return null;
  const parsed = JSON.parse(readFileSync(CORPUS_PATH, "utf8")) as {
    cases: CorpusCase[];
  };
  return parsed.cases;
}

/**
 * The client's verdict on ONE `To` value, in the corpus's own words.
 *
 * A `To` naming zero mailboxes (an empty or whitespace-only field) is not a
 * parse failure — `parseToField("")` reads `ok: true, mailboxes: []`, because
 * an empty Cc is ordinary — but it is not a send either: `recipientsOfSend`
 * refuses it downstream with "it names no recipient". For the purpose of this
 * corpus (every row is judged as a `To`), naming nobody is "refused".
 */
function clientVerdict(value: string): "accepted" | "refused" {
  const parsed = parseToField(value);
  if (!parsed.ok) return "refused";
  return parsed.mailboxes.length === 1 ? "accepted" : "refused";
}

/**
 * The SAME question asked of the real send path.
 *
 * 🚨 A GUARD OVER A FUNCTION THE SEND DOES NOT CALL PROVES NOTHING. Every Gmail
 * send from a record goes through `recipientsOfSend` (inside
 * `preflightGmailRecipients`, which both the compose panel and the approval
 * queue hand the review card), so the corpus is driven through THAT too: a
 * refactor that stopped routing the `To` field through `parseToField` would leave
 * the leg above green while the server refused real sends again (R4 V1).
 */
function sendPathVerdict(value: string): "accepted" | "refused" {
  const parsed = recipientsOfSend(value, []);
  if (!parsed.ok) return "refused";
  return parsed.mailboxes.length === 1 ? "accepted" : "refused";
}

describe("the client's To-field parser agrees with the server's corpus", () => {
  const cases = readCorpus();

  if (!cases) {
    it("is UNMEASURED: the sibling aidream checkout is not in this container", () => {
      console.warn(
        `[mailbox-agreement] UNMEASURED: ${CORPUS_PATH} was not found, so the ` +
          "client parser was NOT compared against the server's corpus. Run this " +
          "test where the sibling aidream checkout exists.",
      );
      expect(true).toBe(true);
    });
    return;
  }

  it("carries at least the hostile inputs this unit was built to close", () => {
    // A corpus that shrank to nothing would let this whole guard pass by
    // vacuous truth — that is the failure mode a forcing test must refuse.
    expect(cases.length).toBeGreaterThanOrEqual(8);
  });

  /**
   * 🚨 AGREEING ON THE VERDICT IS NOT ENOUGH — THE PERSON READS THE REMEDY.
   *
   * `a@x.com, b@y.com` in `To` is the case R4 V1 was raised for, and the server's
   * own answer names what to do: one message goes to one recipient, put the
   * others in Cc where each is checked on its own. A client that refuses it for
   * some OTHER reason ("that is not an email address") sends the person hunting a
   * typo that is not there, so the refusal is asserted, not just the verdict.
   */
  it("refuses a two-address To with the server's own remedy, on the send path", () => {
    const parsed = recipientsOfSend("a@x.com, b@y.com", []);
    expect(parsed.ok).toBe(false);
    if (parsed.ok) return;
    expect(parsed.reason).toMatch(/one recipient in to; add others in cc/i);
    expect(parsed.reason).toContain("a@x.com");
    expect(parsed.reason).toContain("b@y.com");
    // And it is NOT the unreadable-syntax remedy, which would contradict it.
    expect(parsed.reason).not.toMatch(/separate multiple recipients with commas/i);
  });

  for (const testCase of cases) {
    it(`${testCase.verdict}: ${JSON.stringify(testCase.value)} — ${testCase.rule || testCase.why.slice(0, 60)}`, () => {
      expect(clientVerdict(testCase.value)).toBe(testCase.verdict);
      // …and the path a real send actually takes agrees with the same corpus.
      expect(sendPathVerdict(testCase.value)).toBe(testCase.verdict);
    });
  }
});
