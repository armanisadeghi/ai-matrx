/** Per-org capture subtree. Org id in the path keeps each workspace's
 *  captures a DISTINCT global folder path (the server allows one folder
 *  path per user, pinned to one org — a flat `Captures/Videos` cannot exist
 *  under two orgs). Falls back to the flat path when there is no active org
 *  (personal context).
 *
 *  Nested output still resolves to `personal` visibility: the
 *  `resolveDefaultVisibility` rule keys on the `Captures` prefix (a
 *  longest-prefix match), so `Captures/<org>/Videos` matches the same rule as
 *  the flat `Captures/Videos`. The org id in the path is filing, not access —
 *  personal-visibility files stay owner-gated regardless of org. */
export function folderForCaptures(
  kind: "photo" | "video" | "audio",
  orgId?: string | null,
): string {
  const leaf = kind === "photo" ? "Photos" : kind === "video" ? "Videos" : "Audio";
  const trimmed = typeof orgId === "string" ? orgId.trim() : "";
  if (trimmed) {
    return `${CloudFolders.CAPTURES}/${trimmed}/${leaf}`;
  }
  // No active org (personal context) — the flat/legacy path.
  return kind === "photo"
    ? CloudFolders.CAPTURES_PHOTOS
    : kind === "video"
      ? CloudFolders.CAPTURES_VIDEOS
      : CloudFolders.CAPTURES_AUDIO;
}

/** Per-item product-capture folder: `Product Captures/<orgId>/<leaf>`.
 *  `leaf` is the item's sanitized code (the QR value / SKU) when known at
 *  creation, else the item id — set ONCE at item creation and never renamed.
 *  Org id in the path for the same one-path-one-org server rule as
 *  `folderForCaptures`. Files here upload with explicit `visibility:
 *  "internal"` (org-wide access is the point of the surface), so the
 *  `resolveDefaultVisibility` prefix rules are deliberately not consulted. */
export function folderForProductCaptureItem(orgId: string, leaf: string): string {
  // Folder path segments: a scanned QR can carry separators/reserved chars --
  // collapse anything unsafe to single dashes. Callers pass the item id when
  // the code sanitizes to nothing.
  const safe = leaf
    .replace(/[^A-Za-z0-9._@-]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return `${CloudFolders.PRODUCT_CAPTURES}/${orgId.trim()}/${safe}`;
}

/**
 * Commerce-intake artifact folder for one asset (or the batch-level stream in
 * untracked mode — pass the batch id as `leaf`). Fixed at creation, NEVER
 * renamed — a QR/serial that arrives later lives on identifier rows only
 * (PROTOTYPE-CONCEPTS P13: the cloud path is never renamed).
 */
export function folderForIntakeAsset(
  orgId: string,
  batchId: string,
  leaf: string,
): string {
  const safe = leaf.replace(/[^A-Za-z0-9._@-]+/g, "-").replace(/^-+|-+$/g, "");
  return `${CloudFolders.COMMERCE_INTAKE}/${orgId.trim()}/${batchId.trim()}/${safe || batchId.trim()}`;
}

