#!/usr/bin/env node
/**
 * scripts/custom-tables/census-code-named-table-ids.mjs — WHICH CUSTOM TABLES DOES CODE NAME BY ID?
 *
 * The admin Custom tables page (/administration/database/custom-tables) never lets a table be selected
 * for bulk archive when a code path names it by id: a fixture, a safety net, a walk or a kernel that
 * code reaches by its uuid would break the moment it went to Trash. The store's own keeper signals
 * (`kept_by_the_app`, `custom.table_is_platform_context`) miss some of them — census 2026-10-02: of
 * Matrx System's 339 live tables they marked 22, and missed 7 platform tables (Merge Field
 * Declaration, Parity Floor, Parity Line, Rule conformance shape, and three "Example: …" seeds).
 *
 * This script reads every live table id (read-only, session pooler, through scripts/lib/pooled-db.mjs),
 * `git grep`s the tracked files of every code repo for them, and rewrites
 * features/administration/custom-tables/codeNamedTableIds.ts. Rerun it after adding a fixture.
 *
 *   node scripts/custom-tables/census-code-named-table-ids.mjs [--target production|clone]
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { CODE, FRONTEND, psqlRead } from "../lib/pooled-db.mjs";

const target = process.argv.includes("--target") ? process.argv[process.argv.indexOf("--target") + 1] : "production";
const REPOS = ["aidream", "matrx-frontend", "matrx-local", "matrx-extend", "matrx-sandbox"];
const OUT = join(FRONTEND, "features/administration/custom-tables/codeNamedTableIds.ts");

const read = psqlRead(
  target,
  `select t.id || '|' || o.name || '|' || coalesce(t.data ->> 'name', '')
     from custom.record t join iam.organizations o on o.id = t.organization_id
    where t.table_id = '11111111-0000-4000-8000-000000000001'::uuid -- the Table kernel; the read-only role may not call custom.table_kernel_id()
      and t.deleted_at is null`,
  { app: "custom-tables-census" },
);
if (!read.ok) {
  console.error(read.stderr || "The table read failed.");
  process.exit(1);
}
const rows = new Map(
  read.stdout.split("\n").filter(Boolean).map((line) => {
    const [id, org, ...name] = line.split("|");
    return [id, { org, name: name.join("|") }];
  }),
);
const dir = mkdtempSync(join(tmpdir(), "custom-tables-census-"));
const idsFile = join(dir, "ids.txt");
writeFileSync(idsFile, [...rows.keys()].join("\n"));

const named = new Set();
for (const repo of REPOS) {
  const cwd = join(CODE, repo);
  if (!existsSync(join(cwd, ".git"))) continue;
  const out = spawnSync(
    "git",
    ["grep", "-o", "-h", "-F", "-f", idsFile, "--", ".", ":!features/administration/custom-tables/codeNamedTableIds.ts"],
    { cwd, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
  );
  for (const id of out.stdout.split("\n")) if (id) named.add(id);
}

const lines = [...named]
  .sort()
  .map((id) => `  "${id}", // ${rows.get(id)?.org ?? "?"} — ${(rows.get(id)?.name ?? "?").replace(/\s+/g, " ")}`);
writeFileSync(
  OUT,
  `// features/administration/custom-tables/codeNamedTableIds.ts — GENERATED by
// scripts/custom-tables/census-code-named-table-ids.mjs (${new Date().toISOString().slice(0, 10)}, target ${target}).
// Do not edit by hand: rerun the script. Every live custom table whose id a tracked file of a code
// repo names. The admin Custom tables page never offers these for bulk archive.

export const CODE_NAMED_TABLE_IDS: ReadonlySet<string> = new Set([
${lines.join("\n")}
]);
`,
);
console.log(`${rows.size} live tables; ${named.size} named by code → ${OUT}`);
