#!/usr/bin/env npx tsx
/**
 * THE `reference` VARIANT GUARD - a global catalogue is RLS-filtered, read by every signed-in
 * member, and written only by a door.
 *
 * WHAT `rls_variant='reference'` IS. Reference data that belongs to no organization and no person:
 * `workbench.schema_templates` (the user-table schema templates), `context.template_scope_types`,
 * `context.template_context_items`, `platform.masterwork_run_kind`, `research.research_intent`.
 * Before the variant existed there was no canonical RLS for that shape, so each of them ran one of
 * two defects: RLS OFF with a bare `authenticated: SELECT` grant (the grant IS the security
 * model - `check:rls-on` ARM A), or a HAND-WRITTEN `USING (true)` policy, which db-rules 6d
 * forbids outright and `iam.verify_canonical` reports as drift for ever. db-rules names the class
 * and names the fix on `legal.wc_impairment_definition` (D265): the fix is the VARIANT, not the
 * policy.
 *
 * WHAT THIS GUARD PROVES, and it proves it by PLANTING THE REAL DEFECT ON A REAL TABLE IN THIS
 * DATABASE, never against a mock. Every arm runs inside a transaction that is ROLLED BACK, so
 * nothing it creates outlives the run.
 *
 *   RED  1  a reference table with a CLIENT WRITE POLICY is reported by name
 *   RED  2  a reference table with RLS switched OFF is reported by name
 *   RED  3  a reference table whose read lane carries a PREDICATE is reported by name
 *   RED  4  `iam.apply_rls(...,'reference')` REFUSES a table carrying organization_id (22023)
 *   RED  5  `iam.apply_rls(...,'reference')` REFUSES a table carrying created_by (22023)
 *   RED  6  the registry REFUSES `data_class='private'` on a reference token (23514)
 *   RED  7  a reference table that hands `anon` a SELECT key with no anonymous lane is reported
 *   GREEN 8  the same table, generated by `iam.apply_rls(...,'reference')`, passes every check
 *   GREEN 9  the generated table admits a real member's READ and refuses a real member's WRITE
 *   GREEN 10 the live reference catalogues carry no access/policy drift
 *
 * Arms 1-3 and 7 are the mutation proof this file would otherwise be missing: the object under
 * test is the SAME table that goes green in arm 8, so a verifier that had not been taught the
 * variant - the half-taught-verifier failure this variant was built to avoid - cannot pass them.
 *
 * Usage:  pnpm check:reference-variant
 */
import { loadDbEnv, connectDirect } from "./lib/direct-db";
import type pg from "pg";
import { exitAfterDrain } from "./lib/exit-after-drain";

const ESC = String.fromCharCode(27);
const C = {
  r: `${ESC}[31m`, g: `${ESC}[32m`, d: `${ESC}[2m`, b: `${ESC}[1m`, x: `${ESC}[0m`,
};
const SCHEMA = "workbench";
const TABLE = "zzz_reference_variant_selftest"; // scratch: created and rolled back, never committed
const TOKEN = "zzz_reference_variant_selftest";
const REL = `${SCHEMA}.${TABLE}`;

/**
 * The checks that decide whether a reference catalogue's ACCESS is canonical. The base-contract
 * checks a reference table cannot satisfy by construction (metadata, created_at, the mutation
 * trio) are deliberately NOT here: they are a different, older debt with a different remedy, and
 * folding them in would make this guard un-greenable and therefore uncitable.
 */
const ACCESS_CHECKS = [
  "rls_enabled", "policies_canonical", "bespoke_policy_present", "reference_open_read",
  "reference_no_client_write", "reference_has_no_scope_columns", "pub_read_anon",
  "class_lanes_match_policy", "data_class_set", "data_class_derivations",
  "default_list_scope_set", "visibility", "system_org_arm_respects_class",
  "base_organization_id", "base_org_not_null", "base_org_fk",
];

type Arm = { name: string; ok: boolean; got: string };
const arms: Arm[] = [];
function record(name: string, ok: boolean, got: string) {
  arms.push({ name, ok, got });
  console.log(`  ${ok ? `${C.g}PASS${C.x}` : `${C.r}FAIL${C.x}`}  ${name}\n        ${C.d}${got}${C.x}`);
}

/** Build the scratch catalogue and register it. `extraCols` plants a column the variant refuses. */
async function seed(cx: pg.Client, extraCols = "", dataClass = "organization") {
  await cx.query(`create table ${REL} (
      id uuid primary key default gen_random_uuid(),
      label text not null,
      sort_order integer not null default 0${extraCols ? ",\n      " + extraCols : ""})`);
  await cx.query(
    `insert into platform.entity_types
       (token, schema_name, table_name, label, rls_variant, data_class, data_class_reason, is_active)
     values ($1,$2,$3,'Reference variant self-test','reference',$4::platform.data_class,
             'Scratch table created by scripts/check-reference-variant.ts inside a rolled-back transaction. It exists for the length of one arm and is never committed.', true)`,
    [TOKEN, SCHEMA, TABLE, dataClass],
  );
  await cx.query(`insert into ${REL} (label) values ('Ergonomic assessment'),('Return-to-work plan')`);
}

/** Lock contention and serialization failures. Not a verdict - see `arm()`. */
const CONTENTION = new Set(["55P03", "40P01", "40001"]);
const notMeasured: string[] = [];

/**
 * Run one arm inside its own transaction and roll it back whatever happens.
 *
 * CONTENTION IS NOT A VERDICT. Every arm creates a table, writes `platform.entity_types` and runs
 * `iam.apply_rls`, all of which take locks on objects this platform writes constantly. A
 * concurrent release stole the lock twice while this file was being written, and an arm that dies
 * on a lock timeout has measured NOTHING - reporting it as a defect is a claim nobody made. So it
 * retries with backoff OUTSIDE the transaction, and when the lock never comes the arm is recorded
 * `[NOT MEASURED]`: never a pass, never a broken guard, and the run still exits non-zero, because
 * a guard that quietly skipped an arm is a guard you cannot cite. The remedy is different too -
 * re-run when the database is quiet.
 */
async function arm(cx: pg.Client, name: string, body: () => Promise<void>) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    await cx.query("begin");
    await cx.query("set local lock_timeout = '3s'");
    try {
      await body();
      return;
    } catch (err) {
      const code = (err as { code?: string }).code ?? "";
      if (CONTENTION.has(code) && attempt < 3) {
        console.log(`  ${C.d}contention (${code}) on "${name}" - attempt ${attempt}/3, retrying${C.x}`);
        await new Promise((r) => setTimeout(r, 400 * attempt));
        continue;
      }
      if (CONTENTION.has(code)) {
        notMeasured.push(name);
        console.log(`  ${C.d}[NOT MEASURED - contention]${C.x}  ${name}\n        ${C.d}${code} after 3 attempts; re-run when the database is quiet${C.x}`);
        return;
      }
      record(name, false, `the arm itself threw: ${err instanceof Error ? err.message : String(err)}`);
      return;
    } finally {
      await cx.query("rollback");
    }
  }
}

/** Every FAIL iam.verify_canonical reports for the scratch token. */
async function fails(cx: pg.Client): Promise<Map<string, string>> {
  const r = await cx.query<{ check_name: string; detail: string | null }>(
    `select check_name, detail from iam.verify_canonical($1,$2,$3) where status='FAIL'`,
    [SCHEMA, TABLE, TOKEN],
  );
  return new Map(r.rows.map((x) => [x.check_name, x.detail ?? ""]));
}

async function main(): Promise<number> {
  const env = loadDbEnv();
  if ("missing" in env) {
    console.error(`${C.r}No direct database connection - need ${env.missing.join(", ")}${C.x}`);
    return 2;
  }
  const cx = await connectDirect(env, "check:reference-variant");
  console.log(`${C.b}the reference variant${C.x} ${C.d}${env.user}@${env.host}/${env.database}${C.x}\n`);
  try {
    const N1 = "RED 1 - a client WRITE policy on a reference catalogue is reported";
    await arm(cx, N1, async () => {
      await seed(cx);
      await cx.query(`select iam.apply_rls($1,$2,$3,'reference')`, [SCHEMA, TABLE, TOKEN]);
      await cx.query(`grant insert on ${REL} to authenticated`);
      await cx.query(`create policy anybody_writes on ${REL} for insert to authenticated with check (true)`);
      const f = await fails(cx);
      const d = f.get("reference_no_client_write");
      record(N1, !!d && d.includes("anybody_writes") && d.includes("authenticated:INSERT"),
        d ? `reference_no_client_write: ${d.slice(0, 160)}` : `NOT REPORTED - fails were: ${[...f.keys()].join(", ") || "(none)"}`);
    });

    const N2 = "RED 2 - a reference catalogue with RLS switched OFF is reported";
    await arm(cx, N2, async () => {
      await seed(cx);
      await cx.query(`select iam.apply_rls($1,$2,$3,'reference')`, [SCHEMA, TABLE, TOKEN]);
      await cx.query(`alter table ${REL} disable row level security`);
      const f = await fails(cx);
      record(N2, f.has("rls_enabled"),
        f.has("rls_enabled")
          ? "rls_enabled: FAIL - with RLS off the grant is the entire security model (check:rls-on ARM A)"
          : `NOT REPORTED - fails were: ${[...f.keys()].join(", ") || "(none)"}`);
    });

    const N3 = "RED 3 - a reference read lane carrying a PREDICATE is reported";
    await arm(cx, N3, async () => {
      await seed(cx);
      await cx.query(`select iam.apply_rls($1,$2,$3,'reference')`, [SCHEMA, TABLE, TOKEN]);
      await cx.query(`drop policy ref_all_members_read on ${REL}`);
      await cx.query(`create policy ref_all_members_read on ${REL} for select to authenticated using (sort_order > 0)`);
      const f = await fails(cx);
      const d = f.get("reference_open_read");
      record(N3, !!d && d.includes("carries a predicate"),
        d ? `reference_open_read: ${d.slice(0, 160)}` : `NOT REPORTED - fails were: ${[...f.keys()].join(", ") || "(none)"}`);
    });

    for (const [col, label, n] of [
      ["organization_id uuid", "organization_id", 4],
      ["created_by uuid", "created_by", 5],
    ] as const) {
      const name = `RED ${n} - iam.apply_rls refuses a reference table carrying ${label}`;
      await arm(cx, name, async () => {
        await seed(cx, col);
        let code = "(no error)";
        let msg = "the generator ACCEPTED it";
        try {
          await cx.query(`select iam.apply_rls($1,$2,$3,'reference')`, [SCHEMA, TABLE, TOKEN]);
        } catch (e) {
          const pe = e as { code?: string; message?: string };
          code = pe.code ?? "(none)";
          msg = pe.message ?? "";
        }
        record(name, code === "22023" && msg.includes(label), `${code}: ${msg.slice(0, 160)}`);
      });
    }

    const N6 = "RED 6 - the registry refuses data_class=private on a reference token";
    await arm(cx, N6, async () => {
      let code = "(no error)";
      let msg = "the registry ACCEPTED it";
      try {
        await seed(cx, "", "private");
      } catch (e) {
        const pe = e as { code?: string; message?: string };
        code = pe.code ?? "(none)";
        msg = pe.message ?? "";
      }
      record(N6, code === "23514" && msg.includes("entity_types_reference_is_not_private_ck"),
        `${code}: ${msg.slice(0, 160)}`);
    });

    // ARM 7 IS PROVED IN TWO HALVES, AND THE FIRST HALF IS WHY.
    // The obvious plant - generate the catalogue, then `grant select on it to anon` - CANNOT BE
    // BUILT on this database, and that is the point: the live event trigger
    // `iam.anon_key_needs_a_class_lane` (0895) rolls back any grant that hands `anon` a key to a
    // token whose class emits no anonymous lane. Weakening that trigger to make a test green would
    // be deleting a live defence to make a test pass. So the arm asserts the two things that are
    // true today: the shape CANNOT BE BORN through a grant, and the classifier still reports it
    // when it exists by another route (a key issued before the token was registered, which the
    // trigger's registry-joined census cannot see). If that event trigger is ever dropped, half A
    // goes red and says to restore the live plant.
    const N7a = "RED 7a - the live DDL guard refuses an anon key on a members-only catalogue";
    await arm(cx, N7a, async () => {
      await seed(cx);
      await cx.query(`select iam.apply_rls($1,$2,$3,'reference')`, [SCHEMA, TABLE, TOKEN]);
      let code = "(no error)";
      let msg = "the grant STUCK - iam.anon_key_needs_a_class_lane did not fire";
      try {
        await cx.query(`grant select (label) on ${REL} to anon`);
      } catch (e) {
        const pe = e as { code?: string; message?: string };
        code = pe.code ?? "(none)";
        msg = pe.message ?? "";
      }
      record(N7a, code === "22023" && msg.includes("emits NO anonymous lane"), `${code}: ${msg.slice(0, 160)}`);
    });

    const N7b = "RED 7b - the classifier reports an anon key that reached a reference catalogue";
    await arm(cx, N7b, async () => {
      // The key is issued BEFORE the token is registered, so the event trigger's registry-joined
      // census cannot see the table and the grant survives. This is the only shape in which the
      // defect can exist on this database, and it is the shape the classifier must catch.
      await cx.query(`create table ${REL} (
          id uuid primary key default gen_random_uuid(),
          label text not null,
          sort_order integer not null default 0)`);
      await cx.query(`grant select on ${REL} to anon`);
      await cx.query(
        `insert into platform.entity_types
           (token, schema_name, table_name, label, rls_variant, data_class, data_class_reason, is_active)
         values ($1,$2,$3,'Reference variant self-test','reference','organization',
                 'Scratch table created by scripts/check-reference-variant.ts inside a rolled-back transaction.', true)`,
        [TOKEN, SCHEMA, TABLE],
      );
      await cx.query(`alter table ${REL} enable row level security`);
      await cx.query(`create policy ref_all_members_read on ${REL} for select to authenticated using (true)`);
      const f = await fails(cx);
      const d = f.get("pub_read_anon");
      record(N7b, !!d && d.includes("anon holds a SELECT key"),
        d ? `pub_read_anon: ${d.slice(0, 160)}` : `NOT REPORTED - fails were: ${[...f.keys()].join(", ") || "(none)"}`);
    });

    const N8 = "GREEN 8 - the generated reference catalogue passes every access check";
    await arm(cx, N8, async () => {
      await seed(cx);
      await cx.query(`select iam.apply_rls($1,$2,$3,'reference')`, [SCHEMA, TABLE, TOKEN]);
      const r = await cx.query<{ check_name: string; detail: string | null }>(
        `select check_name, detail from iam.verify_canonical($1,$2,$3)
          where check_name = any($4) and status = 'FAIL'`,
        [SCHEMA, TABLE, TOKEN, ACCESS_CHECKS],
      );
      const pols = await cx.query<{ polname: string }>(
        `select polname from pg_policy where polrelid = $1::regclass order by polname`, [REL]);
      const names = pols.rows.map((p) => p.polname).join(",");
      record(N8, r.rowCount === 0 && names === "ref_all_members_read,svc_all",
        r.rowCount === 0
          ? `0 FAILs across ${ACCESS_CHECKS.length} access checks; policies = ${names}`
          : `${r.rowCount} FAIL(s): ${r.rows.map((x) => `${x.check_name}: ${(x.detail ?? "").slice(0, 80)}`).join(" | ")}`);
    });

    const N9 = "GREEN 9 - a real member READS the catalogue and CANNOT write it";
    await arm(cx, N9, async () => {
      await seed(cx);
      await cx.query(`select iam.apply_rls($1,$2,$3,'reference')`, [SCHEMA, TABLE, TOKEN]);
      const who = await cx.query<{ id: string }>(
        `select id::text as id from auth.users where email = 'admin@admin.com' limit 1`);
      if (who.rowCount === 0) { record(N9, false, "admin@admin.com not found on this database"); return; }
      await cx.query("savepoint seat");
      await cx.query("set local role authenticated");
      await cx.query(`select set_config('request.jwt.claims', $1, true)`,
        [JSON.stringify({ sub: who.rows[0]!.id, role: "authenticated" })]);
      const read = await cx.query<{ n: string }>(`select count(*)::text as n from ${REL}`);
      let writeErr = "(the write SUCCEEDED)";
      try {
        await cx.query(`insert into ${REL} (label) values ('a member wrote this')`);
      } catch (e) {
        const pe = e as { code?: string; message?: string };
        writeErr = `${pe.code}: ${pe.message}`;
      }
      await cx.query("rollback to savepoint seat");
      await cx.query("reset role");
      record(N9, read.rows[0]!.n === "2" && writeErr.startsWith("42501"),
        `admin@admin.com reads ${read.rows[0]!.n}/2 rows; a direct INSERT is refused by name - ${writeErr.slice(0, 110)}`);
    });

    const N10 = "GREEN 10 - every live reference catalogue carries no access drift";
    const live = await cx.query<{ token: string; check_name: string; detail: string | null }>(
      `select et.token, v.check_name, v.detail
         from platform.entity_types et
         cross join lateral iam.verify_canonical(et.schema_name, et.table_name, et.token) v
        where et.is_active and et.rls_variant = 'reference' and v.status = 'FAIL'
          and v.check_name = any($1)
        order by et.token, v.check_name`,
      [ACCESS_CHECKS],
    );
    const n = await cx.query<{ n: string }>(
      `select count(*)::text as n from platform.entity_types where is_active and rls_variant='reference'`);
    record(N10, live.rowCount === 0 && Number(n.rows[0]!.n) > 0,
      live.rowCount === 0
        ? `${n.rows[0]!.n} live reference token(s), 0 access FAILs`
        : live.rows.map((x) => `${x.token}/${x.check_name}: ${(x.detail ?? "").slice(0, 70)}`).join(" | "));
  } finally {
    await cx.end().catch(() => { /* the connection is already gone */ });
  }

  const bad = arms.filter((a) => !a.ok);
  console.log("");
  if (notMeasured.length > 0) {
    console.log(`${C.r}[NOT MEASURED - contention] ${notMeasured.length} arm(s) never got their lock: ${notMeasured.join("; ")}.${C.x}`);
    console.log(`${C.d}Nothing is claimed about them. Re-run when the database is quiet.${C.x}`);
  }
  if (bad.length === 0 && notMeasured.length === 0) {
    console.log(`${C.g}OK${C.x} ${C.b}the reference variant fails when it should and passes when it should${C.x} ${C.d}(${arms.length} arms)${C.x}`);
    return 0;
  }
  console.log(`${C.r}${bad.length} of ${arms.length} arm(s) did not hold: ${bad.map((a) => a.name).join("; ")}${C.x}`);
  return 1;
}

main().then((c) => exitAfterDrain(c)).catch((e) => { console.error(e); exitAfterDrain(2); });
