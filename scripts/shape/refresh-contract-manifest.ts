#!/usr/bin/env tsx
/**
 * refresh-contract-manifest — regenerates the checked-in snapshot of the
 * aidream generated-contract inventory (scripts/shape/content-ir-contract-manifest.json).
 *
 * The aidream publisher (`scripts/sync_content_ir_contracts.py --json`) is the
 * ONE inventory of framed runtime contracts (action_io / tool_io / workflow_io /
 * agent_io). This script shells out to it (read-only mode — the publisher never
 * writes without `--apply`) and persists a slim, deterministic snapshot so the
 * frontend coverage gates (crosswalk + shape doctor) can run on machines where
 * aidream is NOT checked out.
 *
 *   pnpm check:shapes:manifest:refresh     # regenerate the snapshot
 *   AIDREAM_ROOT=/path/to/aidream …        # override the default sibling path
 *
 * Degrades LOUDLY, never silently: if aidream is missing or the publisher
 * fails, this exits non-zero with a scream — the committed snapshot stays as
 * the last known-good inventory and check-shapes keeps consuming it.
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import type {
  ContractManifestEntry,
  ContractManifestSnapshot,
} from "./contract-manifest-format";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SNAPSHOT_PATH = resolve(ROOT, "scripts/shape/content-ir-contract-manifest.json");
const AIDREAM_ROOT = process.env.AIDREAM_ROOT ?? resolve(ROOT, "..", "aidream");
const PUBLISHER = "scripts/sync_content_ir_contracts.py";

function fail(message: string): never {
  console.error(`\x1b[31m\x1b[1mCONTRACT MANIFEST REFRESH FAILED:\x1b[0m ${message}`);
  console.error(
    "The committed scripts/shape/content-ir-contract-manifest.json is UNCHANGED (last known-good). " +
      "Fix aidream access (AIDREAM_ROOT) and re-run — do NOT hand-edit the snapshot.",
  );
  process.exit(1);
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

function asString(v: unknown, field: string, i: number): string {
  if (typeof v !== "string") fail(`manifest entry ${i}: "${field}" is not a string`);
  return v;
}

function main(): void {
  if (!existsSync(resolve(AIDREAM_ROOT, PUBLISHER))) {
    fail(
      `aidream publisher not found at ${resolve(AIDREAM_ROOT, PUBLISHER)} — ` +
        `is aidream checked out? (set AIDREAM_ROOT to override the default sibling path)`,
    );
  }

  let raw: string;
  try {
    raw = execFileSync("uv", ["run", "python", PUBLISHER, "--json"], {
      cwd: AIDREAM_ROOT,
      encoding: "utf8",
      maxBuffer: 512 * 1024 * 1024,
      stdio: ["ignore", "pipe", "inherit"],
    });
  } catch (err) {
    fail(`publisher run failed: ${err instanceof Error ? err.message : String(err)}`);
  }

  // uv may prefix build noise; the JSON document starts at the first "{".
  const start = raw.indexOf("{");
  if (start < 0) fail("publisher emitted no JSON document");
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw.slice(start));
  } catch (err) {
    fail(`publisher JSON unparseable: ${err instanceof Error ? err.message : String(err)}`);
  }
  if (!isRecord(parsed) || !Array.isArray(parsed.manifest)) {
    fail(`publisher JSON has no "manifest" array — did --json output change shape?`);
  }

  const contracts: ContractManifestEntry[] = parsed.manifest.map((entry, i) => {
    if (!isRecord(entry)) fail(`manifest entry ${i} is not an object`);
    const version = entry.version;
    if (typeof version !== "number") fail(`manifest entry ${i}: "version" is not a number`);
    return {
      kind: asString(entry.kind, "kind", i),
      family: asString(entry.family, "family", i),
      direction: asString(entry.direction, "direction", i),
      source_id: asString(entry.source_id, "source_id", i),
      source_name: asString(entry.source_name, "source_name", i),
      label: asString(entry.label, "label", i),
      version,
      fingerprint: asString(entry.fingerprint, "fingerprint", i),
    };
  });
  if (contracts.length === 0) fail("publisher manifest is EMPTY — refusing to write a zero snapshot");
  contracts.sort((a, b) => a.kind.localeCompare(b.kind));

  const families: Record<string, number> = {};
  for (const c of contracts) families[c.family] = (families[c.family] ?? 0) + 1;
  const sortedFamilies = Object.fromEntries(
    Object.entries(families).sort(([a], [b]) => a.localeCompare(b)),
  );

  const hash = createHash("sha256").update(JSON.stringify(contracts)).digest("hex").slice(0, 12);
  const snapshot: ContractManifestSnapshot = {
    _generated:
      "GENERATED by pnpm check:shapes:manifest:refresh (scripts/shape/refresh-contract-manifest.ts) — do not hand-edit.",
    generated_for: `${contracts.length}-contracts+${hash}`,
    source: `aidream ${PUBLISHER} --json (read-only inventory mode)`,
    families: sortedFamilies,
    contracts,
  };

  writeFileSync(SNAPSHOT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(
    `✓ contract manifest snapshot: ${contracts.length} contracts (${Object.entries(sortedFamilies)
      .map(([f, n]) => `${f}=${n}`)
      .join(", ")}) → ${SNAPSHOT_PATH}`,
  );
}

main();
