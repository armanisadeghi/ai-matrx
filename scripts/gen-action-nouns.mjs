/**
 * gen-action-nouns.mjs — generate the slim client-side noun table from the
 * mirrored action-catalog manifest (docs/protocol/matrx_actions_catalog.generated.json).
 *
 * Output: features/matrx-envelope/catalog-nouns.generated.ts — token → { table,
 * title_column, identity_fields, label } + the alias map. This is what lets the
 * reference resolvers derive a generic resolver for ANY registered noun with
 * zero hand edits (the 900-line hand RESOLVERS map is now the overlay for
 * bespoke rendering only).
 *
 * Run via `pnpm gen:action-nouns` — invoked automatically by
 * check-protocol-sync --fix after the manifest mirror updates. Never hand-edit
 * the output.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = process.cwd();
const MANIFEST = resolve(ROOT, "docs/protocol/matrx_actions_catalog.generated.json");
const OUT = resolve(ROOT, "features/matrx-envelope/catalog-nouns.generated.ts");

const catalog = JSON.parse(readFileSync(MANIFEST, "utf-8"));

const nouns = {};
for (const n of catalog.nouns) {
  nouns[n.noun] = {
    table: n.table || null,
    title_column: n.title_column ?? null,
    identity_fields: n.identity_fields ?? [],
    label: n.label || n.noun,
  };
}

const body = `/**
 * GENERATED by scripts/gen-action-nouns.mjs from
 * docs/protocol/matrx_actions_catalog.generated.json — DO NOT EDIT.
 * Regenerate: pnpm gen:action-nouns (runs with check-protocol-sync --fix).
 */

export interface CatalogNounEntry {
  /** "schema.table" (bare name = public); null for derived shapes. */
  table: string | null;
  title_column: string | null;
  /** Required fields of the registered reference item model. */
  identity_fields: string[];
  label: string;
}

export const CATALOG_NOUNS: Record<string, CatalogNounEntry> = ${JSON.stringify(nouns, null, 1)} as const;

/** Legacy wire noun → canonical entity token (server-published). */
export const CATALOG_ALIASES: Record<string, string> = ${JSON.stringify(catalog.aliases ?? {}, null, 1)} as const;
`;

writeFileSync(OUT, body, "utf-8");
console.log(`wrote features/matrx-envelope/catalog-nouns.generated.ts (${Object.keys(nouns).length} nouns)`);
