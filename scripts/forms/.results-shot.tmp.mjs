import { execSync } from "node:child_process";
import { chromium } from "playwright";
const out = execSync("pnpm -s dev-login", { encoding: "utf8" });
const url = out.match(/OPEN\s*:\s*(\S+)/)[1];
const origin = new URL(url).origin;
const make = `/make?make=form&table=50da9456-dfe4-4e48-b076-9dffaacfa422&id=47209f01-8d15-421a-be1a-bd3de4578a18&org=11d47e36-4b1e-46b8-bdf6-8ef928b730fb`;
const signIn = url.replace(/next=[^&]*/, "next=" + encodeURIComponent(make));
const b = await chromium.launch({ headless: true });
const p = await b.newPage({ viewport: { width: 1500, height: 1300 } });
await p.goto(signIn, { waitUntil: "domcontentloaded", timeout: 180000 });
await p.waitForURL(/\/make/, { timeout: 180000 }).catch(() => {});
const toggle = p.locator("[data-records-form-results-toggle]");
await toggle.waitFor({ timeout: 180000 });
await p.screenshot({ path: "/tmp/typeform-builder.png" });
await toggle.click();
const panel = p.locator("[data-records-form-results]");
await panel.waitFor({ timeout: 90000 });
await p.waitForTimeout(3000);
const text = await panel.innerText();
console.log("RESULTS-TEXT " + text.replace(/\s+/g, " ").slice(0, 400));
await p.screenshot({ path: "/tmp/typeform-builder-results.png", fullPage: true });
await b.close();
