/**
 * THE LIST — every place outside the /data screen that reads or writes the older tables
 * (`workbench.udt_dataset*` and their public doors), CUTOVER-PLAN rev 3 §1 (72 rows: F1–F30,
 * A1–A22, E1–E4, L1, D1–D15), plus the places the census itself found that the plan did not list.
 *
 * Every row says HOW it is known to be repointed — a check `census.ts` runs every time (an import
 * or call site that must be there, an older door that must NOT be there, a released tag, a live
 * read of the database) — or that it changes at the switch itself by design, or that it needs
 * nothing. Nothing here is a status someone typed: a `repointed` row whose checks fail is OPEN.
 *
 *   disposition `repointed`  → status `proven` when every proof passes, else `open`
 *   disposition `flip_time`  → status `flip_time` (repointed, archived or regenerated BY the flip;
 *                              does not block the switch). Any proof it carries must still pass.
 *   disposition `nothing`    → status `nothing` (out of scope, not the older store, or already
 *                              the replacement). Any proof it carries must still pass.
 *
 * `claims` are the runtime files (globs, per repo) this row answers for. The census scans every
 * runtime file in matrx-frontend, aidream, matrx-extend and matrx-local for older-door names (code
 * only, comments stripped); a file that names one and is claimed by no row is an UNLISTED finding,
 * and any unlisted finding keeps the switch's fact FALSE — a new integration nobody inventoried is
 * exactly the silent writer this census exists to catch.
 *
 * Lane CUTOVER-CENSUS, 2026-09-25. Edit a row only with the evidence that changed it.
 */

export type Repo = "matrx-frontend" | "aidream" | "matrx-extend" | "matrx-local";

export type Proof =
  /** `pattern` (regex, code only) appears in `file` — optionally only between `from` and `to`. */
  | { kind: "contains"; repo: Repo; file: string; pattern: string; from?: string; to?: string; says: string }
  /** `pattern` (regex, code only) appears in none of `files` (globs). */
  | { kind: "lacks"; repo: Repo; files: string[]; pattern: string; says: string }
  /** No runtime file of `repo` outside `except` (globs) matches `pattern` (regex, code only). */
  | { kind: "nowhere"; repo: Repo; pattern: string; except: string[]; says: string }
  /** No runtime file of `repo` imports a module matching `module` (regex on the import specifier). */
  | { kind: "no_importer"; repo: Repo; module: string; says: string }
  /** A release tag of `repo` contains `commit`. */
  | { kind: "released"; repo: Repo; commit: string; says: string }
  /** A live read: one row `(ok boolean, detail text)`. */
  | { kind: "db"; sql: string; says: string };

export interface Integration {
  id: string;
  repo: Repo | "database";
  what: string;
  /** CUTOVER-PLAN rev 3's "Today" column, for the record: Y / R / G / —. */
  plan: "Y" | "R" | "G" | "—" | "found";
  disposition: "repointed" | "flip_time" | "nothing";
  /** Why this disposition, in one line. */
  why: string;
  /** What the owner reads when this row is open: plain English, no paths. */
  plain: string;
  /** Who fixes it when it is open: the file(s) to change. */
  owner: string;
  claims?: Partial<Record<Repo, string[]>>;
  proofs?: Proof[];
}

