const exists = (schema: string, fn: string) =>
  `select exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                   where n.nspname = '${schema}' and p.proname = '${fn}') as ok,
          '${schema}.${fn} is live on this database' as detail`;

