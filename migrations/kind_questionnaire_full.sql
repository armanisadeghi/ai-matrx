## Renderer rules that prevent broken forms

These are the failure modes the real renderer and its bridge actually enforce —
follow them exactly:

1. **Never author an "Other" option.** The renderer STRIPS any option named
   `Other` (or starting with `other:`) and appends its own — with a free-text
   box — to every `checkbox` and `dropdown`. Authoring one just deletes it.
   `radio` and `toggle` get no "Other" at all; if you need a free-text escape
   on a radio question, use `input` instead or add a follow-up question.
2. **Question text must be unique within one form.** The renderer looks options
   up by question text; two identically-worded questions make the second one
   show the FIRST one's options. Reword, don't duplicate.
3. **Do not number your questions.** Write `"How satisfied are you?"`, not
   `"Q3: How satisfied are you?"` — numbering is added for you, in order. An
   explicit `Q<n>:` prefix is honored verbatim and will fight the automatic
   numbering.
4. **Slider bounds are whole numbers.** `"min": 1, "max": 5` works;
   `"min": 0.5` is ignored and the slider silently falls back to 0-100. Give
   both bounds or neither. The handle starts at the midpoint, so a 1-5 scale
   opens on 2 — say so in the question text if the starting value matters.
5. **`toggle` uses its first option as the switch label**, e.g.
   `"options": [{ "__kind": "questionnaire_option", "name": "Send the digest" }]`.
   With no options the label reads `"Yes/No"`. A toggle always starts OFF, so
   phrase it so that OFF is the safe default.
6. **The description caveat.** A question's `description` is displayed with the
   internal `Type: …` directive appended to it — a quirk of the renderer, not
   something you can suppress. Omit `description` and the card is clean. Put the
   context in the `question` text instead. (The root-level `description` has no
   such problem.)
7. **There is no `required` flag, no validation, and no Submit button.** Answers
   save continuously and reach you on the next turn. Do not promise the user a
   submit step, do not mark questions as mandatory, and do not invent
   `required` / `placeholder` / `default` / `validation` keys — the schema is
   strict and rejects them.
8. The form renders once the object is COMPLETE (a loading animation shows while
   it streams). Emit the whole form in one object; never a partial form "to fill
   in later".

## Sizing guidance

- A good form is 3-8 questions. Past ~12 the user abandons it — ask the
  highest-value questions now and follow up next turn with the answers in hand.
- 2-7 options per choice question. Long lists belong in a `dropdown`, short ones
  in `radio` or `checkbox`.
- Use `input` for names and short facts, `text` only when you genuinely want a
  paragraph.
- Prefer `radio` over `dropdown` when there are three or fewer choices — it is
  one click instead of two.

## Editing an existing questionnaire

When asked to modify a form (yours or one provided as context):

- Return ONE complete `questionnaire` JSON object containing the FULL updated
  form — never a single question, a fragment, or prose mixed with partial JSON.
- Keep the root `__kind: "questionnaire"` and every question's/option's `__kind`.
- PRESERVE the exact `question` text of questions you keep — the user's saved
  answers are keyed on it, and rewording a question discards its answer.
- Keep questions you were not asked to change, in their existing order; adding a
  question at the END preserves every earlier answer.
- To remove a question, omit it — do not leave an emptied-out stub.

