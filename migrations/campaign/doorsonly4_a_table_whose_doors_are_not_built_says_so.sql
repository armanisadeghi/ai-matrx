-- chair-step: the two patches below are `select`-driven DO blocks that read a function body from
-- pg_get_functiondef and re-install it -- the canonical route, which the additive allow-list
-- cannot read. Their replacement text contains no DROP, REVOKE or TRUNCATE; the chair step is
-- for the DO-block shape itself.
--
-- 🚨 A TABLE WHOSE DOORS ARE NOT BUILT YET SAYS SO, IN THE REGISTRY, WITH A REASON AND AN OWNER.
--
-- THE DEFECT THIS CLOSES, AND IT WAS THIS LANE'S OWN. Declaring `platform` doors-only made the
-- generator stop emitting client write lanes for EVERY table in the schema. Regenerating the
-- schema then closed `platform.saved_view` and `platform.rulebook` -- two of the three tables
-- DOORS-ONLY-3 deliberately left open because they are the MANY-WRITER cases: twelve write call
-- sites for saved views across five files in two repos, nine for the Masterwork rulebook, and
-- none of them moved to a door yet. For eleven minutes saving a view and editing a Masterwork
-- rulebook answered 42501. That is the exact failure the campaign's own rule forbids: "no table
-- has its callers moved with the write still open, or the write closed with callers not moved."
--
-- WHY A DECLARATION AND NOT A HAND-RESTORED GRANT. Re-granting by hand would last until the next
-- `iam.apply_rls` -- which `platform.provision` calls -- and would break these two tables again,
-- silently, on a day nobody connected the two events. The generator has to KNOW. So the state
-- "this table belongs in a doors-only schema and its doors are not built yet" becomes a row with
-- a reason and an owning lane, which the generator reads and ANNOUNCES every time it honours it.
-- A stand-in that announces itself with a remedy, rather than a grant somebody has to remember.
--
-- IT IS A LADDER DOWN, NEVER UP. A row here only ever KEEPS a table generating what it already
-- generated. It cannot open a table that is closed, it cannot reach a schema that is not declared
-- doors-only, and deleting the row is the whole of the cutover's last step -- which is why the
-- doors-only guard's baseline still counts every triple these three tables carry.
--
-- ADDITIVE: one new table, one new function, three rows, and two generator bodies patched to read
-- them. No grant, no policy, no table regenerated by this file.
-- Inverse: migrations/inverse/doorsonly4_a_table_whose_doors_are_not_built_says_so.inverse.sql

create table if not exists platform.doors_only_pending_cutover (
  schema_name  text not null,
  table_name   text not null,
  reason       text not null,
  owner_lane   text not null,
  declared_at  timestamptz not null default now(),
  primary key (schema_name, table_name)
);

comment on table platform.doors_only_pending_cutover is
  'Tables in a doors-only schema whose SECURITY DEFINER doors are NOT BUILT YET. The generator '
  'keeps emitting their client write lanes and says so out loud on every run. A row is a debt '
  'with an owner, not an exemption: it can only KEEP what a table already generated, it cannot '
  'open a closed table, and the doors-only guard still counts every triple the table carries. '
  'Deleting the row is the last step of that table''s cutover, taken in the SAME commit that '
  'moves its callers to the door (DOORS-ONLY-4).';

