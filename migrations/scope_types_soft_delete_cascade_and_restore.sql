-- Scope types: removal CASCADES to their parts, and a removal can be UNDONE.
--
-- THE DEFECT (F6, reproduced on production by two independent reviewers
-- 2026-09-18, root-caused 2026-09-21). Deleting a scope type from its own page
-- left it on `/organizations/<org>/scopes` as a card with an "Open" door after
-- a full reload, and left its `context.context_items` rows LIVE with
-- `deleted_at IS NULL` under a parent whose `deleted_at` was set. The card was
-- the frontend's boot tree reading `context.scope_types` with no `deleted_at`
-- filter at all (fixed in features/scopes/service/scopesService.ts). The
-- orphans are this file: `context.scope_types` was never registered with the
-- platform soft-delete cascade, so `public.delete_scope_type` hand-wrote its
-- own child updates — it stamped `context.scopes.deleted_at` and flipped
-- `context.context_items.is_active` to false, which is a DIFFERENT column with
-- a DIFFERENT meaning (a person's own on/off switch) and no way back.
--
-- WHAT THIS FILE DOES
--   1. Rules on EVERY inbound foreign key of `context.scope_types` and
--      `context.scopes` — none skipped, each with its reason, the same shape as
--      the mandate edges in platform_soft_delete_cascade.sql.
--   2. Backfills the orphans the hand-written cascade already created.
--   3. Replaces `public.delete_scope_type` so it stops hand-cascading: the
--      generic trigger does it, on one shared timestamp, which is what makes an
--      exact restore possible.
--   4. Adds `public.restore_scope_type`, so the archive disclosure the scopes
--      page now carries is a door and not a dead end.
--
-- based-on lines are generated by `pnpm db:based-on`; see the header block
-- below this comment.

