-- E-sign C7 — migration 2 of 6 (register item HRB-011, lane core-c7-esign).
--
-- THE CONFIGURATION REGISTER (§7), THE CONSENT DISCLOSURE CATALOG (§4.1), AND THE CERTIFICATE
-- SIGNING KEY (§2.6). Nothing in §7 may be a constant in code, and every envelope freezes its
-- resolved values into config_snapshot at send so a later change never rewrites history.
--
-- Authority: SPEC-ESIGN §2.6, §4.1, §7. Applied live as `esign_02_config_and_disclosure`. Idempotent.
--
-- ===================================================================================
-- RECORDED TECHNICAL DECISIONS (EXECUTION §8)
--
-- 1. §7 SAYS TO BUILD THIS TABLE, AND THIS TABLE IS DELIBERATELY TEMPORARY. "No general
--    configuration registry exists today … Until it lands, e-sign reads them from a single seeded
--    definition table of its own WITH THE SAME KEY NAMES, so the cutover is a data move, not a
--    rewrite." Every key below is spelled exactly as §7 spells it, so
--    platform.configuration_definition can adopt these rows verbatim when AD-12 ships.
--
-- 2. THE DEFAULT VALUE IS `jsonb`, NOT A TYPED SCALAR COLUMN, and that is not laziness — it is the
--    blocker HRB-004, HRB-006 and HRB-007 each hit independently. The live knob store's value_type
--    CHECK admits only number/integer/boolean/string/enum, so §7's array (`reminder.cadence_days`
--    = [3,7,12]) and its time range (`reminder.quiet_hours`) are not expressible there at all. A
--    jsonb value expresses every §7 row without inventing a sixth knob store.
--
-- 3. OVERRIDABILITY IS DATA, INCLUDING ITS DIRECTION. §7 does not say only "org may override" — it
--    says "org may lower only", "org (raise only)", "floor 30", and "not settable to anything else,
--    at any level". Those are four different rules and a boolean cannot carry them, so the
--    definition row carries `overridable_by`, `override_direction` and `bound_value`, and
--    esign.config_set REFUSES rather than silently clamping. In particular
--    esign.outsider.verification.default_factor.hr_anonymous_report is locked at every level,
--    because a verification factor there would end anonymity (§5.6 G).
--
-- 4. THE Ed25519 PRIVATE KEY LIVES IN A `restricted` TABLE AND IS DECLARED A CLIENT-EXCLUDED
--    COLUMN, which is the platform's own mechanism — the ai.endpoint / ai.api precedent for
--    credential-bearing tables is exactly this variant with no bespoke column grants layered on
--    top. The key is generated by pgsodium (crypto_sign_new_keypair) and is never returned by any
--    RPC; the PUBLIC key is returned by esign_certificate_public_keys(), which is what "public keys
--    published at a stable URL" (§2.6) resolves to at the data layer. Rotation is supported and old
--    keys are never deleted, so old certificates stay verifiable forever.
-- ===================================================================================

