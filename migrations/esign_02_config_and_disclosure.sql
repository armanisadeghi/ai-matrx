-- ---------------------------------------------------------------------------------
-- 4. Resolution — nearest wins (§7).
-- ---------------------------------------------------------------------------------
create or replace function esign.config_resolve(p_organization_id uuid, p_key text)
returns jsonb
language plpgsql stable security definer set search_path to 'esign','public' as $fn$
declare d esign.config_definition%rowtype; v jsonb;
begin
  select * into d from esign.config_definition
   where config_key = p_key and deleted_at is null limit 1;
  if not found then
    raise exception 'esign.config_resolve: % is not a registered configuration key', p_key
      using errcode = '22023',
            hint = 'No value in this register is a constant in code. Register the key before reading it.';
  end if;
  if d.override_direction = 'locked' or 'org' <> all(d.overridable_by) then
    return d.default_value;
  end if;
  select value into v from esign.config_value
   where organization_id = p_organization_id and config_key = p_key and deleted_at is null limit 1;
  return coalesce(v, d.default_value);
end $fn$;

create or replace function esign.config_set(p_organization_id uuid, p_key text, p_value jsonb, p_reason text default null)
returns jsonb
language plpgsql security definer set search_path to 'esign','public' as $fn$
declare d esign.config_definition%rowtype; v_other jsonb;
begin
  select * into d from esign.config_definition where config_key = p_key and deleted_at is null limit 1;
  if not found then
    return jsonb_build_object('granted', false, 'reason', 'unregistered_key', 'config_key', p_key);
  end if;
  if d.override_direction = 'locked' or 'org' <> all(d.overridable_by) then
    return jsonb_build_object('granted', false, 'reason', 'not_overridable', 'config_key', p_key,
                              'detail', coalesce(d.notes, 'platform only'));
  end if;
  if d.value_type = 'integer' then
    if d.override_direction = 'lower_only' and (p_value)::numeric > (d.default_value)::numeric then
      return jsonb_build_object('granted', false, 'reason', 'raise_not_permitted', 'config_key', p_key,
                                'ceiling', d.default_value);
    end if;
    if d.override_direction = 'raise_only' and (p_value)::numeric < (d.default_value)::numeric then
      return jsonb_build_object('granted', false, 'reason', 'lower_not_permitted', 'config_key', p_key,
                                'floor', coalesce(d.bound_value, d.default_value));
    end if;
    if d.bound_value is not null and (p_value)::numeric < (d.bound_value)::numeric then
      return jsonb_build_object('granted', false, 'reason', 'below_statutory_floor', 'config_key', p_key,
                                'floor', d.bound_value);
    end if;
  end if;
  if d.override_direction = 'raise_only' and d.value_type = 'enum' and p_value = '"none"'::jsonb then
    return jsonb_build_object('granted', false, 'reason', 'lower_not_permitted', 'config_key', p_key);
  end if;
  -- §7: at least one signature kind must remain true.
  if p_key in ('esign.signature.allow_typed','esign.signature.allow_drawn') and p_value = 'false'::jsonb then
    v_other := esign.config_resolve(p_organization_id,
      case when p_key = 'esign.signature.allow_typed' then 'esign.signature.allow_drawn'
           else 'esign.signature.allow_typed' end);
    if v_other = 'false'::jsonb then
      return jsonb_build_object('granted', false, 'reason', 'last_signature_kind', 'config_key', p_key,
                                'detail', 'at least one of typed/drawn must remain true');
    end if;
  end if;

  insert into esign.config_value (organization_id, config_key, value, set_reason)
  values (p_organization_id, p_key, p_value, p_reason)
  on conflict (organization_id, config_key) where deleted_at is null
  do update set value = excluded.value, set_reason = excluded.set_reason;
  return jsonb_build_object('granted', true, 'config_key', p_key, 'value', p_value);
end $fn$;

-- The resolved bundle an envelope FREEZES at send (§2.2 config_snapshot / AD-11).
create or replace function esign.resolve_config_snapshot(p_organization_id uuid, p_sensitivity text)
returns jsonb
language plpgsql stable security definer set search_path to 'esign','public' as $fn$
declare v_factor jsonb; v_disc uuid;
begin
  v_factor := esign.config_resolve(p_organization_id, 'esign.outsider.verification.default_factor.esign_signer');
  -- §5.6 A: email_code is FORCED when the envelope is sensitive; the `none` escape exists only for
  -- standard envelopes, and the certificate records which factor actually applied.
  if p_sensitivity = 'sensitive' then v_factor := '"email_code"'::jsonb; end if;

  select id into v_disc from esign.consent_disclosure
   where deleted_at is null and is_current
     and (organization_id = p_organization_id or is_platform_default)
   order by (organization_id = p_organization_id) desc, effective_from desc limit 1;

  return jsonb_build_object(
    'resolved_at', now(),
    'expiry_days', esign.config_resolve(p_organization_id,
        case when p_sensitivity = 'sensitive' then 'esign.expiry_days.sensitive' else 'esign.expiry_days.standard' end),
    'reminder_cadence_days', esign.config_resolve(p_organization_id, 'esign.reminder.cadence_days'),
    'reminder_max_count',    esign.config_resolve(p_organization_id, 'esign.reminder.max_count'),
    'reminder_quiet_hours',  esign.config_resolve(p_organization_id, 'esign.reminder.quiet_hours'),
    'verification_factor',   v_factor,
    'consent_disclosure_id', to_jsonb(v_disc),
    'require_preview',       esign.config_resolve(p_organization_id, 'esign.consent.require_preview'),
    'hash_algorithm',        esign.config_resolve(p_organization_id, 'esign.hash.algorithm'),
    'allow_typed',           esign.config_resolve(p_organization_id, 'esign.signature.allow_typed'),
    'allow_drawn',           esign.config_resolve(p_organization_id, 'esign.signature.allow_drawn'),
    'delegation_allowed',    esign.config_resolve(p_organization_id, 'esign.delegation.allowed'),
    'download_url_ttl_seconds', esign.config_resolve(p_organization_id, 'esign.download.url_ttl_seconds'),
    'session_ttl_minutes',   esign.config_resolve(p_organization_id, 'esign.outsider.session.ttl_minutes.esign_signer'),
    'retention_trigger',     esign.config_resolve(p_organization_id, 'esign.retention.default_trigger'),
    'certificate_key_id',    to_jsonb((select key_id from esign.signing_key where is_current limit 1)),
    'branding', (select jsonb_build_object('organization_id', o.id, 'name', o.name, 'logo_url', o.logo_url)
                   from iam.organizations o where o.id = p_organization_id));
end $fn$;

