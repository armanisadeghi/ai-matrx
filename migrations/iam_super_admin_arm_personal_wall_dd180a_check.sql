-- ══════════════════════════ THE FORCING TEST — RED THEN GREEN, ON THIS DATABASE ══════════════════
-- A scratch entity table built by the canonical builder (`platform._ddl_guard` refuses any other
-- way, and is right to), given the PRE-DD-170 unwalled arm verbatim as a hand-written policy, then
-- regenerated by the real `iam.apply_rls`. Both halves raise; a forcing test that prints is a wish.
do $dd180ft$
declare
  v_schema text := 'zz_dd180_forcing_' || to_hex((extract(epoch from clock_timestamp())*1000)::bigint);
  v_token  text;
  v_st text; v_det text;
begin
  v_token := v_schema || '_token';
  execute format('create schema %I', v_schema);
  perform platform.create_entity_table(
    v_schema, 'probe', v_token, 'DD-180 forcing probe',
    array['note text'], 'entity', false, false, 'internal', false, false, false, false,
    null::text[], 'organization'::platform.data_class, 'organization'::platform.list_scope);
  update platform.entity_types
     set data_class_reason = 'DD-180 forcing test; this row and its schema are dropped before this migration commits'
   where token = v_token;

  -- The table the generator just built must already PASS, or the check is failing something else.
  select status, detail into v_st, v_det from iam.verify_canonical(v_schema, 'probe', v_token, 'entity')
   where check_name = 'super_admin_system_org_arm_walled';
  if v_st is distinct from 'PASS' then
    raise exception 'DD-180 forcing test: the check says % on a table the CURRENT generator just built. Either the generator does not emit the wall (this file''s premise is wrong) or the check does not recognise it. Detail: %', coalesce(v_st,'<no row>'), coalesce(v_det,'');
  end if;
  raise notice 'DD-180 CHECK baseline — a freshly generated entity table PASSes super_admin_system_org_arm_walled.';

  -- ── RED: the arm exactly as every one of the 167 live policies carries it today ──────────────
  execute format('drop policy std_select on %I.probe', v_schema);
  execute format(
    'create policy std_select on %I.probe for select to authenticated using ('
    || 'created_by = (select auth.uid()) or visibility = ''public'' or '
    || '((organization_id is not null) and (select public.is_super_admin()) and (organization_id in '
    || '(select so.organization_id from iam.system_orgs so where so.global_readable))))', v_schema);
  select status, detail into v_st, v_det from iam.verify_canonical(v_schema, 'probe', v_token, 'entity')
   where check_name = 'super_admin_system_org_arm_walled';
  if v_st is distinct from 'FAIL' then
    raise exception 'DD-180 forcing test: super_admin_system_org_arm_walled returned % on a std_select carrying the UNWALLED §6e super-admin arm verbatim. A check that cannot fail is decoration. Detail: %', coalesce(v_st,'<no row>'), coalesce(v_det,'');
  end if;
  raise notice 'DD-180 CHECK RED   — %', v_det;

  -- ── the same arm WITH the wall: the check must not fire on it ───────────────────────────────
  execute format('drop policy std_select on %I.probe', v_schema);
  execute format(
    'create policy std_select on %I.probe for select to authenticated using ('
    || 'created_by = (select auth.uid()) or visibility = ''public'' or '
    || '((organization_id is not null) and (visibility >= ''internal''::platform.visibility) and '
    || '(select public.is_super_admin()) and (organization_id in '
    || '(select so.organization_id from iam.system_orgs so where so.global_readable))))', v_schema);
  select status, detail into v_st, v_det from iam.verify_canonical(v_schema, 'probe', v_token, 'entity')
   where check_name = 'super_admin_system_org_arm_walled';
  if v_st is distinct from 'PASS' then
    raise exception 'DD-180 forcing test: the check says % on the SAME arm carrying the wall. It is matching something other than the wall, and it would refuse the fix it exists to demand. Detail: %', coalesce(v_st,'<no row>'), coalesce(v_det,'');
  end if;
  raise notice 'DD-180 CHECK walled-form — the same arm with `visibility >= ''internal''` PASSes.';

  -- ── GREEN: the real generator, the one path the 167 will be swept through ───────────────────
  execute format('drop policy std_select on %I.probe', v_schema);
  execute format(
    'create policy std_select on %I.probe for select to authenticated using ('
    || 'created_by = (select auth.uid()) or '
    || '((organization_id is not null) and (select public.is_super_admin()) and (organization_id in '
    || '(select so.organization_id from iam.system_orgs so where so.global_readable))))', v_schema);
  perform iam.apply_rls(v_schema, 'probe', v_token, 'entity');
  select status, detail into v_st, v_det from iam.verify_canonical(v_schema, 'probe', v_token, 'entity')
   where check_name = 'super_admin_system_org_arm_walled';
  if v_st is distinct from 'PASS' then
    raise exception 'DD-180 forcing test: GREEN FAILED — after iam.apply_rls the check still says %. The sweep in part 2 cannot work. Detail: %', coalesce(v_st,'<no row>'), coalesce(v_det,'');
  end if;
  raise notice 'DD-180 CHECK GREEN — iam.apply_rls removes the unwalled arm and the check PASSes.';

  -- ── teardown, verified ─────────────────────────────────────────────────────────────────────
  delete from iam.superseded_policy where schema_name = v_schema;
  delete from platform.entity_types where token = v_token;
  execute format('drop schema %I cascade', v_schema);
  if to_regclass(format('%I.probe', v_schema)) is not null
     or exists (select 1 from platform.entity_types where token = v_token) then
    raise exception 'DD-180 forcing test: the teardown left something behind (schema %, token %).', v_schema, v_token;
  end if;
  raise notice 'DD-180 — forcing test torn down: schema % and token % are gone.', v_schema, v_token;
end
