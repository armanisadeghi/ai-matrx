-- based-on: public.delete_context_item(uuid) 67a197ffab9d2c617a2db3b94418f91cdb3d694ca255dded1978a7d237b36255
-- `delete_context_item` REMOVES the row instead of only switching it off.
--
-- THE CLASS BEHIND F6 (2026-09-21). F6 was a scope type that stayed on the
-- scopes page after it was deleted; its cause had two halves — a list read with
-- no `deleted_at` filter, and a delete RPC that wrote a DIFFERENT column than
-- the one deletion means. This file closes the second half where it repeats:
-- `public.delete_context_item` flipped `is_active` to false and left
-- `deleted_at` NULL, so a "deleted" context item was a LIVE row that happened
-- to be switched off. `is_active` is the person's own on/off switch for a field
-- — switching a field off and removing it are two different acts, and one
-- column cannot mean both.
--
-- Both are now written: `deleted_at` says the row is gone (every reader and the
-- platform soft-delete cascade agree on that column), and `is_active` stays
-- false so any reader that has only ever asked that question — including
-- readers outside this repository — keeps the answer it had.
--
-- based-on is generated by `pnpm db:based-on`.

create or replace function public.delete_context_item(p_item_id uuid)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_org uuid;
  v_result jsonb;
begin
  select st.organization_id
    into v_org
    from context.context_items ci
    join context.scope_types st on st.id = ci.scope_type_id
   where ci.id = p_item_id
     and ci.deleted_at is null;

  if v_org is null then
    raise exception 'active context item % not found', p_item_id
      using errcode = 'P0002';
  end if;

  if (auth.role() = 'service_role' or iam.has_org_admin(v_org)) is not true then
    raise exception 'organization admin required for %', v_org
      using errcode = '42501';
  end if;

  update context.context_items
     set deleted_at = now(),
         is_active = false,
         updated_at = now()
   where id = p_item_id
  returning jsonb_build_object('id', id, 'deleted_at', deleted_at) into v_result;

  return v_result;
end;
$function$;
