## Renderer rules that prevent broken timelines

These are the failure modes the real renderer and its bridge actually enforce —
follow them exactly:

1. The timeline renders once the object is COMPLETE (a loading animation shows
   while it streams). Never emit a partial or placeholder timeline "to fill
   in later" — emit the whole plan in one object.
2. A period with zero renderable events is dropped entirely. Never emit an
   empty `events` array as a stub for a future phase.
3. An event without a non-empty `title` string is dropped silently.
4. `status` must be exactly `completed`, `in-progress`, or `pending`. The
   spaced spelling `"in progress"` is tolerated and normalized, but anything
   else (`"done"`, `"todo"`, `"blocked"`) is ignored and the event falls back
   to the neutral icon. Omit `status` entirely for plain future events.
5. `category` strings group by EXACT match — `"Engineering"` and
   `"engineering"` become two separate filter options. Reuse identical
   strings, and keep the set small (2-6 categories) or skip categories
   entirely for simple timelines.
6. Period collapse behavior: every period starts collapsed EXCEPT the one
   named `"Phase 1 ..."` (or the first period when none matches). Naming
   phases `"Phase 1: ..."`, `"Phase 2: ..."` gives users the guided
   one-phase-at-a-time reveal.
7. The schema is strict: only the fields listed above are part of the
   contract. Do not invent extra keys.

## Sizing guidance

- A focused timeline is 2-6 periods with 2-8 events each. Above ~40 total
  events, split distinct workstreams into separate timelines, each its own
  `timeline` object with a sentence between them.
- Keep `date` values consistent within one timeline (all week-based, all
  quarter-based, or all calendar dates) — they are display text, so mixed
  granularity reads as sloppy.
- Use `status` only when the user's plan is genuinely in flight; a
  forward-looking roadmap where everything is `pending` reads cleaner with no
  statuses at all.

## Editing an existing timeline

When asked to modify a timeline (yours or one provided as context):

- Return ONE complete `timeline` JSON object containing the FULL updated plan
  — never a single period, a fragment, or prose mixed with partial JSON.
- Keep the root `__kind: "timeline"` and every period's/event's `__kind`.
- PRESERVE existing event `id` values on events you keep — completion
  tracking is keyed on them. New events may omit `id`.
- Keep periods and events you were not asked to change; keep the `title`
  unless asked to rename.
- To add events, insert them in chronological position; to remove, omit them
  — do not leave emptied-out stubs in place.

