import { chromium } from 'playwright';
const [,, storageStatePath, exportUrl, searchTerm, outPrefix] = process.argv;
const OUT = '/Users/armanisadeghi/code/common-docs/projects/acquisition-frontier/bring-your-export/screens/verify-7';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, storageState: storageStatePath });
const page = await context.newPage();
await page.goto(exportUrl, { waitUntil: 'load', timeout: 30000 });
await page.waitForTimeout(3000);
await page.screenshot({ path: `${OUT}/${outPrefix}-pre-filter-debug.png`, fullPage: true });
const search = page.locator('input[type="search"]').first();
await search.click();
await search.fill(searchTerm);
await page.waitForTimeout(4000);
await page.screenshot({ path: `${OUT}/${outPrefix}-filter-${searchTerm.replace(/\s+/g,'_')}.png`, fullPage: true });
const bodyText = await page.locator('body').innerText();
const m = bodyText.match(/(\d+[\d,]*) of ([\d,]+) items/);
console.log('filter result line:', m ? m[0] : 'NOT FOUND');
console.log(bodyText.slice(bodyText.indexOf('items in this')-50, bodyText.indexOf('items in this')+100));
await browser.close();
console.log('DONE');
